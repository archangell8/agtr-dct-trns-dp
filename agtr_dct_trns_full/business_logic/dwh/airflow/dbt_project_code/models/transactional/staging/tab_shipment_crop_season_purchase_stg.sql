WITH

CROP_REDIRECT AS (

    SELECT
        CROP_UNIQUE_KEY,
        CROP_BUSINESS_KEY,
        LOCATION_CODE,
        MAX(PORT_LOCATION) AS PORT_LOCATION,
        SUM(INVOICE_VOLUME_FIRST) AS INVOICE_VOLUME_FIRST,
        SUM(INVOICE_VOLUME_SEC) AS INVOICE_VOLUME_SEC,
        NVL(SUM(INVOICE_VOLUME_FIRST), 0) - SUM(INVOICE_VOLUME_SEC) AS TARGET_DIFF_INVOICE,
        MAX(CROP_SEASON_BEG_DT) AS CROP_SEASON_BEG_DT,
        MAX(CROP_SEASON_END_DT) AS CROP_SEASON_END_DT
    FROM {{ ref('tab_shipment_crop_season_control_stg') }} AS S
    WHERE CROP_SEASON_BEG_DT >= '2024-01-06 00:00:00.000'
    GROUP BY 1, 2, 3
    HAVING COALESCE(SUM(INVOICE_VOLUME_FIRST), 0) - SUM(INVOICE_VOLUME_SEC) < 0

),

PURCHASE AS (

    SELECT -- noqa
        C.CROP_UNIQUE_KEY,
        CONCAT(F.PRODUCT_CODE, '-', L.LOCATIONID) AS CROP_BUSINESS_KEY,
        F.PRODUCT_CODE,
        L.LOCATIONID,
        F.PURCHASE_CODE::STRING AS PURCHASE_CODE,
        F.FINALDESTINATION,
        C.PORT_LOCATION,
        F.INVOICE_ISSUANCE_DATE,
        F.INVOICE_VOLUME,
        C.TARGET_DIFF_INVOICE
    --C.CROP_SEASON_BEGIN_ID
    FROM {{ ref('tab_shipment_fichas_jde_stg') }} AS F
    INNER JOIN {{ ref('tab_location_internal_stg') }} AS L
        ON F.BRANCH_PLANT_DESTINATION = L.LOCATIONID
    INNER JOIN CROP_REDIRECT AS C
        ON
            C.CROP_BUSINESS_KEY = CONCAT(F.PRODUCT_CODE, '-', L.LOCATIONID)
            AND C.LOCATION_CODE <> L.LOCATION_CODE
            AND F.INVOICE_ISSUANCE_DATE >= CROP_SEASON_BEG_DT
            AND F.INVOICE_ISSUANCE_DATE <= DATEADD(DAY, -7, CROP_SEASON_END_DT)
    WHERE
        OPERATION_TYPE IN ('CIF', 'FOB')
        AND PURCHASE_STATUS_CODE <> '980-999'
        --AND L.LOCATION_CODE <> 'SFS' --ÇPCATION_CODE
        AND L.LOCATION_UNIT_STRUCTURE IN ('TRANSBORDO', 'PORTO FLUVIAL')
        AND APPLIED_VOLUME <> 0
        AND LOAD_NUMBER IS NULL
        --AND L.LOCATIONID ='0217103018'  --TRANSSHIP TRANSBORDO
        --AND F.PRODUCT_CODE='00001' -- PRODUTO
        --- F.INVOICE_ISSUANCE_DATE < QUE DATA FIM -7

),

PURCHASE_ALL AS (
    SELECT
        *, -- noqa
        --ROW_NUMBER() OVER (PARTITION BY CROP_UNIQUE_KEY ORDER BY INVOICE_VOLUME) AS RK_INVOICE -- noqa
        ROW_NUMBER() OVER (PARTITION BY CROP_UNIQUE_KEY ORDER BY PURCHASE_CODE DESC, INVOICE_VOLUME) AS RK_INVOICE
        --Ordenacao de prioridade para chegar no valor do campo TARGET_DIFF_INVOICE
    FROM PURCHASE
),

GET_TARGET_INVOICE AS (
    SELECT
        P_ALL.CROP_UNIQUE_KEY,
        MAJ.RK_INVOICE,
        P_ALL.TARGET_DIFF_INVOICE * -1 AS TARGET_DIFF_INVOICE,
        SUM(P_ALL.INVOICE_VOLUME) AS INVOICE_VOLUME
    FROM PURCHASE_ALL AS P_ALL
    INNER JOIN PURCHASE_ALL AS MAJ
        ON
            P_ALL.CROP_UNIQUE_KEY = MAJ.CROP_UNIQUE_KEY
            AND P_ALL.RK_INVOICE <= MAJ.RK_INVOICE
    GROUP BY 1, 2, 3
    --ORDER BY 1,2
),

GET_TARGET_INVOICE_2 AS (
    SELECT *, -- noqa
    IFF((INVOICE_VOLUME - TARGET_DIFF_INVOICE) >= 0, RK_INVOICE,NULL) AS RK_INVOICE_TO_GET -- noqa
    FROM GET_TARGET_INVOICE
),

GET_TARGET_INVOICE_3 AS (
    SELECT
        CROP_UNIQUE_KEY,
        MIN(RK_INVOICE_TO_GET) AS RK_INVOICE_TO_GET
    FROM GET_TARGET_INVOICE_2
    GROUP BY 1
)

SELECT P_ALL.*
FROM PURCHASE_ALL AS P_ALL
INNER JOIN GET_TARGET_INVOICE_3 AS GET_INV
    ON
        P_ALL.CROP_UNIQUE_KEY = GET_INV.CROP_UNIQUE_KEY
        AND P_ALL.RK_INVOICE <= GET_INV.RK_INVOICE_TO_GET
