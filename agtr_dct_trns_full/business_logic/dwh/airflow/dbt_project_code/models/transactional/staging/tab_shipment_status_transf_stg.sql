WITH
RDS_HISTORIC_DCT AS (
    SELECT
        LOTID,
        LOADE1,
        IDOPERACAOFINALIDADE,
        MAX(DATAHORASAIDA) AS DATAHORASAIDA
    FROM {{ source('rds', 'VW_RDS_HISTORIC_DCT') }}
    GROUP BY
        LOTID,
        LOADE1,
        IDOPERACAOFINALIDADE
),

SHIPMENT_STATUS_TRF AS (
    SELECT DISTINCT
        ID,
        ITEMID,
        DOCNUMBER AS BK_TRF,
        BK AS SHIP_BK
    FROM {{ ref('tab_shipment_details_transf_stg') }}
),

SHIPMENT_STATUS_CTMS AS (
    SELECT -- noqa
        CTMS.BK_TRF,
        CTMS.COD_ITEM AS ITEMID,
        'KG' AS UOM,
        CTMS.DATA_PREV_COLETA,
        CTMS.DATA_EMISSAO_OC,
        CTMS.DATA_NF,
        CTMS.DATA_VALIDACAO_QRCODE,
        CTMS.DATA_ENTREGA,
        UPPER(TRIM(CTMS.STATUS_OC)) AS STATUS_OC,
        MAX(CTMS.QUANTIDADE) AS QUANTIDADE
    FROM {{ ref('tab_shipment_ctms_oc_stg') }} AS CTMS
    INNER JOIN {{ ref('item_master') }} AS I ON CTMS.COD_ITEM = I.ITEM
    WHERE
        COALESCE(CTMS.LOAD, '') != ''
        AND (CTMS.TIPO_OPERACAO = 'TRF')
    GROUP BY
        CTMS.BK_TRF,
        CTMS.COD_ITEM,
        CTMS.DATA_PREV_COLETA,
        CTMS.DATA_EMISSAO_OC,
        CTMS.DATA_NF,
        CTMS.DATA_VALIDACAO_QRCODE,
        CTMS.DATA_ENTREGA,
        CTMS.STATUS_OC
),

SHIPMENT_STATUS_LOAD AS (
    SELECT -- noqa
        CONCAT(
            LJ.LOAD, '-N/A-TRF'
        ) AS BK_TRF,
        CONCAT(
            LJ.LOAD, '-', COALESCE(LJ.ID_PEDIDO, 'N/A'), '-TRF'
        ) AS SHIP_BK,
        LJ.CODIGO_PRODUTO AS ITEMID,
        LJ.U_M_PRODUTO AS UOM,
        LJ.LOTID,
        UPPER(TRIM(LJ.STATUS_LOAD)) AS STATUS_LOAD,
        CASE
            WHEN DAY(LJ.DATA_EMISSAO_NF) = 1
                THEN LJ.DATA_EMISSAO_NF
            WHEN RDS.DATAHORASAIDA::TIME < TO_TIME(LOC_GROUP.HR_BEGIN_ONHANDS, 'HH24:MI') --noqa
                THEN DATEADD(DAY, -1, LJ.DATA_EMISSAO_NF)
            ELSE LJ.DATA_EMISSAO_NF
        END AS DATA_EMISSAO_NF,
        -- LJ.DATA_EMISSAO_NF,
        LJ.DT_RECEPCAO_JDE,
        LJ.DATA_CONFIRMACAO_CARREGAMENTO,
        LJ.DATA_PROGRAMADA_CARREGAMENTO,
        LJ.SINISTRO,
        MAX(
            CASE
                WHEN LJ.NF_STATUS IN ('994', '998') THEN 0
                ELSE LJ.VOLUME_TRANSPORTADO
            END
        ) AS VOLUME_TRANSPORTADO,
        MAX(
            CASE
                WHEN LJ.NF_STATUS IN ('994', '998') THEN 0
                ELSE LJ.VOL_BALANCA
            END
        ) AS VOL_BALANCA,
        MAX(
            CASE
                WHEN LJ.NF_STATUS IN ('994', '998') THEN 0
                ELSE LJ.VOL_NF
            END
        ) AS VOL_NF
    FROM {{ ref('tab_shipment_load_intransit_stg') }} AS LJ
    INNER JOIN {{ ref('item_master') }} AS I
        ON LJ.CODIGO_PRODUTO = I.ITEM
    LEFT JOIN {{ ref('tab_shipment_ficha_intransit_stg') }} AS FC
        ON LJ.LOAD = FC.LOAD_NUMBER
    LEFT JOIN RDS_HISTORIC_DCT AS RDS
        ON
            RDS.LOADE1::STRING = LJ.LOAD::STRING
            AND UPPER(RDS.IDOPERACAOFINALIDADE) = 'EXPEDICAO'
    INNER JOIN {{ ref('tab_location_internal_stg') }} AS LOC
        ON LJ.BP_ORIGEM = LOC.LOCATIONID
    LEFT JOIN {{ source('pscfl', 'F_MIN_LOCATION_AGRUPADA') }} AS LOC_GROUP
        ON LOC_GROUP.UNIT_ID = LOC.LOCATION_UNIT_ID
    WHERE
        LJ.TIPO_DE_OPERACAO = 'TRF' -- noqa
        AND COALESCE(LJ.LOAD, '') != ''
    GROUP BY
        LJ.LOAD,
        LJ.ID_PEDIDO,
        LJ.CODIGO_PRODUTO,
        LJ.U_M_PRODUTO,
        LJ.LOTID,
        LJ.STATUS_LOAD,
        LJ.SINISTRO,
        CASE
            WHEN DAY(LJ.DATA_EMISSAO_NF) = 1
                THEN LJ.DATA_EMISSAO_NF
            WHEN RDS.DATAHORASAIDA::TIME < TO_TIME(LOC_GROUP.HR_BEGIN_ONHANDS, 'HH24:MI') --noqa
                THEN DATEADD(DAY, -1, LJ.DATA_EMISSAO_NF)
            ELSE LJ.DATA_EMISSAO_NF
        END,
        LJ.DT_RECEPCAO_JDE,
        LJ.DATA_CONFIRMACAO_CARREGAMENTO,
        LJ.DATA_PROGRAMADA_CARREGAMENTO
),

SHIPMENT_STATUS_RDS AS (
    SELECT DISTINCT
        RDS.LOTID,
        RDS.LOADE1,
        RDS.FICHAJDE,
        RDS.IDOPERACAOFINALIDADE,
        RDS.CODIGOLONGOPRODUTO,
        RDS.QUANTIDADEPRODUTO,
        RDS.PESOSECORATEIO,
        RDS.PESOESTIMADO,
        RDS.DATAHORACHEGADA,
        RDS.DATAHORASAIDA,
        RDS.DATAHORASEGUNDAPESAGEM,
        RDS.UNIDADEMEDIDA
    FROM {{ source('rds', 'VW_RDS_HISTORIC_DCT') }} AS RDS
    INNER JOIN {{ ref('item_master') }} AS I ON RDS.CODIGOLONGOPRODUTO = I.ITEM
),

ALL_STATUS_DATA_PART1 AS (
    SELECT -- noqa
        S.ID AS SHIPMENTID,
        S.SHIP_BK,
        COALESCE(C.ITEMID, S.ITEMID) AS ITEMID,
        C.UOM AS UOM_CTMS,
        C.DATA_EMISSAO_OC AS DT_EMISSAO_OC,
        C.DATA_PREV_COLETA AS DT_PREV_COLETA,
        C.DATA_NF AS DT_NF,
        C.DATA_VALIDACAO_QRCODE AS DT_QRCODE,
        C.DATA_ENTREGA AS DT_ENTREGA,
        C.STATUS_OC AS STATUS_CTMS,
        C.QUANTIDADE AS QUANTIDADE_CTMS
    FROM SHIPMENT_STATUS_TRF AS S
    LEFT JOIN SHIPMENT_STATUS_CTMS AS C ON S.BK_TRF = C.BK_TRF
),

ALL_STATUS_DATA_FINAL AS (
    SELECT -- noqa
        S.SHIPMENTID,
        COALESCE(C.ITEMID, S.ITEMID) AS ITEMID,
        S.SHIP_BK,
        S.DT_EMISSAO_OC,
        S.DT_PREV_COLETA,
        S.DT_NF,
        S.DT_QRCODE,
        S.DT_ENTREGA,
        S.STATUS_CTMS,
        S.QUANTIDADE_CTMS,
        S.UOM_CTMS,
        C.UOM AS UOM_LOAD,
        C.LOTID AS LOTID_LOAD,
        C.STATUS_LOAD,
        C.DT_RECEPCAO_JDE,
        C.DATA_EMISSAO_NF AS DT_EMISSAO_NF_LOAD,
        C.DATA_CONFIRMACAO_CARREGAMENTO AS DT_CONFIRMACAO_LOAD,
        C.DATA_PROGRAMADA_CARREGAMENTO AS DT_PROGRAMADA_LOAD,
        C.VOLUME_TRANSPORTADO AS VL_TRANSPORTADO_LOAD,
        C.VOL_NF AS VL_NF_LOAD,
        C.VOL_BALANCA AS VL_BALANCA_LOAD,
        C.SINISTRO
    FROM ALL_STATUS_DATA_PART1 AS S
    LEFT JOIN SHIPMENT_STATUS_LOAD AS C
        ON
            S.SHIP_BK = C.SHIP_BK
            AND S.ITEMID = C.ITEMID
),

/* QUERIES PARA CADA STATUS DO SHIPMENT */
SHIPMENT_STATUS_CANCELLED AS (
    /* ATUALIZA SHIPMENTS BASEADOS NOS STATUS CANCELADO */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'CANCELLED' AS "STATUS",
        COALESCE(
            ALL_DATA.DT_PREV_COLETA,
            ALL_DATA.DT_PROGRAMADA_LOAD
        ) AS REFERENCEDATE,
    COALESCE(ALL_DATA.UOM_LOAD, ALL_DATA.UOM_CTMS) AS UOM, -- noqa
    COALESCE(ALL_DATA.VL_NF_LOAD, ALL_DATA.QUANTIDADE_CTMS) AS QUANTITY -- noqa
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (ALL_DATA.DT_EMISSAO_OC IS NOT NULL OR ALL_DATA.DT_PROGRAMADA_LOAD IS NOT NULL)  -- noqa
        AND (
            ALL_DATA.STATUS_CTMS = 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD = 'LOAD CANCELADO'
            OR ALL_DATA.SINISTRO = 'TRUE')  -- noqa
),

SHIPMENT_STATUS_SINISTRO AS (
    /* ATUALIZA SHIPMENTS BASEADOS NOS STATUS CANCELADO */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'SINISTRO' AS "STATUS",
        COALESCE(
            ALL_DATA.DT_PREV_COLETA,
            ALL_DATA.DT_PROGRAMADA_LOAD
        ) AS REFERENCEDATE,
    COALESCE(ALL_DATA.UOM_LOAD, ALL_DATA.UOM_CTMS) AS UOM, -- noqa
    COALESCE(ALL_DATA.VL_NF_LOAD, ALL_DATA.QUANTIDADE_CTMS) AS QUANTITY -- noqa
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (ALL_DATA.DT_EMISSAO_OC IS NOT NULL OR ALL_DATA.DT_PROGRAMADA_LOAD IS NOT NULL)  -- noqa
        AND (ALL_DATA.SINISTRO = 'TRUE')  -- noqa
),

SHIPMENT_STATUS_LOADING_ORDER AS (
    /*
        ATUALIZA SHIPMENTS BASEADOS NO STATUS DIFERENTE DE CANCELADO
        SE FOI FINALIZADO... FOI PLANEJADO, EM TESE
    */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'LOADING ORDER' AS "STATUS",
        CASE
            WHEN IT.L2 = 'GRAOS'
                THEN ALL_DATA.DT_PREV_COLETA
            ELSE
                COALESCE(
                    ALL_DATA.DT_PROGRAMADA_LOAD,
                    ALL_DATA.DT_PREV_COLETA
                )
        END AS REFERENCEDATE,
        ALL_DATA.UOM_CTMS AS UOM,
        ALL_DATA.QUANTIDADE_CTMS AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    INNER JOIN {{ ref('item_master') }} AS IT
        ON IT.ITEM = ALL_DATA.ITEMID
    WHERE
        (
            ALL_DATA.DT_PREV_COLETA IS NOT NULL
            OR ALL_DATA.DT_PROGRAMADA_LOAD IS NOT NULL
        )
        AND COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
),

SHIPMENT_STATUS_INVOICE AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA EMISSAO DA NOTA FISCAL */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'INVOICE' AS "STATUS",
        COALESCE(
            ALL_DATA.DT_EMISSAO_NF_LOAD,
            ALL_DATA.DT_NF
        ) AS REFERENCEDATE,
        COALESCE(
            ALL_DATA.UOM_LOAD,
            ALL_DATA.UOM_CTMS
        ) AS UOM,
        COALESCE(
            ALL_DATA.VL_NF_LOAD,
            ALL_DATA.QUANTIDADE_CTMS
        ) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (ALL_DATA.DT_EMISSAO_NF_LOAD IS NOT NULL OR ALL_DATA.DT_NF IS NOT NULL)
        AND (
            COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD != 'LOAD CANCELADO')  -- noqa
),

SHIPMENT_STATUS_IN_SOURCE AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA DE VALIDACAO DO QRCODE */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'IN SOURCE' AS "STATUS",
        ALL_DATA.DT_QRCODE AS REFERENCEDATE,
        ALL_DATA.UOM_CTMS AS UOM,
        ALL_DATA.QUANTIDADE_CTMS AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (ALL_DATA.DT_QRCODE IS NOT NULL)
        AND (
            COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD != 'LOAD CANCELADO')  -- noqa
),

SHIPMENT_STATUS_IN_DESTINATION AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA DE CHEGADA NA LOCALIDADE */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'IN DESTINATION' AS "STATUS",
        RDS.DATAHORACHEGADA AS REFERENCEDATE,
        RDS.UNIDADEMEDIDA,
        SUM(RDS.QUANTIDADEPRODUTO) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    INNER JOIN SHIPMENT_STATUS_RDS AS RDS
        ON ALL_DATA.LOTID_LOAD = RDS.LOTID
    WHERE
        RDS.DATAHORACHEGADA IS NOT NULL
        AND (
            COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD != 'LOAD CANCELADO')  -- noqa
    GROUP BY
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        RDS.DATAHORACHEGADA,
        RDS.UNIDADEMEDIDA
),

SHIPMENT_STATUS_UNLOADED AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA DA SAIDA DA LOCALIDADE */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'UNLOADED' AS "STATUS",
        COALESCE(
            RDS.DATAHORASAIDA, RDS.DATAHORASEGUNDAPESAGEM
        ) AS REFERENCEDATE,
        RDS.UNIDADEMEDIDA,
        SUM(RDS.QUANTIDADEPRODUTO) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    INNER JOIN SHIPMENT_STATUS_RDS AS RDS
        ON ALL_DATA.LOTID_LOAD = RDS.LOTID
    WHERE
        (RDS.DATAHORASAIDA IS NOT NULL OR RDS.DATAHORASEGUNDAPESAGEM IS NOT NULL)  -- noqa
        AND (
            COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD != 'LOAD CANCELADO')  -- noqa
    GROUP BY
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        COALESCE(RDS.DATAHORASAIDA, RDS.DATAHORASEGUNDAPESAGEM),
        RDS.UNIDADEMEDIDA
),

SHIPMENT_STATUS_FINISHED AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA APLICACAO DA FICHA / LOAD */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'FINISHED' AS "STATUS",
        COALESCE(
            ALL_DATA.DT_RECEPCAO_JDE,
            ALL_DATA.DT_ENTREGA
        ) AS REFERENCEDATE,
        COALESCE(
            ALL_DATA.UOM_LOAD,
            ALL_DATA.UOM_CTMS
        ) AS UOM,
        ALL_DATA.VL_BALANCA_LOAD AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (ALL_DATA.DT_ENTREGA IS NOT NULL OR ALL_DATA.DT_RECEPCAO_JDE IS NOT NULL) -- noqa
        AND (
            ALL_DATA.STATUS_CTMS = 'OC DESCARREGADA'
            OR ALL_DATA.STATUS_LOAD IN ('LOAD ENVIADO AO CTMS', 'LOAD CONFIRMADO')) -- noqa
),
/* QUERIES FINAIS */

SHIPMENT_STATUS AS (
    SELECT * FROM SHIPMENT_STATUS_CANCELLED
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_LOADING_ORDER
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_IN_SOURCE
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_INVOICE
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_IN_DESTINATION
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_UNLOADED
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_FINISHED
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_SINISTRO
),

SHIPMENT_STATUS_FINAL AS (
    SELECT DISTINCT
        SHIPMENTID,
        STATUS,
        REFERENCEDATE,
        QUANTITY,
        ITEMID,
        UOM,
        SHIP_BK AS BK
    FROM SHIPMENT_STATUS
)

SELECT -- noqa
    ST.SHIPMENTID,
    ST.STATUS,
    TO_CHAR(ST.REFERENCEDATE, 'DD-MM-YYYY') AS REFERENCEDATE,
    ST.QUANTITY,
    ST.ITEMID,
    ST.UOM,
    ST.BK
FROM SHIPMENT_STATUS_FINAL AS ST
INNER JOIN {{ ref('item_master') }} AS I
    ON ST.ITEMID = I.ITEM
