-- PALAVRAS VALIDAS QUE O REGEX IRA PROCURAR
-- CASO ENCONTRAR TENTARA IDENTIFICAR O NUMERO DO CONTRATO
{% set CONTRACT_KEYWORDS_1 = 'CONTRATO NR CARGILL|CONTRATO|CTR|CARGILL|CLIENTE N|VENDA|NO|CLIENTE|' %}
{% set CONTRACT_KEYWORDS_2 = 'COMPRADOR|CONTRATO N|CT|COMPRA|TRADING|NR|OC CAB|INDUSTRIA|' %}
{% set CONTRACT_KEYWORDS_3 = 'CAK|GRAO|JURIDICO|CARGIL|ORIGINAL|NUMERO|EMP|OFFTAKER|' %}
{% set CONTRACT_KEYWORDS_4 = 'CARGIL N|NS|NO|NUM|CONTRATOS|N CONTRATO|PEDIDO|LAR|SOJA|CTT|CT T|VENDA N' %}

{% set CONTRACT_KEYWORDS = CONTRACT_KEYWORDS_1 ~ CONTRACT_KEYWORDS_2 ~ CONTRACT_KEYWORDS_3 ~ CONTRACT_KEYWORDS_4 %}

WITH
EXTRACT_CONTRACT AS (
    SELECT
        INVOICE_KEY,
        INF_REP AS TEXT_COMPL_NOTA,
        {{ regex_find_contract('INF_REP', CONTRACT_KEYWORDS, '1', pattern=1) }} AS CONTRACT_NUMBER,
        {{ regex_find_contract('INF_REP', CONTRACT_KEYWORDS, '2', pattern=1) }} AS CONTRACT_NUMBER_2,
        {{ regex_find_contract('INF_REP', CONTRACT_KEYWORDS, '3', pattern=1) }} AS CONTRACT_NUMBER_3,
        {{ regex_find_contract('INF_REP', CONTRACT_KEYWORDS, '1', pattern=2) }} AS CONTRACT_NUMBER_PT2,
        {{ regex_find_contract('INF_REP', CONTRACT_KEYWORDS, '2', pattern=2) }} AS CONTRACT_NUMBER_PT2_2,
        {{ regex_find_contract('INF_REP', CONTRACT_KEYWORDS, '3', pattern=2) }} AS CONTRACT_NUMBER_PT2_3
    FROM (
        SELECT
            *,
            REPLACE(
                REGEXP_REPLACE(
                    {{ remove_acent('UPPER(TEXTO_NOTA)') }},
                    '({{ CONTRACT_KEYWORDS }})',
                    ' \\1 '
                ), '  ', ' '
            ) AS INF_REP
        FROM {{ ref('tab_shipment_invoice_details_stg') }}
    ) AS X

),

TRANSFORM_CONTRACT AS (
    SELECT
        INVOICE_KEY,
        TEXT_COMPL_NOTA,
        {{ format_contract('CONTRACT_NUMBER') }} AS CONTRACT_NUMBER,
        {{ format_contract('CONTRACT_NUMBER_2') }} AS CONTRACT_NUMBER_2,
        {{ format_contract('CONTRACT_NUMBER_3') }} AS CONTRACT_NUMBER_3,
        {{ format_contract('CONTRACT_NUMBER_PT2') }} AS CONTRACT_NUMBER_PT2,
        {{ format_contract('CONTRACT_NUMBER_PT2_2') }} AS CONTRACT_NUMBER_PT2_2,
        {{ format_contract('CONTRACT_NUMBER_PT2_3') }} AS CONTRACT_NUMBER_PT2_3
    FROM EXTRACT_CONTRACT
),

SOURCING_CONTRACT_WITHOUT_BALANCE AS (
    SELECT DISTINCT
        H.CONTRACTNUMBER,
        H.ID,
        D.TORECEIVETOTAL,
        D.ITEMID
    FROM {{ ref('tab_sourcing_contract_internal_stg') }} AS H
    INNER JOIN {{ ref('tab_sourcing_contract_details_stg') }} AS D
        ON H.ID = D.SOURCINGCONTRACTID
    WHERE
        1 = 1
        AND D.TORECEIVETOTAL = 0
        AND TO_DATE(
            NULLIF(H.DELIVERYEND, 'N/A'), 'DD-MM-YYYY'
        ) >= DATEADD('DAY', -60, CURRENT_DATE())
),

SOURCING_CONTRACT_WITH_BALANCE AS (
    SELECT DISTINCT
        H.CONTRACTNUMBER,
        H.ID,
        D.TORECEIVETOTAL,
        D.ITEMID
    FROM {{ ref('tab_sourcing_contract_internal_stg') }} AS H
    INNER JOIN {{ ref('tab_sourcing_contract_details_stg') }} AS D
        ON H.ID = D.SOURCINGCONTRACTID
    WHERE
        1 = 1
        AND D.TORECEIVETOTAL > 0
)

SELECT DISTINCT
    X.INVOICE_KEY,
    X.TEXT_COMPL_NOTA,
    COALESCE(
        H1.ID, H2.ID, H3.ID, H4.ID, H5.ID, H6.ID
    ) AS SOURCINGCONTRACTID,
    COALESCE(
        H1.CONTRACTNUMBER, H2.CONTRACTNUMBER,
        H3.CONTRACTNUMBER, H4.CONTRACTNUMBER,
        H5.CONTRACTNUMBER, H6.CONTRACTNUMBER
    ) AS CONTRACTNUMBER,
    COALESCE(
        H1.ITEMID, H2.ITEMID,
        H3.ITEMID, H4.ITEMID,
        H5.ITEMID, H6.ITEMID
    ) AS ITEMID
FROM TRANSFORM_CONTRACT AS X
LEFT JOIN SOURCING_CONTRACT_WITH_BALANCE AS H1
    ON H1.CONTRACTNUMBER IN (
        X.CONTRACT_NUMBER,
        X.CONTRACT_NUMBER_2,
        X.CONTRACT_NUMBER_3,
        X.CONTRACT_NUMBER_PT2,
        X.CONTRACT_NUMBER_PT2_2,
        X.CONTRACT_NUMBER_PT2_3
    )
LEFT JOIN SOURCING_CONTRACT_WITH_BALANCE AS H2
    ON LEFT(H2.CONTRACTNUMBER, 10) IN (
        X.CONTRACT_NUMBER,
        X.CONTRACT_NUMBER_2,
        X.CONTRACT_NUMBER_3,
        X.CONTRACT_NUMBER_PT2,
        X.CONTRACT_NUMBER_PT2_2,
        X.CONTRACT_NUMBER_PT2_3
    )
LEFT JOIN SOURCING_CONTRACT_WITH_BALANCE AS H3
    ON H3.CONTRACTNUMBER IN (
        LEFT(X.CONTRACT_NUMBER, 10),
        LEFT(X.CONTRACT_NUMBER_2, 10),
        LEFT(X.CONTRACT_NUMBER_3, 10),
        LEFT(X.CONTRACT_NUMBER_PT2, 10),
        LEFT(X.CONTRACT_NUMBER_PT2_2, 10),
        LEFT(X.CONTRACT_NUMBER_PT2_3, 10)
    )
LEFT JOIN SOURCING_CONTRACT_WITH_BALANCE AS H4
    ON LEFT(H4.CONTRACTNUMBER, 10) IN (
        LEFT(X.CONTRACT_NUMBER, 10),
        LEFT(X.CONTRACT_NUMBER_2, 10),
        LEFT(X.CONTRACT_NUMBER_3, 10),
        LEFT(X.CONTRACT_NUMBER_PT2, 10),
        LEFT(X.CONTRACT_NUMBER_PT2_2, 10),
        LEFT(X.CONTRACT_NUMBER_PT2_3, 10)
    )
LEFT JOIN SOURCING_CONTRACT_WITHOUT_BALANCE AS H5
    ON H5.CONTRACTNUMBER IN (
        X.CONTRACT_NUMBER,
        X.CONTRACT_NUMBER_2,
        X.CONTRACT_NUMBER_3,
        X.CONTRACT_NUMBER_PT2,
        X.CONTRACT_NUMBER_PT2_2,
        X.CONTRACT_NUMBER_PT2_3
    )
LEFT JOIN SOURCING_CONTRACT_WITHOUT_BALANCE AS H6
    ON LEFT(H6.CONTRACTNUMBER, 10) IN (
        LEFT(X.CONTRACT_NUMBER, 10),
        LEFT(X.CONTRACT_NUMBER_2, 10),
        LEFT(X.CONTRACT_NUMBER_3, 10),
        LEFT(X.CONTRACT_NUMBER_PT2, 10),
        LEFT(X.CONTRACT_NUMBER_PT2_2, 10),
        LEFT(X.CONTRACT_NUMBER_PT2_3, 10)
    )
WHERE
    1 = 1
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY X.INVOICE_KEY
    ORDER BY COALESCE(
        H1.CONTRACTNUMBER,
        H2.CONTRACTNUMBER,
        H3.CONTRACTNUMBER,
        H4.CONTRACTNUMBER,
        H5.CONTRACTNUMBER,
        H6.CONTRACTNUMBER
    )
) = 1
