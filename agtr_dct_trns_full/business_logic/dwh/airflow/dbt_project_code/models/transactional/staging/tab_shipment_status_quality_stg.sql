-- FILTRA APENAS ITEMS SOJA E MILHO PARA O RELEASE 1 APENAS PRODUTOS DE INBOUND
-- PARA OS PROXIMOS RELEASES, PREVISTO A INCLUSAO DE DADOS DE QUALIDADE DO FSQR
-- DEVEM SER INCLUIDOS DAODS DE QUALIDADE PARA OUTBOUND (EXPEDICAO DE PRODUTOS)
WITH
ITEM_DCT AS (
    SELECT
        I.ITEM,
        I.L1
    FROM {{ ref('item_master') }} AS I
    WHERE I.L1 IN ('SOJA', 'MILHO') -- RESTRINGE PRODUTOS
),

-- CONSULTA INFORMACOES DE QUALIDADE DISPONIVEIS NO RDS
RDS_QUALIDADE AS (
    SELECT DISTINCT -- noqa
        RDS.IDOPERACAOFINALIDADE,
        TO_CHAR(RDS.FICHAJDE) AS LOADNUMBER,
        RDS.CODIGOLONGOPRODUTO AS ITEMID,
        RDS.IMPUREZASORIGEMVALOR,
        RDS.IMPUREZASVALOR,
        RDS.UMIDADEORIGEMVALOR,
        RDS.UMIDADEVALOR,
        RDS.AVARIADOSORIGEMVALOR,
        RDS.AVARIADOSTOTAISVALOR
    FROM
        {{ source('rds', 'VW_RDS_HISTORIC_DCT') }} AS RDS
    INNER JOIN ITEM_DCT AS I ON RDS.CODIGOLONGOPRODUTO = I.ITEM
    WHERE
        RDS.IDOPERACAOFINALIDADE = 'RECEPCAO'
        AND (RDS.FICHAJDE IS NOT NULL AND RDS.FICHAJDE != 0)

    UNION DISTINCT

    SELECT DISTINCT -- noqa
        RDS.IDOPERACAOFINALIDADE,
        TO_CHAR(RDS.LOADE1) AS LOADNUMBER,
        TRIM(RDS.CODIGOLONGOPRODUTO) AS ITEMID,
        RDS.IMPUREZASORIGEMVALOR,
        RDS.IMPUREZASVALOR,
        RDS.UMIDADEORIGEMVALOR,
        RDS.UMIDADEVALOR,
        RDS.AVARIADOSORIGEMVALOR,
        RDS.AVARIADOSTOTAISVALOR
    FROM
        {{ source('rds', 'VW_RDS_HISTORIC_DCT') }} AS RDS
    INNER JOIN ITEM_DCT AS I ON RDS.CODIGOLONGOPRODUTO = I.ITEM
    WHERE
        RDS.IDOPERACAOFINALIDADE = 'RECEPCAO'
        AND (RDS.LOADE1 IS NOT NULL OR RDS.LOADE1 != 0)
),

RDS_QUALIDADE_ALL AS (
    SELECT -- noqa
        NULL AS SHIPMENTID,
        IDOPERACAOFINALIDADE,
        LOADNUMBER,
        ITEMID,
        CASE
            WHEN METRICA LIKE '%AVARIADO%' THEN 'AVARIADOS'
            WHEN METRICA LIKE '%IMPUREZA%' THEN 'IMPUREZA'
            WHEN METRICA LIKE '%UMIDADE%' THEN 'UMIDADE'
        END AS METRICA,
        MAX(VALOR_METRICA) AS VALOR_METRICA, -- noqa
    FROM RDS_QUALIDADE
        UNPIVOT (VALOR_METRICA FOR METRICA IN (IMPUREZASORIGEMVALOR, IMPUREZASVALOR,  -- noqa
            UMIDADEORIGEMVALOR, UMIDADEVALOR, AVARIADOSORIGEMVALOR, AVARIADOSTOTAISVALOR))   -- noqa
    GROUP BY
        1, 2, 3, 4, 5
),

-- CONSULTA INFORMACOES DE QUALIDADE DISPONIVEIS NO JDE
JDE_QUALIDADE_ALL AS (
    SELECT DISTINCT -- noqa
        Q.SHIPMENTID,
        Q.EVENTO AS IDOPERACAOFINALIDADE,
        TO_CHAR(Q.FICHA) AS LOADNUMBER,
        TRIM(Q.CODIGOPRODUTO) AS ITEMID,
        Q.IDTESTQUALIDADE AS METRICA,
        Q.TESTQUALIDADE AS VALOR_METRICA
        --'EXPEDICAO' AS TIPO -- noqa
    FROM {{ ref('tab_shipment_jde_quality_ficha_stg') }} AS Q
    WHERE
        (Q.IDTESTQUALIDADE LIKE 'AVARIADOS%'  -- noqa
            OR Q.IDTESTQUALIDADE LIKE 'UMIDADE%'
            OR Q.IDTESTQUALIDADE LIKE 'IMPUREZA%')  -- noqa
    QUALIFY
        RANK() OVER (
            PARTITION BY
                Q.SHIPMENTID,
                Q.FICHA,
                Q.EVENTO,
                Q.CODIGOPRODUTO,
                Q.IDTESTQUALIDADE
            ORDER BY
                Q.LINHAFICHA ASC,
                Q.DATAQUALIDADE DESC
        ) = 1

    UNION DISTINCT

    SELECT DISTINCT -- noqa
        NULL AS SHIPMENTID,
        Q.EVENTO AS IDOPERACAOFINALIDADE,
        Q.LOADNUMBER,
        TRIM(Q.CODIGOPRODUTO) AS ITEMID,
        Q.IDTESTQUALIDADE AS METRICA,
        Q.TESTQUALIDADE AS VALOR_METRICA
       -- 'EXPEDICAO' AS TIPO -- noqa
    FROM {{ ref('tab_shipment_jde_quality_invoice_load_stg') }} AS Q

    UNION DISTINCT

    SELECT DISTINCT -- noqa
        NULL AS SHIPMENTID,
        Q.EVENTO AS IDOPERACAOFINALIDADE,
        Q.LOADNUMBER,
        TRIM(Q.CODIGOPRODUTO) AS ITEMID,
        Q.IDTESTQUALIDADE AS METRICA,
        Q.TESTQUALIDADE AS VALOR_METRICA
       -- 'RECEPCAO' AS TIPO -- noqa
    FROM {{ ref('tab_shipment_jde_quality_finish_load_stg') }} AS Q
),

/* PRIORIZA INFORMAÇÕES DE QUALIDADE DISPONÍVEIS NO JDE */
QUALIDADE_ALL AS (
    SELECT * FROM JDE_QUALIDADE_ALL
    UNION DISTINCT
    SELECT * FROM RDS_QUALIDADE_ALL
    WHERE CONCAT(LOADNUMBER || ITEMID || METRICA) NOT IN -- noqa
        (SELECT CONCAT(LOADNUMBER || ITEMID || METRICA) FROM JDE_QUALIDADE_ALL) -- noqa
),

TB_METRICA AS (
    /* L1: MILHO E SOJA */
    SELECT
        I.ITEM,
        I.L1,
        M.*
    FROM ITEM_DCT AS I,
    ( -- noqa
        SELECT 'UMIDADE' AS MEASURE, '%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'IMPUREZA' AS MEASURE, '%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'AVARIADOS' AS MEASURE, '%' AS UNIT -- noqa
    ) AS M -- noqa
    WHERE I.L1 IN ('SOJA', 'MILHO')

    UNION DISTINCT

    /* L1: FARELO% */
    SELECT
        I.ITEM,
        I.L1,
        M.*
    FROM ITEM_DCT AS I,
    ( -- noqa
        SELECT 'FIBRA' AS MEASURE, '%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'ÓLEO' AS MEASURE, '%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'PROTEÍNA' AS MEASURE, '%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'PROTEÍNA SOLÚVEL' AS MEASURE, '%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'SILICA' AS MEASURE, '%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'UREASE' AS MEASURE, '%' AS UNIT -- noqa
    ) AS M -- noqa
    WHERE I.L1 LIKE '%FARELO%'

    UNION DISTINCT

    /* L1: CASCA */
    SELECT
        I.ITEM,
        I.L1,
        M.*
    FROM ITEM_DCT AS I,
    ( -- noqa
        SELECT 'ÓLEO' AS MEASURE, '%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'FIBRA' AS MEASURE, '%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'PROTEÍNA' AS MEASURE, '%' AS UNIT -- noqa
    ) AS M -- noqa
    WHERE I.L1 IN ('CASCA')

    UNION ALL

    /* L1: OLEO DEGOMADO */
    SELECT
        I.ITEM,
        I.L1,
        M.*
    FROM ITEM_DCT AS I,
    ( -- noqa
        SELECT 'UMIDADE' AS MEASURE, '%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'COR RED' AS MEASURE, 'RED' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'COR YELLOW' AS MEASURE,'YELLOW' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'CLOROFILA' AS MEASURE,'PPB' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'FLASH POINT' AS MEASURE,'CELSIUS' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'IMPUREZA' AS MEASURE,'%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'ACIDEZ' AS MEASURE,'%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'FÓSFORO' AS MEASURE,'PPM' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'SABÕES' AS MEASURE,'PPM' AS UNIT -- noqa
    ) AS M -- noqa
    WHERE I.L1 IN ('OLEO DEGOMADO')

    UNION ALL

    /* L1: OLEO REFINADO */
    SELECT
        I.ITEM,
        I.L1,
        M.*
    FROM ITEM_DCT AS I,
    ( -- noqa
        SELECT 'UMIDADE' AS MEASURE,'%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'COR RED' AS MEASURE,'RED' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'COR YELLOW' AS MEASURE,'YELLOW' AS UNIT  -- noqa
        UNION ALL -- noqa
        SELECT 'CLOROFILA' AS MEASURE,'PPB' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'FLASH POINT' AS MEASURE,'CELSIUS' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'IMPUREZA' AS MEASURE,'%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'FFA' AS MEASURE,'%' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'FÓSFORO' AS MEASURE,'PPM' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'SABÕES' AS MEASURE,'PPM' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'DENSIDADE' AS MEASURE,'G/CM3' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'OSI' AS MEASURE,'HOURS' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'CÁLCIO' AS MEASURE,'PPM' AS UNIT -- noqa
        UNION ALL -- noqa
        SELECT 'MAGNÉSIO' AS MEASURE,'PPM' AS UNIT -- noqa
    ) AS M -- noqa
    WHERE I.L1 IN ('OLEO REFINADO')
),

TB_SHIP_STATUS AS (
    SELECT DISTINCT -- noqa
        S.ID AS SHIPMENTID, S.LOADNUMBER, STS.ITEMID,
        STS.STATUS, STS.REFERENCEDATE, MTR.MEASURE, MTR.UNIT
    FROM
        {{ ref('tab_shipment_details_stg') }} AS S
    INNER JOIN {{ ref('tab_shipment_status_stg') }} AS STS
        ON S.ID = STS.SHIPMENTID
    INNER JOIN TB_METRICA AS MTR
        ON STS.ITEMID = MTR.ITEM
    WHERE
        STS.STATUS IN ('INVOICE', 'IN DESTINATION', 'UNLOADED', 'FINISHED')
),

SHIPMENT_STATUS_QUALITY_STG AS (
    SELECT -- STATUS INVOICE
        COALESCE(QLTY.SHIPMENTID, SHIP.SHIPMENTID) AS SHIPMENTID,
        SHIP.STATUS,
        SHIP.REFERENCEDATE,
        SHIP.MEASURE,
        QLTY.VALOR_METRICA AS "VALUE",
        SHIP.UNIT
    FROM TB_SHIP_STATUS AS SHIP
    INNER JOIN JDE_QUALIDADE_ALL AS QLTY
        ON
            SHIP.ITEMID = QLTY.ITEMID
            AND (SHIP.LOADNUMBER = QLTY.LOADNUMBER)
            AND SHIP.MEASURE = QLTY.METRICA
            AND IFF(
                QLTY.SHIPMENTID IS NOT NULL,
                QLTY.SHIPMENTID = SHIP.SHIPMENTID,
                1 = 1
            )
    WHERE
        SHIP.STATUS = 'INVOICE'
        AND QLTY.IDOPERACAOFINALIDADE = 'EXPEDICAO'
        AND QLTY.VALOR_METRICA IS NOT NULL
        AND QLTY.METRICA IN ('AVARIADOS', 'IMPUREZA','UMIDADE')  -- noqa

    UNION DISTINCT

    SELECT -- STATUS IN DESTINATION
        COALESCE(QLTY.SHIPMENTID, SHIP.SHIPMENTID) AS SHIPMENTID,
        SHIP.STATUS,
        SHIP.REFERENCEDATE,
        SHIP.MEASURE,
        QLTY.VALOR_METRICA AS "VALUE",
        SHIP.UNIT
    FROM TB_SHIP_STATUS AS SHIP
    INNER JOIN QUALIDADE_ALL AS QLTY
        ON
            SHIP.ITEMID = QLTY.ITEMID
            AND (SHIP.LOADNUMBER = QLTY.LOADNUMBER)
            AND SHIP.MEASURE = QLTY.METRICA
            AND IFF(
                QLTY.SHIPMENTID IS NOT NULL,
                QLTY.SHIPMENTID = SHIP.SHIPMENTID,
                1 = 1
            )
    WHERE
        SHIP.STATUS = 'IN DESTINATION'
        AND QLTY.IDOPERACAOFINALIDADE = 'RECEPCAO'
        AND QLTY.VALOR_METRICA IS NOT NULL
        AND QLTY.METRICA IN ('AVARIADOS', 'IMPUREZA','UMIDADE')  -- noqa

    UNION DISTINCT

    SELECT -- STATUS UNLOADED
        COALESCE(QLTY.SHIPMENTID, SHIP.SHIPMENTID) AS SHIPMENTID,
        SHIP.STATUS,
        SHIP.REFERENCEDATE,
        SHIP.MEASURE,
        QLTY.VALOR_METRICA AS "VALUE",
        SHIP.UNIT
    FROM TB_SHIP_STATUS AS SHIP
    INNER JOIN QUALIDADE_ALL AS QLTY
        ON
            SHIP.ITEMID = QLTY.ITEMID
            AND (SHIP.LOADNUMBER = QLTY.LOADNUMBER)
            AND SHIP.MEASURE = QLTY.METRICA
            AND IFF(
                QLTY.SHIPMENTID IS NOT NULL,
                QLTY.SHIPMENTID = SHIP.SHIPMENTID,
                1 = 1
            )
    WHERE
        SHIP.STATUS = 'UNLOADED'
        AND QLTY.IDOPERACAOFINALIDADE = 'RECEPCAO'
        AND QLTY.VALOR_METRICA IS NOT NULL
        AND QLTY.METRICA IN ('AVARIADOS', 'IMPUREZA','UMIDADE')  -- noqa

    UNION DISTINCT

    SELECT -- STATUS FINISHED
        COALESCE(QLTY.SHIPMENTID, SHIP.SHIPMENTID) AS SHIPMENTID,
        SHIP.STATUS,
        SHIP.REFERENCEDATE,
        SHIP.MEASURE,
        QLTY.VALOR_METRICA AS "VALUE",
        SHIP.UNIT
    FROM TB_SHIP_STATUS AS SHIP
    INNER JOIN JDE_QUALIDADE_ALL AS QLTY
        ON
            SHIP.ITEMID = QLTY.ITEMID
            AND (SHIP.LOADNUMBER = QLTY.LOADNUMBER)
            AND SHIP.MEASURE = QLTY.METRICA
            AND IFF(
                QLTY.SHIPMENTID IS NOT NULL,
                QLTY.SHIPMENTID = SHIP.SHIPMENTID,
                1 = 1
            )
    WHERE
        SHIP.STATUS = 'FINISHED'
        AND QLTY.IDOPERACAOFINALIDADE = 'RECEPCAO'
        AND QLTY.VALOR_METRICA IS NOT NULL
        AND QLTY.METRICA  IN ('AVARIADOS', 'IMPUREZA','UMIDADE')  -- noqa

),

SHIPMENT_STATUS_QUALITY_FINAL AS (
    SELECT DISTINCT
        SHIPMENTID,
        "STATUS",
        REFERENCEDATE,
        MEASURE,
        "VALUE",
        UNIT
    FROM SHIPMENT_STATUS_QUALITY_STG
    WHERE REFERENCEDATE IS NOT NULL
),

SHIPMENT_STATUS_QUALITY AS (
    SELECT DISTINCT
        SHIPMENTID,
        COALESCE(NULLIF("STATUS", ''), 'N/A') AS "STATUS",
        COALESCE(NULLIF(REFERENCEDATE, ''), 'N/A') AS REFERENCEDATE,
        COALESCE(NULLIF(MEASURE, ''), 'N/A') AS MEASURE,
        ROUND(COALESCE("VALUE", 0), 3) AS "VALUE",
        COALESCE(NULLIF(UNIT, ''), 'N/A') AS UNIT
    FROM SHIPMENT_STATUS_QUALITY_FINAL
    WHERE
        "VALUE" IS NOT NULL
        AND "STATUS" IN ('INVOICE', 'FINISHED')
)

SELECT
    *,
    HASH(*) AS HASH_ID
FROM SHIPMENT_STATUS_QUALITY
