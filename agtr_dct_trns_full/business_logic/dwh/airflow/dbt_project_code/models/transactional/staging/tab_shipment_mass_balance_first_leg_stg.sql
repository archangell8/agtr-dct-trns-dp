WITH

MASS_BALANCE AS (

    SELECT -- noqa
        --CONCAT(F.PRODUCT_CODE,'-',L.LOCATIONID,'-', F.FINALDESTINATION) AS CROP_BUSINESS_KEY, -- noqa
        CONCAT(F.PRODUCT_CODE, '-', L.LOCATIONID) AS CROP_BUSINESS_KEY,
        F.PRODUCT_CODE,
        L.LOCATIONID AS TRANSSHIPMENT_LOCATION, --TRANSBORDO
        F.FINALDESTINATION AS PORT_LOCATION, --LOCATION_PORTO,
        LF.LOCATION_CODE,
        F.INVOICE_ISSUANCE_DATE,
        SUM(F.INVOICE_VOLUME) AS INVOICE_VOLUME
    FROM {{ ref('tab_shipment_fichas_jde_stg') }} AS F
    INNER JOIN {{ ref('tab_location_internal_stg') }} AS L
        ON F.BRANCH_PLANT_DESTINATION = L.LOCATIONID
    LEFT JOIN {{ ref('tab_location_internal_stg') }} AS LF
        ON F.FINALDESTINATION = LF.LOCATIONID

    WHERE
        F.OPERATION_TYPE IN ('CIF', 'FOB')
        AND F.PURCHASE_STATUS_CODE <> '980-999'
        AND L.LOCATION_UNIT_STRUCTURE IN ('TRANSBORDO', 'PORTO FLUVIAL')
        AND L.LOCATIONID IN
        (
            SELECT DISTINCT SUBSTR(SOURCE_CODE, 1, 10) AS LOCATIONTRANSBORDO
            FROM {{ source('pscfl', 'F_MIN_DCT_UDC') }} AS S
            WHERE
                S.CATEGORY = 'SHIPMENT'
                AND S.STAGE = 'CIF FOB TRANSBORDO'
        )
    GROUP BY 1, 2, 3, 4, 5, 6

)

SELECT *, -- noqa
    RANK() OVER (PARTITION BY CROP_BUSINESS_KEY ORDER BY INVOICE_ISSUANCE_DATE) AS RK  -- noqa
FROM MASS_BALANCE
