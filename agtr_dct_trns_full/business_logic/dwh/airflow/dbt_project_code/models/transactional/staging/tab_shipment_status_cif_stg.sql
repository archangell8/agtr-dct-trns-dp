WITH

SHIPMENT_STATUS_CIF AS (
    SELECT DISTINCT
        ID,
        ITEMID,
        DOCNUMBER AS BK_CIF,
        BK AS SHIP_BK
    FROM {{ ref('tab_shipment_details_cif_stg') }}
),

SHIPMENT_STATUS_FICHA AS (
    SELECT -- noqa
        CONCAT(
            FC.ID_NF, '-',
            COALESCE(FC.FICHA, 'N/A'), '-CIF'
        ) AS BK_CIF,
        CONCAT(
            COALESCE(FC.ID_NF, 'N/A'), '-',
            COALESCE(CTR_FC.CONTRACTNUMBER, 'N/A'), '-',
            COALESCE(FC.FICHA, 'N/A'), '-',
            COALESCE(FC.ADDRESS_FAZENDA, 'N/A'), '-',
            COALESCE(FC.DESTINATION_CODE, 'N/A')
        ) AS SHIP_BK,
        FC.CODIGO_PRODUTO AS ITEMID,
        FC.UOM,
        UPPER(TRIM(FC.STATUS_FICHA)) AS STATUS_FICHA,
        FC.DATA_APLICACAO_FICHA,
        FC.DATA_CRIACAO_FICHA,
        FC.DATA_EMISSAO_NF,
        MAX(FC.LOTID) AS LOTID,
        SUM(FC.VOL_NF) AS VL_NF_FICHA,
        MAX(FC.VOLUME_TRANSPORTADO) AS VL_TRANSPORTADO_FICHA,
        SUM(FC.VOL_BALANCA) AS VL_BALANCA_FICHA,
        MAX(FC.DATA_CANCELAMENTO) AS DATA_CANCELAMENTO
    FROM {{ ref('tab_shipment_ficha_intransit_stg') }} AS FC -- noqa
    INNER JOIN {{ ref('item_master') }} AS I ON FC.CODIGO_PRODUTO = I.ITEM
    LEFT JOIN {{ ref('tab_shipment_invoice_and_contracts_stg') }} AS CTR_INVOICE
        ON FC.ID_NF = CTR_INVOICE.INVOICE_KEY
    LEFT JOIN {{ ref('tab_sourcing_contract_internal_stg') }} AS CTR_FC
        ON CTR_FC.CONTRACTNUMBER = COALESCE(
            NULLIF(FC.CONTRATO_ORIGINACAO, 'N/A'), CTR_INVOICE.CONTRACTNUMBER
        )
    WHERE
        FC.TIPO_DE_OPERACAO = 'CIF'
    GROUP BY
        1, 2, 3, 4, 5, 6, 7, 8
),

SHIPMENT_STATUS_NEOGRID AS (
    SELECT -- noqa
        CONCAT(
            NEO.INVOICE_KEY, '-',
            COALESCE(NEO.PURCHASE_CODE, 'N/A'), '-CIF'
        ) AS BK_CIF,
        CONCAT(
            COALESCE(NEO.INVOICE_KEY, 'N/A'), '-',
            COALESCE(NEO.CONTRACTNUMBER, 'N/A'), '-',
            COALESCE(NEO.PURCHASE_CODE, 'N/A'), '-',
            COALESCE(SRC.LOCATIONID, 'N/A')
        ) AS SHIP_BK,
        NEO.PRODUCT_CODE AS ITEMID,
        UPPER(NEO.INVOICE_ITEM_UOM) AS UOM,
        'BRE' AS CURRENCY,
        NEO.CONTRACTNUMBER AS CONTRACT_INFO_NF,
        MAX(NEO.INVOICE_WEIGHT) AS INVOICE_WEIGHT,
        SUM(COALESCE(NEO.INVOICE_ITEM_WEIGHT, 0)) AS QUANTITY,
        MAX(NEO.INVOICE_ISSUANCE_DATE) AS INVOICE_ISSUANCE_DATE
    FROM {{ ref('tab_shipment_neogrid_stg') }} AS NEO
    LEFT JOIN {{ ref('tab_location_internal_stg') }} AS SRC
        ON LPAD(SRC.CNPJ, 14, '0') = LPAD(TRIM(NEO.SOURCE_CNPJ), 14, '0')
    GROUP BY
        1, 2, 3, 4, 5, 6
),

SHIPMENT_STATUS_RDS AS (
    SELECT DISTINCT
        RDS.LOTID,
        RDS.LOADE1,
        RDS.FICHAJDE,
        RDS.IDOPERACAOFINALIDADE,
        RDS.CODIGOLONGOPRODUTO,
        RDS.QUANTIDADEPRODUTO,
        RDS.PESOSECORATEIO,
        RDS.PESOESTIMADO,
        RDS.DATAHORACHEGADA,
        RDS.DATAHORASAIDA,
        RDS.DATAHORASEGUNDAPESAGEM,
        RDS.UNIDADEMEDIDA
    FROM {{ source('rds', 'VW_RDS_HISTORIC_DCT') }} AS RDS
    INNER JOIN {{ ref('item_master') }} AS I ON RDS.CODIGOLONGOPRODUTO = I.ITEM
),

ALL_STATUS_DATA_FINAL AS (
    SELECT -- noqa
        S.ID AS SHIPMENTID,
        S.SHIP_BK,
        C.ITEMID,
        C.UOM AS UOM_FICHA,
        C.DATA_APLICACAO_FICHA AS DT_APLICACAO_FICHA,
        C.DATA_CRIACAO_FICHA AS DT_CRIACAO_FICHA,
        C.DATA_EMISSAO_NF AS DT_EMISSAO_NF,
        C.STATUS_FICHA,
        C.LOTID AS LOTID_FICHA,
        C.VL_BALANCA_FICHA,
        C.VL_TRANSPORTADO_FICHA,
        C.VL_NF_FICHA,
        C.DATA_CANCELAMENTO AS DT_CANCELAMENTO,
        N.QUANTITY AS QUANTITY_NEO,
        N.INVOICE_ISSUANCE_DATE AS INVOICE_ISSUANCE_DATE_NEO,
        N.ITEMID AS ITEMID_NEO,
        N.UOM AS UOM_NEO
    FROM SHIPMENT_STATUS_CIF AS S
    LEFT JOIN SHIPMENT_STATUS_FICHA AS C
        ON
            S.SHIP_BK = C.SHIP_BK
            AND S.ITEMID = C.ITEMID
    LEFT JOIN SHIPMENT_STATUS_NEOGRID AS N
        ON
            S.BK_CIF = N.BK_CIF
            AND S.ITEMID = N.ITEMID
),

/* QUERIES PARA CADA STATUS DO SHIPMENT */
SHIPMENT_STATUS_CANCELLED AS (
    /* ATUALIZA SHIPMENTS BASEADOS NOS STATUS CANCELADO */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'CANCELLED' AS "STATUS",
        COALESCE(
            ALL_DATA.DT_CANCELAMENTO,
            ALL_DATA.DT_CRIACAO_FICHA
        ) AS REFERENCEDATE,
        ALL_DATA.UOM_FICHA AS UOM,
        ALL_DATA.VL_NF_FICHA AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (
            ALL_DATA.DT_CRIACAO_FICHA IS NOT NULL
            OR ALL_DATA.DT_CANCELAMENTO IS NOT NULL
        )  -- noqa
            AND (ALL_DATA.STATUS_FICHA = 'FICHA CANCELADA' )  -- noqa
),

SHIPMENT_STATUS_INVOICE AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA EMISSAO DA NOTA FISCAL */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        COALESCE(ALL_DATA.ITEMID_NEO, ALL_DATA.ITEMID) AS ITEMID,
        'INVOICE' AS "STATUS",
        COALESCE(
            ALL_DATA.INVOICE_ISSUANCE_DATE_NEO,
            ALL_DATA.DT_EMISSAO_NF
        ) AS REFERENCEDATE,
        COALESCE(ALL_DATA.UOM_NEO, ALL_DATA.UOM_FICHA) AS UOM,
        COALESCE(ALL_DATA.QUANTITY_NEO, ALL_DATA.VL_NF_FICHA, 0) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (ALL_DATA.DT_EMISSAO_NF IS NOT NULL -- noqa
        AND ALL_DATA.STATUS_FICHA != 'FICHA CANCELADA')  -- noqa
        OR ALL_DATA.INVOICE_ISSUANCE_DATE_NEO IS NOT NULL
),

SHIPMENT_STATUS_IN_DESTINATION AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA DE CHEGADA NA LOCALIDADE */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'IN DESTINATION' AS "STATUS",
        RDS.DATAHORACHEGADA AS REFERENCEDATE,
        RDS.UNIDADEMEDIDA,
        SUM(RDS.QUANTIDADEPRODUTO) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    INNER JOIN SHIPMENT_STATUS_RDS AS RDS
        ON ALL_DATA.LOTID_FICHA = RDS.LOTID
    WHERE
        RDS.DATAHORACHEGADA IS NOT NULL
        AND (ALL_DATA.STATUS_FICHA != 'FICHA CANCELADA')  -- noqa
    GROUP BY
        1, 2, 3, 4, 5, 6
),

SHIPMENT_STATUS_UNLOADED AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA DA SAIDA DA LOCALIDADE */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'UNLOADED' AS "STATUS",
        COALESCE(
            RDS.DATAHORASAIDA, RDS.DATAHORASEGUNDAPESAGEM
        ) AS REFERENCEDATE,
        RDS.UNIDADEMEDIDA,
        AVG(RDS.PESOSECORATEIO) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    INNER JOIN SHIPMENT_STATUS_RDS AS RDS
        ON ALL_DATA.LOTID_FICHA = RDS.LOTID
    WHERE
        (RDS.DATAHORASAIDA IS NOT NULL OR RDS.DATAHORASEGUNDAPESAGEM IS NOT NULL)  -- noqa
        AND (ALL_DATA.STATUS_FICHA != 'FICHA CANCELADA')  -- noqa
    GROUP BY
        1, 2, 3, 4, 5, 6
),

SHIPMENT_STATUS_FINISHED AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA APLICACAO DA FICHA / LOAD */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'FINISHED' AS "STATUS",
        ALL_DATA.DT_APLICACAO_FICHA AS REFERENCEDATE,
        ALL_DATA.UOM_FICHA AS UOM,
        ALL_DATA.VL_BALANCA_FICHA AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (ALL_DATA.DT_APLICACAO_FICHA IS NOT NULL)
        AND (ALL_DATA.STATUS_FICHA = 'FICHA APLICADA')  -- noqa
),
/* QUERIES FINAIS */

SHIPMENT_STATUS AS (
    SELECT * FROM SHIPMENT_STATUS_CANCELLED
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_INVOICE
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_IN_DESTINATION
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_UNLOADED
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_FINISHED
),

SHIPMENT_STATUS_FINAL AS (
    SELECT DISTINCT
        SHIPMENTID,
        STATUS,
        REFERENCEDATE,
        QUANTITY,
        ITEMID,
        UOM,
        SHIP_BK AS BK
    FROM SHIPMENT_STATUS
)

SELECT -- noqa
    ST.SHIPMENTID,
    ST.STATUS,
    TO_CHAR(ST.REFERENCEDATE, 'DD-MM-YYYY') AS REFERENCEDATE,
    ST.QUANTITY,
    ST.ITEMID,
    ST.UOM,
    ST.BK
FROM SHIPMENT_STATUS_FINAL AS ST
INNER JOIN {{ ref('item_master') }} AS I
    ON ST.ITEMID = I.ITEM
