    config(
        materialized='table',
        post_hook=[
            """
                INSERT INTO {{ ref('tab_shipment_control_id') }}
                SELECT
                    BK,
                    {{ target.database }}.{{ target.schema }}.SEQ_ID_SHIPMENT.NEXTVAL AS ID
                FROM {{ this }}
                WHERE BK NOT IN (
                    SELECT BK FROM {{ ref('tab_shipment_control_id') }}
                )
            """,
            """
                UPDATE {{ this }}
                SET ID = TB_CONTROL.ID
                FROM (
                    SELECT BK, MIN(ID) AS ID
                    FROM {{ ref('tab_shipment_control_id') }}
                    GROUP BY BK
                ) AS TB_CONTROL
                WHERE {{ this }}.BK = TB_CONTROL.BK
            """
        ]
    )
