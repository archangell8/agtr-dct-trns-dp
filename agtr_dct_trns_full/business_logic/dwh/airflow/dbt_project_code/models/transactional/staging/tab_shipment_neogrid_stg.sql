WITH
CMM_CTE AS (
    SELECT DISTINCT
        T.CONTRACT_NUMBER,
        CRTD.ID AS SOURCINGCONTRACTID,
        DECODE(T.TYPE, 'FBZ', 'CIF', T.TYPE) AS FREIGHTYPE,
        TO_DATE(T.DATE, 'DD-MM-YYYY') AS "DATE"
    FROM {{ ref('vw_transportation_schedule_stg') }} AS T
    INNER JOIN {{ ref('sourcing_contract_details_master') }} AS CRTD
        ON T.CONTRACT_NUMBER = CRTD.CONTRACTNUMBER
    WHERE
        1 = 1
        AND T.TYPE IN ('FOB', 'FBZ')
        AND TO_DATE(T.DATE, 'DD-MM-YYYY') >= DATEADD('DAY', -30, CURRENT_DATE())
        AND CRTD.TORECEIVETOTAL > 0
    QUALIFY RANK() OVER (
        PARTITION BY LEFT(T.CONTRACT_NUMBER, 10), T.DATE
        ORDER BY T.CONTRACT_NUMBER
    ) = 1
)

SELECT DISTINCT
    NEO.COMPANY_CODE,
    NEO.PURCHASE_CODE,
    NEO.INVOICE_KEY,
    NEO.INVOICE_MOD,
    NEO.INVOICE,
    NEO.INVOICE_SERIES,
    NEO.INVOICE_TOTAL_VALUE,
    NEO.INVOICE_WEIGHT,
    NEO.COMP_INFO,
    NEO.INVOICE_ITEM_VALUE,
    NEO.INVOICE_ITEM_WEIGHT,
    NEO.INVOICE_CFOP,
    NEO.INVOICE_GTIN,
    NEO.INVOICE_PRODUCT,
    NEO.INVOICE_ISSUANCE_DATE,
    NEO.PLATE,
    --NEO.SOURCE_CNPJ,
    --NEO.DESTINATION_CNPJ,
    NEO.EXTRACTION_DATE,
    NEO.INVOICE_ITEM_UOM,
    NEO.TEXTO_NOTA,
    NEO.FINALIDADE_EMIT_NF,
    NEO.DESC_NAT_OPERACAO,
    NEO.DOCTYPE,
    NEO.SOURCE_IE,
    NEO.DESTINATION_IE,
    SC.SOURCE,
    NEO.CARRIER,
    CASE
        WHEN NEO.TRANSMODE != 'ROD'
            THEN COALESCE(SC.TRANSMODE, NEO.TRANSMODE)
        ELSE NEO.TRANSMODE
    END AS TRANSMODE,
    COALESCE(IC.ITEMID, NEO.PRODUCT_CODE) AS PRODUCT_CODE,
    CASE
        WHEN (
            CTE_1.NRO_CHAVE_NF IS NOT NULL OR CTE_2.NRO_CHAVE_NF IS NOT NULL
        )
            THEN 'FOB'
        WHEN SC.FREIGHTTYPE = 'FBZ'
            THEN 'CIF'
        ELSE
            COALESCE(SC.FREIGHTTYPE, NEO.FREIGHT_TYPE)
    END AS FREIGHT_TYPE,
    CASE
        WHEN (
            CTE_1.NRO_CHAVE_NF IS NOT NULL OR CTE_2.NRO_CHAVE_NF IS NOT NULL
        )
            THEN 'CTMS_CTE'
        WHEN SC.FREIGHTTYPE IS NOT NULL
            THEN 'CONTRACTS'
        ELSE
            'INVOICE_DETAILS'
    END AS FREIGHTTYPE_SOURCE,
    COALESCE(LOC1.CNPJ, NEO.SOURCE_CNPJ) AS SOURCE_CNPJ,
    COALESCE(LOC2.CNPJ, NEO.DESTINATION_CNPJ) AS DESTINATION_CNPJ,
    COALESCE(
        NEO.SOURCINGCONTRACTID_, CMM.SOURCINGCONTRACTID, IC.SOURCINGCONTRACTID
    ) AS SOURCINGCONTRACTID,
    COALESCE(
        NEO.CONTRACTNUMBER_, CMM.CONTRACT_NUMBER, IC.CONTRACTNUMBER
    ) AS CONTRACTNUMBER
FROM {{ ref('tab_shipment_invoice_details_stg') }} AS NEO
LEFT JOIN {{ ref('tab_shipment_invoice_and_contracts_stg') }} AS IC
    ON NEO.INVOICE_KEY = IC.INVOICE_KEY
LEFT JOIN {{ ref('tab_sourcing_contract_internal_stg') }} AS SC
    ON SC.CONTRACTNUMBER = COALESCE(NEO.CONTRACTNUMBER_, IC.CONTRACTNUMBER)
LEFT JOIN {{ ref('tab_location_internal_stg') }} AS LOC1
    ON SC.SOURCE = LOC1.LOCATIONID
LEFT JOIN {{ ref('tab_location_internal_stg') }} AS LOC2
    ON SC.DELIVERY = LOC2.LOCATIONID
LEFT JOIN CMM_CTE AS CMM
    ON
        TO_DATE(NEO.INVOICE_ISSUANCE_DATE) = CMM.DATE
        AND LEFT(IC.CONTRACTNUMBER, 10) = LEFT(CMM.CONTRACT_NUMBER, 10)
LEFT JOIN {{ source('ctms', 'VW_CSF_CT_CONS_SIT') }} AS CTE_1
    ON
        NEO.INVOICE_KEY = 'NFe' || CTE_1.NRO_CHAVE_NF
        AND CTE_1.DM_SITUACAO != 7
        AND SUBSTR(CTE_1.CNPJ_TOMADOR, 1, 8) IN ('50290329', '60498706')
LEFT JOIN {{ source('ctms', 'VW_CSF_CT_CONS_SIT') }} AS CTE_2
    ON
        NEO.INVOICE = CTE_2.NRO_NF
        AND NEO.INVOICE_SERIES = CTE_2.SERIE_NF
        AND NEO.SOURCE_CNPJ = CTE_2.CNPJ_REMETENTE
        AND CTE_2.DM_SITUACAO != 7
        AND SUBSTR(CTE_2.CNPJ_TOMADOR, 1, 8) IN ('50290329', '60498706')
WHERE
    1 = 1
    AND NEO.PURCHASE_CODE IS NULL
