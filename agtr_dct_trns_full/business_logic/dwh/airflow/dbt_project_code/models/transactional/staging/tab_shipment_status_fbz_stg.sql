WITH

SHIP_SUM_QUANTITY AS (
    SELECT
        LOADNUMBER,
        SUM(QUANTITY) AS TOTAL_QUANTITY
    FROM {{ ref('tab_shipment_details_fbz_stg') }}
    GROUP BY 1
),

SHIPMENT_STATUS_FBZ AS (
    SELECT DISTINCT
        S.ID,
        S.ITEMID,
        S.DOCNUMBER AS BK_FBZ,
        S.BK AS SHIP_BK,
        S.QUANTITY / IFF(Q.TOTAL_QUANTITY = 0, 1, Q.TOTAL_QUANTITY) AS PROPORTION  -- noqa
    FROM {{ ref('tab_shipment_details_fbz_stg') }} AS S
    INNER JOIN SHIP_SUM_QUANTITY AS Q
        ON S.LOADNUMBER = Q.LOADNUMBER
),

SHIPMENT_STATUS_CTMS AS (
    SELECT -- noqa
        CTMS.BK_FBZ,
        CTMS.COD_ITEM AS ITEMID,
        'KG' AS UOM,
        CTMS.DATA_PREV_COLETA,
        CTMS.DATA_EMISSAO_OC,
        CTMS.DATA_NF,
        CTMS.DATA_VALIDACAO_QRCODE,
        CTMS.DATA_ENTREGA,
        UPPER(TRIM(CTMS.STATUS_OC)) AS STATUS_OC,
        MAX(CTMS.QUANTIDADE) AS QUANTIDADE
    FROM {{ ref('tab_shipment_ctms_oc_stg') }} AS CTMS
    INNER JOIN {{ ref('item_master') }} AS I ON CTMS.COD_ITEM = I.ITEM
    WHERE
        COALESCE(CTMS.LOAD, '') != ''
        AND (CTMS.TIPO_OPERACAO = 'FBZ')
    GROUP BY
        1, 2, 3, 4, 5, 6, 7, 8, 9
),

SHIPMENT_STATUS_LOAD AS (
    SELECT -- noqa
        CONCAT(
            COALESCE(LJ.LOAD, 'N/A'), '-',
            COALESCE(
                CASE
                    WHEN FC.STATUS_FICHA != 'FICHA APLICADA'
                        THEN COALESCE(
                            CTR_INVOICE.CONTRACTNUMBER,
                            NULLIF(CTR_FC.CONTRACTNUMBER, 'N/A'),
                            CTR_LJ.CONTRACTNUMBER
                        )
                    ELSE
                        COALESCE(CTR_FC.CONTRACTNUMBER, CTR_LJ.CONTRACTNUMBER)
                END,
                'N/A'
            ), '-',
            COALESCE(FC.FICHA, 'N/A'), '-',
            COALESCE(
                LJ.ADDRESS_COLETA, FC.ADDRESS_FAZENDA, LJ.BP_ORIGEM, 'N/A'
            ), '-',
            COALESCE(FC.ADDRESS_FAZENDA, 'N/A')
        ) AS SHIP_BK,
        LJ.CODIGO_PRODUTO AS ITEMID,
        LJ.U_M_PRODUTO AS UOM,
        LJ.LOTID,
        UPPER(TRIM(LJ.STATUS_LOAD)) AS STATUS_LOAD,
        LJ.DATA_EMISSAO_NF,
        LJ.DT_RECEPCAO_JDE,
        LJ.DATA_CONFIRMACAO_CARREGAMENTO,
        LJ.DATA_PROGRAMADA_CARREGAMENTO,
        MAX(
            CASE
                WHEN LJ.NF_STATUS IN ('994', '998') THEN 0
                ELSE LJ.VOLUME_TRANSPORTADO
            END
        ) AS VOLUME_TRANSPORTADO,
        MAX(
            CASE
                WHEN LJ.NF_STATUS IN ('994', '998') THEN 0
                ELSE LJ.VOL_BALANCA
            END
        ) AS VOL_BALANCA,
        MAX(
            CASE
                WHEN LJ.NF_STATUS IN ('994', '998') THEN 0
                ELSE LJ.VOL_NF
            END
        ) AS VOL_NF,
        LJ.SINISTRO
    FROM {{ ref('tab_shipment_load_intransit_stg') }} AS LJ
    INNER JOIN {{ ref('item_master') }} AS I ON LJ.CODIGO_PRODUTO = I.ITEM
    LEFT JOIN {{ ref('tab_shipment_ficha_intransit_stg') }} AS FC
        ON
            LJ.LOAD = FC.LOAD_NUMBER
    LEFT JOIN {{ ref('tab_sourcing_contract_internal_stg') }} AS CTR_LJ
        ON LJ.CONTRATO_ORIGINACAO = CTR_LJ.CONTRACTNUMBER
    LEFT JOIN {{ ref('tab_sourcing_contract_internal_stg') }} AS CTR_FC
        ON FC.CONTRATO_ORIGINACAO = CTR_FC.CONTRACTNUMBER
    LEFT JOIN {{ ref('tab_shipment_invoice_and_contracts_stg') }} AS CTR_INVOICE
        ON FC.ID_NF = CTR_INVOICE.INVOICE_KEY
    WHERE LJ.TIPO_DE_OPERACAO = 'FBZ' -- noqa
        AND COALESCE(LJ.LOAD, '') != ''
    GROUP BY
        1, 2, 3, 4, 5, 6, 7, 8, 9, 13
),

SHIPMENT_STATUS_FICHA AS (
    SELECT -- noqa
        CONCAT(
            COALESCE(FC.LOAD_NUMBER, FC.FICHA, 'N/A'), '-',
            COALESCE(
                CASE
                    WHEN FC.STATUS_FICHA != 'FICHA APLICADA'
                        THEN COALESCE(
                            CTR_INVOICE.CONTRACTNUMBER,
                            NULLIF(CTR_FC.CONTRACTNUMBER, 'N/A'),
                            CTR_LD.CONTRACTNUMBER
                        )
                    ELSE
                        COALESCE(CTR_FC.CONTRACTNUMBER, CTR_LD.CONTRACTNUMBER)
                END,
                'N/A'
            ), '-',
            COALESCE(FC.FICHA, 'N/A'), '-',
            COALESCE(LD.ADDRESS_COLETA, FC.ADDRESS_FAZENDA, 'N/A'), '-',
            COALESCE(FC.ADDRESS_FAZENDA, 'N/A')
        ) AS SHIP_BK,
        FC.CODIGO_PRODUTO AS ITEMID,
        FC.UOM,
        UPPER(TRIM(FC.STATUS_FICHA)) AS STATUS_FICHA,
        FC.DATA_APLICACAO_FICHA,
        FC.DATA_CRIACAO_FICHA,
        FC.DATA_EMISSAO_NF,
        MAX(FC.LOTID) AS LOTID,
        SUM(FC.VOL_NF) AS VOL_NF,
        MAX(FC.VOLUME_TRANSPORTADO) AS VOLUME_TRANSPORTADO,
        SUM(FC.VOL_BALANCA) AS VOL_BALANCA,
        SUM(IFF(LD.VOL_NF = 0, FC.VOL_BALANCA, ROUND(LD.VOL_BALANCA * FC.VOL_BALANCA / LD.VOL_NF, 0))) AS VOL_BALANCA_PROP, -- noqa
        LD.SINISTRO
    FROM {{ ref('tab_shipment_ficha_intransit_stg') }} AS FC -- noqa
    INNER JOIN {{ ref('item_master') }} AS I ON FC.CODIGO_PRODUTO = I.ITEM
    LEFT JOIN {{ ref('tab_shipment_load_intransit_stg') }} AS LD
        ON FC.LOAD_NUMBER = LD.LOAD
    LEFT JOIN {{ ref('tab_sourcing_contract_internal_stg') }} AS CTR_LD
        ON LD.CONTRATO_ORIGINACAO = CTR_LD.CONTRACTNUMBER
    LEFT JOIN {{ ref('tab_sourcing_contract_internal_stg') }} AS CTR_FC
        ON FC.CONTRATO_ORIGINACAO = CTR_FC.CONTRACTNUMBER
    LEFT JOIN {{ ref('tab_shipment_invoice_and_contracts_stg') }} AS CTR_INVOICE
        ON FC.ID_NF = CTR_INVOICE.INVOICE_KEY
    GROUP BY
        1, 2, 3, 4, 5, 6, 7, 13
),

SHIPMENT_STATUS_RDS AS (
    SELECT DISTINCT
        RDS.LOTID,
        RDS.LOADE1,
        RDS.FICHAJDE,
        RDS.IDOPERACAOFINALIDADE,
        RDS.CODIGOLONGOPRODUTO,
        RDS.QUANTIDADEPRODUTO,
        RDS.PESOSECORATEIO,
        RDS.PESOESTIMADO,
        RDS.DATAHORACHEGADA,
        RDS.DATAHORASAIDA,
        RDS.DATAHORASEGUNDAPESAGEM,
        RDS.UNIDADEMEDIDA
    FROM {{ source('rds', 'VW_RDS_HISTORIC_DCT') }} AS RDS
    INNER JOIN {{ ref('item_master') }} AS I ON RDS.CODIGOLONGOPRODUTO = I.ITEM
),

ALL_STATUS_DATA_PART1 AS (
    SELECT -- noqa
        S.ID AS SHIPMENTID,
        S.SHIP_BK,
        COALESCE(C.ITEMID, S.ITEMID) AS ITEMID,
        S.PROPORTION,
        C.UOM AS UOM_CTMS,
        C.DATA_EMISSAO_OC AS DT_EMISSAO_OC,
        C.DATA_PREV_COLETA AS DT_PREV_COLETA,
        C.DATA_NF AS DT_NF,
        C.DATA_VALIDACAO_QRCODE AS DT_QRCODE,
        C.DATA_ENTREGA AS DT_ENTREGA,
        C.STATUS_OC AS STATUS_CTMS,
        C.QUANTIDADE AS QUANTIDADE_CTMS
    FROM SHIPMENT_STATUS_FBZ AS S
    LEFT JOIN SHIPMENT_STATUS_CTMS AS C ON S.BK_FBZ = C.BK_FBZ
),

ALL_STATUS_DATA_PART2 AS (
    SELECT -- noqa
        S.SHIPMENTID,
        COALESCE(C.ITEMID, S.ITEMID) AS ITEMID,
        S.SHIP_BK,
        S.PROPORTION,
        S.DT_EMISSAO_OC,
        S.DT_PREV_COLETA,
        S.DT_NF,
        S.DT_QRCODE,
        S.DT_ENTREGA,
        S.STATUS_CTMS,
        S.QUANTIDADE_CTMS,
        S.UOM_CTMS,
        C.UOM AS UOM_LOAD,
        C.LOTID AS LOTID_LOAD,
        C.STATUS_LOAD,
        C.DT_RECEPCAO_JDE,
        C.DATA_EMISSAO_NF AS DT_EMISSAO_NF_LOAD,
        C.DATA_CONFIRMACAO_CARREGAMENTO AS DT_CONFIRMACAO_LOAD,
        C.DATA_PROGRAMADA_CARREGAMENTO AS DT_PROGRAMADA_LOAD,
        C.VOLUME_TRANSPORTADO AS VL_TRANSPORTADO_LOAD,
        C.VOL_NF AS VL_NF_LOAD,
        C.VOL_BALANCA AS VL_BALANCA_LOAD,
        C.SINISTRO
    FROM ALL_STATUS_DATA_PART1 AS S
    LEFT JOIN SHIPMENT_STATUS_LOAD AS C
        ON
            S.SHIP_BK = C.SHIP_BK
            AND S.ITEMID = C.ITEMID
),

ALL_STATUS_DATA_FINAL AS (
    SELECT -- noqa
        S.SHIPMENTID,
        COALESCE(C.ITEMID, S.ITEMID) AS ITEMID,
        S.SHIP_BK,
        S.PROPORTION,
        S.DT_EMISSAO_OC,
        S.DT_PREV_COLETA,
        S.DT_NF AS DT_EMISSAO_NF_CTMS,
        S.DT_QRCODE,
        S.DT_ENTREGA,
        S.STATUS_CTMS,
        S.QUANTIDADE_CTMS,
        S.UOM_CTMS,
        S.UOM_LOAD,
        S.LOTID_LOAD,
        S.STATUS_LOAD,
        S.DT_RECEPCAO_JDE,
        S.DT_EMISSAO_NF_LOAD,
        S.DT_CONFIRMACAO_LOAD,
        S.DT_PROGRAMADA_LOAD,
        S.VL_TRANSPORTADO_LOAD,
        S.VL_NF_LOAD,
        S.VL_BALANCA_LOAD,
        C.LOTID AS LOTID_FICHA,
        C.UOM AS UOM_FICHA,
        C.STATUS_FICHA,
        C.DATA_APLICACAO_FICHA AS DT_APLICACAO_FICHA,
        C.DATA_CRIACAO_FICHA AS DT_CRIACAO_FICHA,
        C.VOLUME_TRANSPORTADO AS VL_TRANSPORTADO,
        C.DATA_EMISSAO_NF AS DT_EMISSAO_NF_FICHA,
        C.VOL_NF AS VOL_NF_FICHA,
        C.VOL_BALANCA AS VOL_BALANCA_FICHA,
        C.VOL_BALANCA_PROP AS VOL_BALANCA_PROP_LOAD_FICHA,
        C.SINISTRO
    FROM ALL_STATUS_DATA_PART2 AS S
    LEFT JOIN SHIPMENT_STATUS_FICHA AS C
        ON
            S.SHIP_BK = C.SHIP_BK
            AND S.ITEMID = C.ITEMID
            AND C.STATUS_FICHA != 'FICHA CANCELADA'
),

/* QUERIES PARA CADA STATUS DO SHIPMENT */
SHIPMENT_STATUS_CANCELLED AS (
    /* ATUALIZA SHIPMENTS BASEADOS NOS STATUS CANCELADO */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'CANCELLED' AS "STATUS",
        COALESCE(
            ALL_DATA.DT_PREV_COLETA,
            ALL_DATA.DT_PROGRAMADA_LOAD,
            ALL_DATA.DT_CRIACAO_FICHA
        ) AS REFERENCEDATE,
        COALESCE(
            ALL_DATA.UOM_CTMS,
            ALL_DATA.UOM_LOAD,
            ALL_DATA.UOM_FICHA
        ) AS UOM,
        COALESCE(
            ALL_DATA.VOL_BALANCA_FICHA,
            ALL_DATA.VL_NF_LOAD,
            ALL_DATA.QUANTIDADE_CTMS
        ) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (
            ALL_DATA.DT_EMISSAO_OC IS NOT NULL
            OR ALL_DATA.DT_PROGRAMADA_LOAD IS NOT NULL
            OR ALL_DATA.DT_CRIACAO_FICHA IS NOT NULL)  -- noqa
        AND (
            ALL_DATA.STATUS_CTMS = 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD = 'LOAD CANCELADO'
            OR ALL_DATA.STATUS_FICHA = 'FICHA CANCELADA'
            OR ALL_DATA.SINISTRO = 'TRUE')  -- noqa
),

SHIPMENT_STATUS_SINISTRO AS (
    /* ATUALIZA SHIPMENTS BASEADOS NOS STATUS CANCELADO */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'SINISTRO' AS "STATUS",
        COALESCE(
            ALL_DATA.DT_PREV_COLETA,
            ALL_DATA.DT_PROGRAMADA_LOAD,
            ALL_DATA.DT_CRIACAO_FICHA
        ) AS REFERENCEDATE,
        COALESCE(
            ALL_DATA.UOM_CTMS,
            ALL_DATA.UOM_LOAD,
            ALL_DATA.UOM_FICHA
        ) AS UOM,
        COALESCE(
            ALL_DATA.VOL_BALANCA_FICHA,
            ALL_DATA.VL_NF_LOAD,
            ALL_DATA.QUANTIDADE_CTMS
        ) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        1 = 1
        AND ALL_DATA.SINISTRO = 'TRUE'
),

SHIPMENT_STATUS_LOADING_ORDER AS (
    /*
        ATUALIZA SHIPMENTS BASEADOS NO STATUS DIFERENTE DE CANCELADO
        SE FOI FINALIZADO... FOI PLANEJADO, EM TESE
    */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'LOADING ORDER' AS "STATUS",
        CASE
            WHEN IT.L2 = 'GRAOS'
                THEN ALL_DATA.DT_PREV_COLETA
            ELSE
                COALESCE(
                    ALL_DATA.DT_PROGRAMADA_LOAD,
                    ALL_DATA.DT_PREV_COLETA
                )
        END AS REFERENCEDATE,
        ALL_DATA.UOM_CTMS AS UOM,
        ALL_DATA.QUANTIDADE_CTMS * ALL_DATA.PROPORTION AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    INNER JOIN {{ ref('item_master') }} AS IT
        ON IT.ITEM = ALL_DATA.ITEMID
    WHERE
        (
            ALL_DATA.DT_PREV_COLETA IS NOT NULL
            OR ALL_DATA.DT_PROGRAMADA_LOAD IS NOT NULL
        )
        AND COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
),

SHIPMENT_STATUS_INVOICE AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA EMISSAO DA NOTA FISCAL */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'INVOICE' AS "STATUS",
        COALESCE(
            ALL_DATA.DT_EMISSAO_NF_FICHA,
            ALL_DATA.DT_EMISSAO_NF_LOAD,
            ALL_DATA.DT_EMISSAO_NF_CTMS
        ) AS REFERENCEDATE,
        COALESCE(
            ALL_DATA.UOM_CTMS,
            ALL_DATA.UOM_LOAD,
            ALL_DATA.UOM_FICHA
        ) AS UOM,
        COALESCE(
            ALL_DATA.VOL_BALANCA_FICHA,
            ALL_DATA.VL_NF_LOAD,
            ALL_DATA.QUANTIDADE_CTMS
        ) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (
            ALL_DATA.DT_EMISSAO_NF_LOAD IS NOT NULL
            OR ALL_DATA.DT_EMISSAO_NF_CTMS IS NOT NULL
            OR ALL_DATA.DT_EMISSAO_NF_FICHA IS NOT NULL
        )
        AND (
            COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD != 'LOAD CANCELADO'
            OR ALL_DATA.STATUS_FICHA != 'FICHA CANCELADA')  -- noqa
),

SHIPMENT_STATUS_IN_SOURCE AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA DE VALIDACAO DO QRCODE */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'IN SOURCE' AS "STATUS",
        ALL_DATA.DT_QRCODE AS REFERENCEDATE,
        ALL_DATA.UOM_CTMS AS UOM,
        ALL_DATA.QUANTIDADE_CTMS * ALL_DATA.PROPORTION AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (ALL_DATA.DT_QRCODE IS NOT NULL)
        AND (
            COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD != 'LOAD CANCELADO'
            OR ALL_DATA.STATUS_FICHA != 'FICHA CANCELADA')  -- noqa
),

SHIPMENT_STATUS_IN_DESTINATION AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA DE CHEGADA NA LOCALIDADE */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'IN DESTINATION' AS "STATUS",
        RDS.DATAHORACHEGADA AS REFERENCEDATE,
        RDS.UNIDADEMEDIDA,
        SUM(RDS.QUANTIDADEPRODUTO * ALL_DATA.PROPORTION) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    INNER JOIN SHIPMENT_STATUS_RDS AS RDS
        ON ALL_DATA.LOTID_LOAD = RDS.LOTID
    WHERE
        RDS.DATAHORACHEGADA IS NOT NULL
        AND (
            COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD != 'LOAD CANCELADO'
            OR ALL_DATA.STATUS_FICHA != 'FICHA CANCELADA')  -- noqa
    GROUP BY
        1, 2, 3, 4, 5, 6

    UNION DISTINCT

    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'IN DESTINATION' AS "STATUS",
        RDS.DATAHORACHEGADA AS REFERENCEDATE,
        RDS.UNIDADEMEDIDA,
        SUM(RDS.QUANTIDADEPRODUTO * ALL_DATA.PROPORTION) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    INNER JOIN SHIPMENT_STATUS_RDS AS RDS
        ON ALL_DATA.LOTID_FICHA = RDS.LOTID
    WHERE
        RDS.DATAHORACHEGADA IS NOT NULL
        AND (
            COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD != 'LOAD CANCELADO'
            OR ALL_DATA.STATUS_FICHA != 'FICHA CANCELADA')  -- noqa
    GROUP BY
        1, 2, 3, 4, 5, 6
),

SHIPMENT_STATUS_UNLOADED AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA DA SAIDA DA LOCALIDADE */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'UNLOADED' AS "STATUS",
        COALESCE(
            RDS.DATAHORASAIDA, RDS.DATAHORASEGUNDAPESAGEM
        ) AS REFERENCEDATE,
        RDS.UNIDADEMEDIDA,
        SUM(RDS.QUANTIDADEPRODUTO * ALL_DATA.PROPORTION) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    INNER JOIN SHIPMENT_STATUS_RDS AS RDS
        ON ALL_DATA.LOTID_LOAD = RDS.LOTID
    WHERE
        (RDS.DATAHORASAIDA IS NOT NULL OR RDS.DATAHORASEGUNDAPESAGEM IS NOT NULL)  -- noqa
        AND (
            COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD != 'LOAD CANCELADO'
            OR ALL_DATA.STATUS_FICHA != 'FICHA CANCELADA')  -- noqa
    GROUP BY
        1, 2, 3, 4, 5, 6

    UNION DISTINCT

    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'UNLOADED' AS "STATUS",
        COALESCE(
            RDS.DATAHORASAIDA, RDS.DATAHORASEGUNDAPESAGEM
        ) AS REFERENCEDATE,
        RDS.UNIDADEMEDIDA,
        AVG(RDS.PESOSECORATEIO * ALL_DATA.PROPORTION) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    INNER JOIN SHIPMENT_STATUS_RDS AS RDS
        ON ALL_DATA.LOTID_FICHA = RDS.LOTID
    WHERE
        (RDS.DATAHORASAIDA IS NOT NULL OR RDS.DATAHORASEGUNDAPESAGEM IS NOT NULL)  -- noqa
        AND (
            COALESCE(ALL_DATA.STATUS_CTMS, '') != 'OC CANCELADA'
            OR ALL_DATA.STATUS_LOAD != 'LOAD CANCELADO'
            OR ALL_DATA.STATUS_FICHA != 'FICHA CANCELADA')  -- noqa
    GROUP BY
        1, 2, 3, 4, 5, 6
),

SHIPMENT_STATUS_FINISHED AS (
    /* ATUALIZA SHIPMENTS BASEADOS NA DATA APLICACAO DA FICHA / LOAD */
    SELECT -- noqa
        ALL_DATA.SHIPMENTID,
        ALL_DATA.SHIP_BK,
        ALL_DATA.ITEMID,
        'FINISHED' AS "STATUS",
        COALESCE(
            ALL_DATA.DT_APLICACAO_FICHA,
            ALL_DATA.DT_RECEPCAO_JDE,
            ALL_DATA.DT_ENTREGA
        ) AS REFERENCEDATE,
        COALESCE(
            ALL_DATA.UOM_FICHA,
            ALL_DATA.UOM_LOAD,
            ALL_DATA.UOM_CTMS
        ) AS UOM,
        COALESCE(
            ALL_DATA.VOL_BALANCA_PROP_LOAD_FICHA,
            --ALL_DATA.VOL_BALANCA_FICHA,
            ALL_DATA.VL_BALANCA_LOAD,
            ALL_DATA.QUANTIDADE_CTMS
        ) AS QUANTITY
    FROM ALL_STATUS_DATA_FINAL AS ALL_DATA
    WHERE
        (ALL_DATA.DT_APLICACAO_FICHA IS NOT NULL OR ALL_DATA.DT_ENTREGA IS NOT NULL OR ALL_DATA.DT_RECEPCAO_JDE IS NOT NULL)  -- noqa
        AND (
            ALL_DATA.STATUS_CTMS = 'OC DESCARREGADA'
            OR ALL_DATA.STATUS_LOAD IN ('LOAD ENVIADO AO CTMS', 'LOAD CONFIRMADO')  -- noqa
            OR ALL_DATA.STATUS_FICHA = 'FICHA APLICADA')  -- noqa
),
/* QUERIES FINAIS */

SHIPMENT_STATUS AS (
    SELECT * FROM SHIPMENT_STATUS_CANCELLED
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_LOADING_ORDER
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_IN_SOURCE
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_INVOICE
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_IN_DESTINATION
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_UNLOADED
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_FINISHED
    UNION DISTINCT
    SELECT * FROM SHIPMENT_STATUS_SINISTRO
),

SHIPMENT_STATUS_FINAL AS (
    SELECT DISTINCT
        SHIPMENTID,
        STATUS,
        REFERENCEDATE,
        QUANTITY,
        ITEMID,
        UOM,
        SHIP_BK AS BK
    FROM SHIPMENT_STATUS
)

SELECT -- noqa
    ST.SHIPMENTID,
    ST.STATUS,
    TO_CHAR(ST.REFERENCEDATE, 'DD-MM-YYYY') AS REFERENCEDATE,
    ST.QUANTITY,
    ST.ITEMID,
    ST.UOM,
    ST.BK
FROM SHIPMENT_STATUS_FINAL AS ST
INNER JOIN {{ ref('item_master') }} AS I
    ON ST.ITEMID = I.ITEM
