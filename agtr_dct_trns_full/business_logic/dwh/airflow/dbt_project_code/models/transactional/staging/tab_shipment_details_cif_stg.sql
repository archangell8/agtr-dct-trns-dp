-- ATUALIZA SHIPMENT BASEADO NOS DADOS DO NEOGRID - NOTA FISCAL EMITIDA
-- E CONTRATO DE ORIGINACAO
SHIPMENT_CORE_PART2 AS (
    SELECT DISTINCT
        SHIP.SHIP_BK,
        SHIP.DOCTYPE,
        SHIP.LOADNUMBER,
        NEO.PURCHASE_CODE AS FICHANUMBER,
        NEO.SOURCINGCONTRACTID,
        NEO.CARRIER,
        NEO.PLATE AS VEHICLEID,
        NEO.INVOICE_ISSUANCE_DATE::TIMESTAMP AS ESTIMATEDSHIPDATE,
        NEO.INVOICE_ISSUANCE_DATE::TIMESTAMP AS ACTUALSHIPDATE,
        SHIP.SCHEDULEDDATE,
        SHIP.ARRIVALDATE,
        SHIP.ESTIMATEDDELIVERYDATE,
        SHIP.ACTUALDELIVERYDATE,
        SHIP.CONTRACT_NUMBER_APPLIED,
        SHIP.LOADAPPLICATIONDATE,
        NEO.CONTRACT_INFO_NF,
        SHIP.LOTEID,
        NEO.ITEMID,
        NEO.UOM,
        NEO.CURRENCY,
        NEO.QUANTITY,
        SHIP.QUALITY_ADJUSTMENT,
        COALESCE(
            NEO.FREIGHT_TYPE, SHIP.OPERATIONTYPE
        ) AS OPERATIONTYPE,
        COALESCE(
            NEO.BP_ORIGEM, SHIP.SOURCE
        ) AS SOURCE,
        COALESCE(
            NEO.BP_NEGOCIACAO, SHIP.SOURCEBP
        ) AS SOURCEBP,
        COALESCE(
            UDC_NEOGRID_DESTINO.TARGET_CODE, NEO.BP_DESTINO, SHIP.DESTINATION
        ) AS DESTINATION,
        COALESCE(
            SHIP.DOCNUMBER, NEO.DOCNUMBER
        ) AS DOCNUMBER,
        COALESCE(
            NEO.INVOICE_ISSUANCE_DATE::TIMESTAMP, SHIP.DOCCREATEDATE::TIMESTAMP
        ) AS DOCCREATEDATE,
        COALESCE(NEO.TRANSMODE, 'ROD') AS TRANSMODE,
        COALESCE(
            FINALDEST.FINALDESTINATION,
            UDC_NEOGRID_DESTINO.TARGET_CODE,
            NEO.FINALDESTINATION
        ) AS FINALDESTINATION
    FROM SHIPMENT_CORE_PART1 AS SHIP
    LEFT JOIN SHIPMENT_NEOGRID AS NEO
        ON NEO.BK_CIF = SHIP.BK_CIF
        --ON NEO.SHIP_BK = SHIP.SHIP_BK
    LEFT JOIN {{ ref('tab_sourcing_contract_internal_stg') }} AS CTR
        ON CTR.ID = NEO.SOURCINGCONTRACTID
    LEFT JOIN UDC AS UDC_NEOGRID_DESTINO
        ON
            UDC_NEOGRID_DESTINO.CATEGORY = 'SHIPMENT'
            AND UDC_NEOGRID_DESTINO.STAGE = 'NEOGRID_DESTINO'
            AND UDC_NEOGRID_DESTINO.SOURCE_CODE = NEO.BP_DESTINO
    LEFT JOIN NEOGRID_FINALDESTINATION AS FINALDEST
        ON NEO.CONTRACTNUMBER = FINALDEST.CONTRATO_ORIGINACAO
),

-- ATUALIZA AS INFORMAÇÕES DO SHIPMENT EM FUNÇÃO DA APLICAÇÃO DA FICHA
SHIPMENT_CORE_PART3 AS (
    SELECT
        SHIP.SHIP_BK,
        SHIP.DOCTYPE,
        SHIP.SCHEDULEDDATE,
        SHIP.ESTIMATEDDELIVERYDATE,
        SHIP.CONTRACT_INFO_NF,
        JDE.PRICETYPE,
        JDE.LINENUMBER,
        COALESCE(JDE.OPERATIONTYPE, SHIP.OPERATIONTYPE) AS OPERATIONTYPE,
        COALESCE(JDE.SOURCE, SHIP.SOURCE) AS SOURCE,
        COALESCE(JDE.SOURCEBP, SHIP.SOURCEBP) AS SOURCEBP,
        COALESCE(JDE.DESTINATION, SHIP.DESTINATION) AS DESTINATION,
        COALESCE(SHIP.DOCNUMBER, JDE.BK_CIF) AS DOCNUMBER,
        COALESCE(JDE.LOADNUMBER, SHIP.LOADNUMBER) AS LOADNUMBER,
        COALESCE(JDE.FICHANUMBER, SHIP.FICHANUMBER) AS FICHANUMBER,
        COALESCE(SHIP.DOCCREATEDATE, JDE.ESTIMATEDSHIPDATE) AS DOCCREATEDATE,
        COALESCE(
            JDE.SOURCINGCONTRACTID, SHIP.SOURCINGCONTRACTID
        ) AS SOURCINGCONTRACTID,
        COALESCE(JDE.TRANSMODE, SHIP.TRANSMODE) AS TRANSMODE,
        COALESCE(JDE.CARRIER, SHIP.CARRIER) AS CARRIER,
        COALESCE(JDE.VEHICLEID, SHIP.VEHICLEID) AS VEHICLEID,
        COALESCE(
            JDE.ESTIMATEDSHIPDATE, SHIP.ESTIMATEDSHIPDATE
        ) AS ESTIMATEDSHIPDATE,
        COALESCE(JDE.ACTUALSHIPDATE, SHIP.ACTUALSHIPDATE) AS ACTUALSHIPDATE,
        COALESCE(JDE.ARRIVALDATE, SHIP.ARRIVALDATE) AS ARRIVALDATE,
        COALESCE(
            JDE.ACTUALDELIVERYDATE, SHIP.ACTUALDELIVERYDATE
        ) AS ACTUALDELIVERYDATE,
        COALESCE(
            JDE.CONTRACT_NUMBER_APPLIED, SHIP.CONTRACT_NUMBER_APPLIED
        ) AS CONTRACT_NUMBER_APPLIED,
        COALESCE(
            JDE.LOADAPPLICATIONDATE, SHIP.LOADAPPLICATIONDATE
        ) AS LOADAPPLICATIONDATE,
        COALESCE(JDE.LOTID, SHIP.LOTEID) AS LOTEID,
        COALESCE(
            JDE.FINALDESTINATION, SHIP.FINALDESTINATION
        ) AS FINALDESTINATION,
        COALESCE(JDE.ITEMID, SHIP.ITEMID) AS ITEMID,
        COALESCE(JDE.UOM, SHIP.UOM) AS UOM,
        COALESCE(JDE.CURRENCY, SHIP.CURRENCY) AS CURRENCY,
        COALESCE(
            IFF(COALESCE(JDE.VOL_BALANCA, 0) = 0, JDE.VOL_NF, JDE.VOL_BALANCA),
            SHIP.QUANTITY,
            0
        ) AS QUANTITY,
        COALESCE(
            JDE.QUALITY_ADJUSTMENT, SHIP.QUALITY_ADJUSTMENT
        ) AS QUALITY_ADJUSTMENT
    FROM SHIPMENT_CORE_PART2 AS SHIP
    LEFT JOIN SHIPMENT_FICHA AS JDE
        ON SHIP.SHIP_BK = JDE.SHIP_BK
),

-- ATUALIZA INFORMAÇÕES COM BASE NO ECOPATIO E MASS BALANCE
SHIPMENT_CORE_PART4 AS (
    SELECT DISTINCT
        NULL AS ID,
        SHIP.SHIP_BK AS BK,
        SHIP.OPERATIONTYPE,
        SHIP.DOCTYPE,
        SHIP.DOCNUMBER,
        SHIP.DOCCREATEDATE,
        NULL AS DATA_ENTREGA,
        NULL AS ID_PEDIDO,
        0 AS PALLETQUANTITY,
        'N/A' AS PALLET,
        'N/A' AS PROFILE,
        SHIP.LINENUMBER,
        SHIP.ITEMID,
        0.0000 AS PLANNEDCOST,
        0.0000 AS ACTUALCOST,
        0.0000 AS PENALTYCOST,
        SHIP.UOM,
        SHIP.CURRENCY,
        COALESCE(SHIP.QUANTITY, 0) AS QUANTITY,
        COALESCE(SHIP.QUALITY_ADJUSTMENT, 0) AS QUALITY_ADJUSTMENT,
        COALESCE(SHIP.SOURCE, 'N/A') AS SOURCE,
        COALESCE(SHIP.SOURCEBP, 'N/A') AS SOURCEBP,
        COALESCE(SHIP.DESTINATION, 'N/A') AS DESTINATION,
        COALESCE(SHIP.LOADNUMBER, SHIP.FICHANUMBER, 'N/A') AS LOADNUMBER,
        COALESCE(SHIP.FICHANUMBER, 'N/A') AS FICHANUMBER,
        COALESCE(SHIP.SOURCINGCONTRACTID, 'N/A') AS SOURCINGCONTRACTID,
        CONCAT(
            SPLIT_PART(SHIP.SOURCINGCONTRACTID, '-', 1),
            '-',
            SPLIT_PART(SHIP.SOURCINGCONTRACTID, '-', 2),
            '-',
            LOC.LOCATION_CODE
        ) AS SOURCINGCONTRACTID_DESTINATION,
        COALESCE(SHIP.TRANSMODE, 'N/A') AS TRANSMODE,
        /* Estudo realizado para unir os shipments com IBP */
        COALESCE(SHIP.CARRIER, '37234268 - TRANSPORTE PROPRIO') AS CARRIER,
        COALESCE(SHIP.VEHICLEID, 'N/A') AS VEHICLEID,
        TO_CHAR(
            SHIP.ESTIMATEDSHIPDATE::TIMESTAMP, 'DD-MM-YYYY'
        ) AS ESTIMATEDSHIPDATE,
        TO_CHAR(
            SHIP.ACTUALSHIPDATE::TIMESTAMP, 'DD-MM-YYYY HH24:MI:SS'
        ) AS ACTUALSHIPDATE,
        COALESCE(
            TO_CHAR(TO_TIMESTAMP(
                ES.SCHEDULE_DATE, 'DD/MM/YYYY HH24:MI:SS'
            ), 'DD-MM-YYYY HH24:MI:SS'),
            SHIP.SCHEDULEDDATE,
            'N/A'
        ) AS SCHEDULEDDATE,
        COALESCE(
            TO_CHAR(SHIP.ARRIVALDATE::TIMESTAMP, 'DD-MM-YYYY'),
            'N/A'
        ) AS ARRIVALDATE,
        COALESCE(
            TO_CHAR(SHIP.ESTIMATEDDELIVERYDATE::TIMESTAMP, 'DD-MM-YYYY'),
            'N/A'
        ) AS ESTIMATEDDELIVERYDATE,
        COALESCE(
            TO_CHAR(SHIP.ACTUALDELIVERYDATE::TIMESTAMP, 'DD-MM-YYYY HH24:MI:SS'),
            'N/A'
        ) AS ACTUALDELIVERYDATE,
        COALESCE(
            SHIP.CONTRACT_NUMBER_APPLIED, 'N/A'
        ) AS CONTRACT_NUMBER_APPLIED,
        COALESCE(
            TO_CHAR(SHIP.LOADAPPLICATIONDATE::TIMESTAMP, 'DD-MM-YYYY'),
            'N/A'
        ) AS LOADAPPLICATIONDATE,
        COALESCE(SHIP.CONTRACT_INFO_NF, 'N/A') AS CONTRACT_INFO_NF,
        COALESCE(SHIP.LOTEID, 'N/A') AS LOTEID,
        COALESCE(
            MB.PORT_LOCATION, SHIP.FINALDESTINATION, SHIP.DESTINATION, 'N/A'
        ) AS FINALDESTINATION,
        COALESCE(SHIP.PRICETYPE, 'N/A') AS PRICETYPE
    FROM SHIPMENT_CORE_PART3 AS SHIP
    LEFT JOIN ECOPATIO_STATUS AS ES
        ON REPLACE(ES.TRUCK_PLATE, '-', '') = SHIP.VEHICLEID
            AND SPLIT_PART(SHIP.DOCNUMBER, '-', 0) = ES.INVOICE_NUMBER
    LEFT JOIN MASS_BALANCE_CROP_SEASON AS MB
        ON SHIP.FICHANUMBER = MB.PURCHASE_CODE::STRING
    LEFT JOIN {{ ref('tab_location_internal_stg') }} AS LOC
        ON SHIP.FINALDESTINATION = LOC.LOCATIONID
    WHERE SHIP.OPERATIONTYPE IN (
        'CIF', 'FOB_NEOGRID', 'CIF_NEOGRID', 'FOB_CTE', 'CIF_CTE'
    )
),

-- ATUALIZA INFORMAÇÕES DE CONTRATO COM BASE NO FINAL DESTINATION CORRETO
SHIPMENT_FINAL AS (
    SELECT DISTINCT
        SHIP.ID,
        SHIP.BK,
        SHIP.OPERATIONTYPE,
        SHIP.SOURCE,
        SHIP.SOURCEBP,
        SHIP.DESTINATION,
        SHIP.DOCTYPE,
        SHIP.DOCNUMBER,
        SHIP.LOADNUMBER,
        SHIP.FICHANUMBER,
        COALESCE(CTR_1.ID, CTR_2.ID, 'N/A') AS SOURCINGCONTRACTID,
        SHIP.TRANSMODE,
        SHIP.CARRIER,
        SHIP.CONTRACT_NUMBER_APPLIED,
        SHIP.CONTRACT_INFO_NF,
        SHIP.LOTEID,
        SHIP.DATA_ENTREGA,
        SHIP.ID_PEDIDO,
        SHIP.FINALDESTINATION,
        SHIP.PRICETYPE,
        SHIP.PALLETQUANTITY,
        SHIP.PALLET,
        SHIP.PROFILE,
        SHIP.LINENUMBER,
        SHIP.ITEMID,
        SHIP.PLANNEDCOST,
        SHIP.ACTUALCOST,
        SHIP.PENALTYCOST,
        SHIP.QUANTITY,
        SHIP.QUALITY_ADJUSTMENT,
        SHIP.UOM,
        SHIP.CURRENCY,
        MAX(SHIP.VEHICLEID) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.VEHICLEID DESC
        ) AS VEHICLEID,
        MAX(SHIP.DOCCREATEDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.DOCCREATEDATE DESC
        ) AS DOCCREATEDATE,
        MAX(SHIP.ESTIMATEDSHIPDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ESTIMATEDSHIPDATE DESC
        ) AS ESTIMATEDSHIPDATE,
        MAX(SHIP.ACTUALSHIPDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ACTUALSHIPDATE DESC
        ) AS ACTUALSHIPDATE,
        MAX(SHIP.SCHEDULEDDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.SCHEDULEDDATE DESC
        ) AS SCHEDULEDDATE,
        MAX(SHIP.ARRIVALDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ARRIVALDATE DESC
        ) AS ARRIVALDATE,
        MAX(SHIP.ESTIMATEDDELIVERYDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ESTIMATEDDELIVERYDATE DESC
        ) AS ESTIMATEDDELIVERYDATE,
        MAX(SHIP.ACTUALDELIVERYDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ACTUALDELIVERYDATE DESC
        ) AS ACTUALDELIVERYDATE,
        MAX(SHIP.LOADAPPLICATIONDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.LOADAPPLICATIONDATE DESC
        ) AS LOADAPPLICATIONDATE
    FROM SHIPMENT_CORE_PART4 AS SHIP
    LEFT JOIN {{ ref('sourcing_contract_details_master') }} AS CTR_1
        ON CTR_1.ID = SHIP.SOURCINGCONTRACTID_DESTINATION
    LEFT JOIN {{ ref('sourcing_contract_details_master') }} AS CTR_2
        ON CTR_2.ID = SHIP.SOURCINGCONTRACTID

)

SELECT DISTINCT * FROM SHIPMENT_FINAL
