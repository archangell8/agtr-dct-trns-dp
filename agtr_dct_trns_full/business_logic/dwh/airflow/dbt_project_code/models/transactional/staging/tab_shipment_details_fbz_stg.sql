        CTMS.TN,
        CTMS.ROTA,
        CTMS.DATA_PREV_COLETA,
        CTMS.DATA_EMISSAO_OC,
        CTMS.DATA_VALIDACAO_QRCODE,
        COALESCE(
            CTMS.DATA_PREV_COLETA,
            CTMS.DATA_EMISSAO_OC
        ) AS DOCCREATEDATE,
        COALESCE(
            CONCAT(CTMS.ADRESS_TRANSPORTADORA, ' - ', CTMS.NOME_TRANSPORTADORA), -- noqa
            '00000000 - TRANSPORTADORA NAO INFORMADA'
        ) AS CARRIER,
        COALESCE(
            CTMS.DATA_PREV_COLETA,
            CTMS.DATA_EMISSAO_OC
        ) AS ESTIMATEDSHIPDATE
