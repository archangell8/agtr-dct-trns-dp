    LEFT JOIN SHIPMENT_HEADER_CTMS AS CTMS
        ON CHAVE.BK_FBZ = CTMS.BK_FBZ
),

-- ATUALIZA O SHIPMENT BASEADO NO LOAD JDE
SHIPMENT_CORE_PART2 AS (
    SELECT -- noqa
        CHAVE.SHIP_BK,
        CHAVE.SCHEDULEDDATE,
        CHAVE.ESTIMATEDDELIVERYDATE,
        CHAVE.LOADAPPLICATIONDATE,
