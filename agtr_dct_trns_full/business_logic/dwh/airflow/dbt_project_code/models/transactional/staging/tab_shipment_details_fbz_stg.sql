        CHAVE.SHIP_BK,
        CTMS.OPERATIONTYPE,
        CTMS.ADRESS_COLETA AS "SOURCE",
        CTMS.BP_ORIGEM AS SOURCEBP,
        CTMS.BP_DESTINO AS DESTINATION,
