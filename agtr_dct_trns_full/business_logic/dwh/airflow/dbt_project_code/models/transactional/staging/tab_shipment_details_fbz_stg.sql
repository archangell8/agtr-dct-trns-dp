        ) AS QUANTITY,
        COALESCE(
            SHIP.VOL_DISCONTO, CHAVE.QUALITY_ADJUSTMENT
        ) AS QUALITY_ADJUSTMENT,
        COALESCE(SHIP.PLANNED_FREIGHT, CHAVE.PLANNED_FREIGHT) AS PLANNED_FREIGHT
    FROM SHIPMENT_CORE_PART2 AS CHAVE
    LEFT JOIN SHIPMENT_HEADER_FICHA AS SHIP
        ON CHAVE.SHIP_BK = SHIP.SHIP_BK
    -- LEFT JOIN RDS_HISTORIC_DCT AS RDS
    --     ON SHIP.LOTID = RDS.LOTID
    LEFT JOIN {{ ref('tab_sourcing_contract_internal_stg') }} AS CTR
        ON SHIP.CONTRATO_ORIGINACAO = CTR.CONTRACTNUMBER
    LEFT JOIN {{ ref('sourcing_contract_details_master') }} AS CTR_2
        ON CONCAT(
            SHIP.CONTRATO_ORIGINACAO, '-', SHIP.DESTINATION_CODE
        ) = CTR_2.CONTRACTNUMBER
),

SHIPMENT_CORE_PART4 AS (
    SELECT DISTINCT -- noqa
        NULL AS ID,
        S.SHIP_BK AS BK,
        S.DOCTYPE,
        S.DOCNUMBER,
        S.DOCCREATEDATE,
        NULL AS ID_PEDIDO,
        S.LINENUMBER,
        S.ITEMID,
        ACT.VALOR_FRETE_TONELADA AS ACTUALCOST,
        0.0000 AS PENALTYCOST,
        S.QUANTITY,
        S.QUALITY_ADJUSTMENT,
        S.UOM,
        S.CURRENCY,
        S.PLANNED_FREIGHT,
        S.NUMERO_OC,
        S.TN,
        S.ROTA,
        S.DATA_PREV_COLETA,
        S.DATA_EMISSAO_OC,
        S.DATA_VALIDACAO_QRCODE,
        S.DATA_EMISSAO_NF_LOAD,
        S.DATA_EMISSAO_NF_FICHA,
        COALESCE(S.OPERATIONTYPE, 'N/A') AS OPERATIONTYPE,
        COALESCE(S.SOURCE, 'N/A') AS SOURCE,
        COALESCE(S.SOURCEBP, 'N/A') AS SOURCEBP,
        COALESCE(S.DESTINATION, 'N/A') AS DESTINATION,
        COALESCE(TO_CHAR(TRUNC(S.LOADNUMBER)), 'N/A') AS LOADNUMBER,
        COALESCE(TO_CHAR(S.FICHANUMBER), 'N/A') AS FICHANUMBER,
        COALESCE(S.SOURCINGCONTRACTID, 'N/A') AS SOURCINGCONTRACTID,
        CONCAT(
            SPLIT_PART(S.SOURCINGCONTRACTID, '-', 1),
            '-',
            SPLIT_PART(S.SOURCINGCONTRACTID, '-', 2),
            '-',
            LOC.LOCATION_CODE
        ) AS SOURCINGCONTRACTID_DESTINATION,
        COALESCE(S.TRANSMODE, 'N/A') AS TRANSMODE,
        COALESCE(
            S.CARRIER, '00000000 - TRANSPORTADORA NAO INFORMADA'
        ) AS CARRIER,
        COALESCE(S.VEHICLEID, 'N/A') AS VEHICLEID,
        COALESCE(
            TO_CHAR(S.ESTIMATEDSHIPDATE, 'DD-MM-YYYY'), 'N/A'
        ) AS ESTIMATEDSHIPDATE,
        COALESCE(
            TO_CHAR(S.ACTUALSHIPDATE, 'DD-MM-YYYY HH24:MI:SS'), 'N/A'
        ) AS ACTUALSHIPDATE,
        'N/A' AS SCHEDULEDDATE,
        COALESCE(TO_CHAR(S.ARRIVALDATE, 'DD-MM-YYYY'), 'N/A') AS ARRIVALDATE,
        'N/A' AS ESTIMATEDDELIVERYDATE,
        COALESCE(
            TO_CHAR(S.ACTUALDELIVERYDATE, 'DD-MM-YYYY HH24:MI:SS'), 'N/A'
        ) AS ACTUALDELIVERYDATE,
        COALESCE(S.CONTRACT_NUMBER_APPLIED, 'N/A') AS CONTRACT_NUMBER_APPLIED,
        COALESCE(
            TO_CHAR(S.LOADAPPLICATIONDATE, 'DD-MM-YYYY'), 'N/A'
        ) AS LOADAPPLICATIONDATE,
        COALESCE(S.CONTRACT_INFO_NF, 'N/A') AS CONTRACT_INFO_NF,
        COALESCE(S.LOTEID, 'N/A') AS LOTEID,
        COALESCE(
            TO_CHAR(S.DATA_ENTREGA, 'DD-MM-YYYY HH24:MI:SS'), 'N/A'
        ) AS DATA_ENTREGA,
        COALESCE(S.FINALDESTINATION, S.DESTINATION, 'N/A') AS FINALDESTINATION,
        COALESCE(S.FINALDESTINATION_REAL, 'N/A') AS FINALDESTINATION_REAL,
        COALESCE(S.PRICETYPE, 'N/A') AS PRICETYPE,
        COALESCE(S.PALLETQUANTITY, 0) AS PALLETQUANTITY,
        COALESCE(S.PALLET, 'N/A') AS PALLET,
        COALESCE(S.PROFILE, 'N/A') AS PROFILE,
        CASE
            WHEN S.TRANSMODE = 'ROD'
                THEN COALESCE(PLN.FRETE_RODO_CONTRATO, 0)
            WHEN S.TRANSMODE != 'ROD'
                THEN COALESCE(PLN.FRETE_INTERMODAL_CONTRATO, 0)
        END AS PLANNEDCOST
    FROM SHIPMENT_CORE_PART3 AS S
    LEFT JOIN {{ ref('tab_location_internal_stg') }} AS LOC
        ON S.FINALDESTINATION = LOC.LOCATIONID
    LEFT JOIN FRETE_REALIZADO AS ACT
        ON S.LOADNUMBER = ACT.LOADNUMBER -- noqa
            AND S.ITEMID = ACT.ITEMID
    LEFT JOIN FRETE_PLANEJADO AS PLN
        ON S.SOURCINGCONTRACTID = PLN.SOURCINGCONTRACTID
    WHERE
        OPERATIONTYPE = 'FBZ'
),

SHIPMENT_FINAL AS (
    SELECT DISTINCT -- noqa
        SHIP.ID,
        SHIP.BK,
        SHIP.OPERATIONTYPE,
        SHIP.SOURCE,
        SHIP.SOURCEBP,
        SHIP.DESTINATION,
        SHIP.DOCTYPE,
        SHIP.DOCNUMBER,
        SHIP.LOADNUMBER,
        SHIP.FICHANUMBER,
        SHIP.TRANSMODE,
        SHIP.CARRIER,
        SHIP.CONTRACT_NUMBER_APPLIED,
        SHIP.CONTRACT_INFO_NF,
        SHIP.LOTEID,
        SHIP.DATA_ENTREGA,
        SHIP.ID_PEDIDO,
        SHIP.FINALDESTINATION,
        SHIP.FINALDESTINATION_REAL,
        SHIP.PRICETYPE,
        SHIP.PALLETQUANTITY,
        SHIP.PALLET,
        SHIP.PROFILE,
        SHIP.LINENUMBER,
        SHIP.ITEMID,
        SHIP.UOM,
        SHIP.CURRENCY,
        SHIP.NUMERO_OC,
        SHIP.TN,
        SHIP.ROTA,
        SHIP.DATA_PREV_COLETA,
        SHIP.DATA_EMISSAO_OC,
        SHIP.DATA_VALIDACAO_QRCODE,
        SHIP.DATA_EMISSAO_NF_LOAD,
        SHIP.DATA_EMISSAO_NF_FICHA,
        COALESCE(
            IFF(
                COALESCE(SHIP.PLANNEDCOST, 0) = 0,
                SHIP.PLANNED_FREIGHT,
                SHIP.PLANNEDCOST
            ), 0
        ) AS PLANNEDCOST,
        COALESCE(SHIP.ACTUALCOST, 0) AS ACTUALCOST,
        COALESCE(SHIP.PENALTYCOST, 0) AS PENALTYCOST,
        COALESCE(ROUND(SHIP.QUANTITY, 2), 0) AS QUANTITY,
        COALESCE(SHIP.QUALITY_ADJUSTMENT, 0) AS QUALITY_ADJUSTMENT,
        COALESCE(
            CTR_2.ID, CTR_1.ID, 'N/A'
        ) AS SOURCINGCONTRACTID,
        MAX(SHIP.VEHICLEID) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.VEHICLEID DESC
        ) AS VEHICLEID,
        MAX(SHIP.DOCCREATEDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.DOCCREATEDATE DESC
        ) AS DOCCREATEDATE,
        MAX(SHIP.ESTIMATEDSHIPDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ESTIMATEDSHIPDATE DESC
        ) AS ESTIMATEDSHIPDATE,
        MAX(SHIP.ACTUALSHIPDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ACTUALSHIPDATE DESC
        ) AS ACTUALSHIPDATE,
        MAX(SHIP.SCHEDULEDDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.SCHEDULEDDATE DESC
        ) AS SCHEDULEDDATE,
        MAX(SHIP.ARRIVALDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ARRIVALDATE DESC
        ) AS ARRIVALDATE,
        MAX(SHIP.ESTIMATEDDELIVERYDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ESTIMATEDDELIVERYDATE DESC
        ) AS ESTIMATEDDELIVERYDATE,
        MAX(SHIP.ACTUALDELIVERYDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ACTUALDELIVERYDATE DESC
        ) AS ACTUALDELIVERYDATE,
        MAX(SHIP.LOADAPPLICATIONDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.LOADAPPLICATIONDATE DESC
        ) AS LOADAPPLICATIONDATE
    FROM SHIPMENT_CORE_PART4 AS SHIP
    LEFT JOIN {{ ref('sourcing_contract_details_master') }} AS CTR_1
        ON SHIP.SOURCINGCONTRACTID_DESTINATION = CTR_1.ID
    LEFT JOIN {{ ref('sourcing_contract_details_master') }} AS CTR_2
        ON SHIP.SOURCINGCONTRACTID = CTR_2.ID
)

SELECT DISTINCT * FROM SHIPMENT_FINAL
