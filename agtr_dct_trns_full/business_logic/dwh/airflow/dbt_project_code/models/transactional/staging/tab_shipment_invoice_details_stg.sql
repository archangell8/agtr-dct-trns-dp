INVOICE_DETAILS_FINAL AS (
    SELECT * FROM INVOICE_DETAILS_NEOGRID
    WHERE
        1 = 1
        AND PRODUCT_CODE IS NOT NULL
        AND PRODUCT_CODE != 'NULL'
        --AND PURCHASE_CODE IS NULL
        --AND FREIGHT_TYPE != 'CIF'
        AND NOT EXISTS (
            SELECT 1
            FROM {{ source('jde', 'NEOGRID_EVENTS_FLAT') }} AS NEO
            WHERE
                1 = 1
                AND INVOICE_DETAILS_NEOGRID.INVOICE_KEY = 'NFe' || NEO.CHAVE_NFE
                AND NEO.TPEVENTO IN ('110111', '210220')
        )

    UNION ALL

    SELECT * FROM INVOICE_DETAILS_FICHAS
    WHERE
        1 = 1
        AND INVOICE_KEY NOT IN (
            SELECT INV.INVOICE_KEY
            FROM INVOICE_DETAILS_NEOGRID AS INV
        )
        AND PURCHASE_CODE IS NULL

    UNION ALL

    SELECT INVCTE.* FROM INVOICE_DETAILS_CTMS_CTE AS INVCTE
    LEFT JOIN INVOICE_DETAILS_NEOGRID AS INVNEO_1
        ON
            LTRIM(INVCTE.CNPJ_EXPEDIDOR, 0) = LTRIM(INVNEO_1.SOURCE_CNPJ, 0)
            AND INVCTE.INVOICE = INVNEO_1.INVOICE
    LEFT JOIN INVOICE_DETAILS_NEOGRID AS INVNEO_2
        ON
            LTRIM(INVCTE.CNPJ_REMETENTE, 0) = LTRIM(INVNEO_2.SOURCE_CNPJ, 0)
            AND INVCTE.INVOICE = INVNEO_2.INVOICE
    LEFT JOIN INVOICE_DETAILS_FICHAS AS INVF
        ON
            LTRIM(INVCTE.SOURCE_CNPJ, 0) = LTRIM(INVF.SOURCE_CNPJ, 0)
            AND INVCTE.INVOICE = INVF.INVOICE
    WHERE
        1 = 1
        AND INVCTE.FREIGHT_TYPE = 'FOB'
        -- remover registros que já existam na INVOICE_DETAILS_NEOGRID
        AND (
            INVNEO_1.INVOICE IS NULL AND INVNEO_2.INVOICE IS NULL
        )
        -- remover registros que já existam na INVOICE_DETAILS_FICHAS
        AND INVF.INVOICE IS NULL

    UNION ALL

    SELECT INVCTE.* FROM INVOICE_DETAILS_CTMS_CTE AS INVCTE
    LEFT JOIN INVOICE_DETAILS_NEOGRID AS INVNEO_1
        ON
            LTRIM(INVCTE.CNPJ_EXPEDIDOR, 0) = LTRIM(INVNEO_1.SOURCE_CNPJ, 0)
            AND INVCTE.INVOICE = INVNEO_1.INVOICE
    LEFT JOIN INVOICE_DETAILS_NEOGRID AS INVNEO_2
        ON
            LTRIM(INVCTE.CNPJ_REMETENTE, 0) = LTRIM(INVNEO_2.SOURCE_CNPJ, 0)
            AND INVCTE.INVOICE = INVNEO_2.INVOICE
    LEFT JOIN INVOICE_DETAILS_FICHAS AS INVF
        ON
            LTRIM(INVCTE.SOURCE_CNPJ, 0) = LTRIM(INVF.SOURCE_CNPJ, 0)
            AND INVCTE.INVOICE = INVF.INVOICE
    LEFT JOIN INVOICE_DETAILS_CTMS_CTE AS CTE_FOB
        ON
            INVCTE.INVOICE_KEY = CTE_FOB.INVOICE_KEY
            AND CTE_FOB.FREIGHT_TYPE = 'FOB'
    WHERE
        1 = 1
        AND INVCTE.FREIGHT_TYPE = 'CIF'
        -- remover registros que já existam na INVOICE_DETAILS_NEOGRID
        AND (
            INVNEO_1.INVOICE IS NULL AND INVNEO_2.INVOICE IS NULL
        )
        -- remover registros que já existam na INVOICE_DETAILS_FICHAS
        AND INVF.INVOICE IS NULL
        --remover registros que também existam como FOB na DETAILS_CTMS_CTE
        AND CTE_FOB.INVOICE_KEY IS NULL
)

