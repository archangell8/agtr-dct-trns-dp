SHIPMENT_STG AS (
    SELECT DISTINCT
        SHIP.ID,
        SHIP.LOADNUMBER_RAW,
        SHIP.FICHANUMBER_RAW,
        SHIP.LINENUMBER,
        SHIP.CURRENCY,
        SHIP.NUMERO_OC,
        SHIP.TN,
        SHIP.ROTA,
        SHIP.DATA_PREV_COLETA,
        SHIP.DATA_EMISSAO_OC,
        SHIP.DATA_VALIDACAO_QRCODE,
        SHIP.DATA_EMISSAO_NF_LOAD,
        SHIP.DATA_EMISSAO_NF_FICHA,
        COALESCE(NULLIF(SHIP.BK, ''), 'N/A') AS BK,
        CASE COALESCE(NULLIF(SHIP.OPERATIONTYPE, ''), 'N/A')
            WHEN 'FOB_CTE' THEN 'FOB'
            WHEN 'CIF_CTE' THEN 'CIF'
            WHEN 'FOB_NEOGRID' THEN 'FOB'
            WHEN 'CIF_NEOGRID' THEN 'CIF'
            ELSE COALESCE(NULLIF(SHIP.OPERATIONTYPE, ''), 'N/A')
        END AS OPERATIONTYPE,
        COALESCE(NULLIF(LOC1.LOCATION_UNIT_ID, ''), 'N/A') AS SOURCE,
        COALESCE(NULLIF(LOC2.LOCATION_UNIT_ID, ''), 'N/A') AS SOURCEBP,
        COALESCE(NULLIF(LOC3.LOCATION_UNIT_ID, ''), 'N/A') AS DESTINATION,
        COALESCE(NULLIF(SHIP.LOADNUMBER, ''), 'N/A') AS LOADNUMBER,
        COALESCE(NULLIF(SHIP.SOURCINGCONTRACTID, ''), 'N/A') AS SOURCINGCONTRACTID,
        COALESCE(NULLIF(SHIP.TRANSMODE, ''), 'N/A') AS TRANSMODE,
        COALESCE(
            CASE
                WHEN SHIP.TRANSMODE = 'ROD'
                    THEN 'ROD'
                WHEN SHIP.TRANSMODE = 'HID' AND LOC1.LOCATION_UNIT_STRUCTURE IN ('PORTO MARÍTIMO', 'PORTO FLUVIAL')
                    THEN LOC1.LOCATION_CODE
                WHEN SHIP.TRANSMODE = 'FER' AND LOC1.LOCATION_UNIT_STRUCTURE IN ('TRANSBORDO')
                    THEN LOC1.LOCATION_CODE
                ELSE SHIP.TRANSMODE
            END,
            SHIP.TRANSMODE
        ) AS TRANSMODE_IBP,
        COALESCE(
            CONCAT(
                LOC1.LOCATION_UNIT_ID, '-', LOC3.LOCATION_UNIT_ID, '-',
                COALESCE(
                    CASE
                        WHEN SHIP.OPERATIONTYPE = 'FOB' AND SHIP.TRANSMODE = 'FER'
                            THEN LOC1.LOCATION_CODE
                        WHEN SHIP.TRANSMODE = 'ROD'
                            THEN 'ROD'
                        WHEN SHIP.TRANSMODE = 'HID' AND LOC1.LOCATION_UNIT_STRUCTURE IN ('PORTO MARÍTIMO', 'PORTO FLUVIAL')
                            THEN LOC1.LOCATION_CODE
                        WHEN SHIP.TRANSMODE = 'FER' AND LOC1.LOCATION_UNIT_STRUCTURE IN ('TRANSBORDO')
                            THEN LOC1.LOCATION_CODE
                        ELSE SHIP.TRANSMODE
                    END,
                    SHIP.TRANSMODE
                )
            ),
            'N/A'
        ) AS LANEID,
        IFF(
            COALESCE(NULLIF(SHIP.CARRIER, ''), 'N/A') = 'N/A',
            '00000000 - TRANSPORTADORA NAO INFORMADA',
            SHIP.CARRIER
        ) AS CARRIER,
        COALESCE(NULLIF(SHIP.VEHICLEID, ''), 'N/A') AS VEHICLEID,
        COALESCE(NULLIF(SHIP.ESTIMATEDSHIPDATE, ''), 'N/A') AS ESTIMATEDSHIPDATE,
        COALESCE(
            TO_CHAR(
                TO_TIMESTAMP(
                    NULLIF(SHIP.ACTUALSHIPDATE, 'N/A'), 'DD-MM-YYYY HH24:MI:SS'
                ),
                'DD-MM-YYYY HH24:MI:SS'
            ),
            'N/A'
        ) AS ACTUALSHIPDATE,
        -- COALESCE(NULLIF(SHIP.SCHEDULEDDATE, ''), 'N/A') AS SCHEDULEDDATE,
        COALESCE(
            TO_CHAR(
                TO_TIMESTAMP(
                    NULLIF(SHIP.SCHEDULEDDATE, 'N/A'), 'DD-MM-YYYY HH24:MI:SS'
                ),
                'DD-MM-YYYY HH24:MI:SS'
            ),
            'N/A'
        ) AS SCHEDULEDDATE,
        COALESCE(NULLIF(SHIP.ARRIVALDATE, ''), 'N/A') AS ARRIVALDATE,
        COALESCE(NULLIF(SHIP.ESTIMATEDDELIVERYDATE, ''), 'N/A') AS ESTIMATEDDELIVERYDATE,
        COALESCE(
            TO_CHAR(
                TO_TIMESTAMP(
                    NULLIF(SHIP.ACTUALDELIVERYDATE, 'N/A'),
                    'DD-MM-YYYY HH24:MI:SS'
                ),
                'DD-MM-YYYY HH24:MI:SS'
            ),
            'N/A'
        ) AS ACTUALDELIVERYDATE,
        COALESCE(NULLIF(SHIP.LOADAPPLICATIONDATE, ''), 'N/A') AS LOADAPPLICATIONDATE,
        COALESCE(NULLIF(SHIP.CONTRACT_NUMBER_APPLIED, ''), 'N/A') AS CONTRACT_NUMBER_APPLIED,
        COALESCE(SHIP.SALESORDERDELIVERYID, 'N/A') AS SALESORDERDELIVERYID,
        COALESCE(NULLIF(
            CASE
                WHEN LOC3.LOCATION_UNIT_STRUCTURE = 'PORTO MARÍTIMO'
                    THEN LOC3.LOCATION_UNIT_ID
                ELSE
                    LOC4.LOCATION_UNIT_ID
            END,
            ''
        ), 'N/A') AS FINALDESTINATION,
        COALESCE(FINALDESTINATION_REAL, 'N/A') AS FINALDESTINATION_REAL,
        COALESCE(NULLIF(SHIP.PRICETYPE, ''), 'PAF') AS PRICETYPE,
        ROUND(COALESCE(SHIP.PALLETQUANTITY, 0), 3) AS PALLETQUANTITY,
        COALESCE(NULLIF(SHIP.PALLET, ''), 'N/A') AS PALLET,
        COALESCE(NULLIF(SHIP.PROFILE, ''), 'N/A') AS PROFILE,
        COALESCE(NULLIF(SHIP.LOTEID, ''), 'N/A') AS LOTEID,
        COALESCE(UDC_ITEM.TARGET_CODE, SHIP.ITEMID) AS ITEMID,
        ROUND(COALESCE(SHIP.PLANNEDCOST, 0), 3) AS PLANNEDCOST,
        ROUND(COALESCE(SHIP.ACTUALCOST, 0), 3) AS ACTUALCOST,
        ROUND(
            COALESCE(SP.PENALTYCOST, SHIP.PENALTYCOST, 0), 3
        ) AS PENALTYCOST,
        ROUND(
            COALESCE(
                SHIP.QUANTITY / CONV.SUPPLYPLANNINGFINALCONVERSIONFACTOR, 0
            ), 3
        ) AS QUANTITY,
        ROUND(
            COALESCE(
                SHIP.QUALITY_ADJUSTMENT
                / CONV.SUPPLYPLANNINGFINALCONVERSIONFACTOR,
                0
            ), 3
        ) AS QUALITY_ADJUSTMENT,
        COALESCE(CONV.UOMFROM, 'TN') AS UOM
    FROM SHIPMENT_UNION AS SHIP
    LEFT JOIN  {{ ref('tab_location_internal_stg') }} AS LOC1
        ON SHIP.SOURCE = LOC1.LOCATIONID
    LEFT JOIN  {{ ref('tab_location_internal_stg') }} AS LOC2
        ON SHIP.SOURCEBP = LOC2.LOCATIONID
    LEFT JOIN  {{ ref('tab_location_internal_stg') }} AS LOC3
        ON SHIP.DESTINATION = LOC3.LOCATIONID
    LEFT JOIN  {{ ref('tab_location_internal_stg') }} AS LOC4
        ON SHIP.FINALDESTINATION = LOC4.LOCATIONID
    LEFT JOIN SHIPMENT_PENALTIES AS SP
        ON SHIP.ID = SP.SHIPMENTID
    LEFT JOIN {{ ref('uom_conversion_master') }} AS CONV
        ON
            TRIM(SHIP.ITEMID) = TRIM(CONV.ITEM)
            AND TRIM(COALESCE(SHIP.UOM, 'KG')) = TRIM(CONV.UOMTO)
            AND TRIM(CONV.UOMFROM) = 'TN'
    LEFT JOIN {{ source('pscfl', 'F_MIN_DCT_UDC') }} AS UDC_ITEM
        ON
            UDC_ITEM.SOURCE_CODE = SHIP.ITEMID
            AND UDC_ITEM.CATEGORY = 'SHIPMENT'
            AND UDC_ITEM.STAGE = 'DE-PARA PRODUTO'
    WHERE
        1 = 1
    ORDER BY BK ASC
),

ECOPATIO_SCHEDULE_DATE AS (
    SELECT
        ID,
        MAX(E.SCHEDULEDDATE) AS SCHEDULEDDATE
    FROM SHIPMENT_STG AS S
    LEFT JOIN {{ ref('tab_shipment_load_intransit_stg') }} AS L
        ON S.LOADNUMBER_RAW = L.LOAD
    LEFT JOIN {{ ref('tab_shipment_ficha_intransit_stg') }} AS FF
        ON S.FICHANUMBER_RAW = FF.FICHA
    INNER JOIN {{ ref('vw_shipment_ecopatio_schedule_stg') }} AS E
        ON
            S.VEHICLEID = E.VEHICLEID
            AND (FF.NF_NUM = E.NUM_NF OR L.NF_NUM = E.NUM_NF)
    WHERE
        1 = 1
        AND (
            L.NF_STATUS NOT IN ('994','998')
            OR FF.STATUS_FICHA != 'FICHA CANCELADA'
        )
        AND S.TRANSMODE = 'ROD'
    GROUP BY 1
),

