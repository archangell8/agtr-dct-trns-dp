        LOC.LOCATIONID
    FROM {{ ref('vw_transportation_schedule_stg') }} AS CMM
    INNER JOIN  {{ ref('tab_location_internal_stg') }} AS LOC_IN
        ON
            CMM.LOCAL_DESCARGA = LOC_IN.LOCATION_NAME
            AND LOC_IN.LOCATION_UNIT_STRUCTURE IN (
                'PORTO MARÍTIMO', 'FÁBRICA', 'MERCADO INTERNO'
            )
            AND LEFT(CMM.BP_DESTINO, 5) = LEFT(LOC_IN.LOCATIONID, 5)
    INNER JOIN  {{ ref('location_master') }} AS LOC
        ON LOC_IN.LOCATION_CODE = LOC.LOCATION_CODE
    WHERE
        1 = 1
        AND CMM.VOLUME > 0
        AND TO_DATE(CMM.DATE, 'DD-MM-YYYY') >= DATEADD('DAY', -30, CURRENT_DATE())
    QUALIFY RANK() OVER (
        PARTITION BY
            CMM.CONTRACT_NUMBER,
            TO_DATE(CMM.DATE, 'DD-MM-YYYY')
        ORDER BY CMM.VOLUME DESC, CMM.TRANSPORTATIONNUMBER DESC
    ) = 1
