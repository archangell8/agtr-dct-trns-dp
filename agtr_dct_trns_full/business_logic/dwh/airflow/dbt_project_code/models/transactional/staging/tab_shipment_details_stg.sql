                    SHIP.DESTINATION
            END
        ) AS DESTINATION,
        IFF(B.LEADTIME IS NULL, 'N/A', SHIP.LANEID) AS LANEID,
        COALESCE(
            TO_CHAR(
                TO_DATE(CONVOYS.ACTUALDELIVERYDATE, 'YYYY-MM-DD HH24:MI:SS'),
                'DD-MM-YYYY'
            ),
            SHIP.ARRIVALDATE
        ) AS ARRIVALDATE,
        COALESCE(
            TO_CHAR(
                TO_TIMESTAMP(CONVOYS.ESTIMATEDDELIVERYDATE, 'YYYY-MM-DD HH24:MI:SS'),
                'DD-MM-YYYY HH24:MI:SS'
            ),
            SHIP.ESTIMATEDDELIVERYDATE
        ) AS ESTIMATEDDELIVERYDATE,
        CASE
            WHEN SHIP.FINALDESTINATION_REAL = 'TRUE'
                THEN SHIP.FINALDESTINATION
            ELSE
                COALESCE(SFD.LOCATION_UNIT_ID, SHIP.FINALDESTINATION)
        END AS FINALDESTINATION,
        COALESCE(
            TO_CHAR(
                TO_TIMESTAMP(CONVOYS.ACTUALSHIPDATE, 'YYYY-MM-DD HH24:MI:SS'),
                'DD-MM-YYYY HH24:MI:SS'
            ),
            SHIP.ACTUALSHIPDATE
        ) AS ACTUALSHIPDATE,
        COALESCE(
            TO_CHAR(
                TO_TIMESTAMP(CONVOYS.ACTUALDELIVERYDATE, 'YYYY-MM-DD HH24:MI:SS'),
                'DD-MM-YYYY HH24:MI:SS'
            ),
            SHIP.ACTUALDELIVERYDATE
        ) AS ACTUALDELIVERYDATE
    FROM SHIPMENT AS SHIP
    LEFT JOIN {{ ref('tab_sourcing_contract_internal_stg') }} AS SCI
        ON SCI.ID = SHIP.SOURCINGCONTRACTID
    LEFT JOIN {{ ref('lane_master') }} AS L
        ON L.LANEID = SHIP.LANEID
    LEFT JOIN {{ ref('itemlanetransmode_master') }} AS B
        ON L.LANEID = B.BODLANEID
    LEFT JOIN SCHEDULED_FINAL_DESTINATION AS SFD
        ON
            TO_DATE(
                NULLIF(SHIP.ACTUALSHIPDATE, 'N/A'), 'DD-MM-YYYY HH24:MI:SS'
            ) = SFD.DATE
            AND SCI.CONTRACTNUMBER = SFD.CONTRACT_NUMBER
            AND SHIP.FINALDESTINATION = SFD.LOCATIONID
    LEFT JOIN {{ ref('tab_location_internal_stg') }} AS LOC
        ON SHIP.DESTINATION = LOC.LOCATIONID
    LEFT JOIN CTE_VW_CMAX_CONVOYS AS CONVOYS
        ON CONVOYS.LOAD_NUMBER = SHIP.LOADNUMBER
),

PRICETYPE_PRIORITY AS (
    SELECT
        ID,
        SOURCINGCONTRACTID,
        QUANTITY,
        PRICETYPE,
        -- PRIORIZANDO LINHA COM MAIOR VOLUME
        ROW_NUMBER() OVER (
            PARTITION BY ID, SOURCINGCONTRACTID
            ORDER BY QUANTITY DESC
        ) AS VOLUME_PRIORITY
    FROM SHIPMENT_FINAL
    QUALIFY
        VOLUME_PRIORITY = 1
),

DETAILS_TEMP AS (
    SELECT DISTINCT
        SHIP.ID,
        SHIP.BK,
        SHIP.OPERATIONTYPE,
        SHIP.SOURCE,
        MAX(SHIP.SOURCEBP) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.SOURCEBP DESC
        ) AS SOURCEBP,
        SHIP.DESTINATION,
        SHIP.LOADNUMBER,
        SHIP.SOURCINGCONTRACTID,
        SHIP.TRANSMODE AS TRANSMODE_INTERNAL,
        SHIP.TRANSMODE_IBP AS TRANSMODE,
        IFF(B.LEADTIME IS NULL, 'N/A', SHIP.LANEID) AS LANEID,
        SHIP.CARRIER,
        MAX(SHIP.VEHICLEID) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.VEHICLEID DESC
        ) AS VEHICLEID,
        MAX(SHIP.ESTIMATEDSHIPDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ESTIMATEDSHIPDATE DESC
        ) AS ESTIMATEDSHIPDATE,
        MAX(SHIP.ACTUALSHIPDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ACTUALSHIPDATE DESC
        ) AS ACTUALSHIPDATE,
        MAX(SHIP.SCHEDULEDDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.SCHEDULEDDATE DESC
        ) AS SCHEDULEDDATE,
        MAX(SHIP.ARRIVALDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ARRIVALDATE DESC
        ) AS ARRIVALDATE,
        MAX(SHIP.ESTIMATEDDELIVERYDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ESTIMATEDDELIVERYDATE DESC
        ) AS ESTIMATEDDELIVERYDATE,
        MAX(SHIP.ACTUALDELIVERYDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.ACTUALDELIVERYDATE DESC
        ) AS ACTUALDELIVERYDATE,
        MAX(SHIP.LOADAPPLICATIONDATE) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
            ORDER BY SHIP.LOADAPPLICATIONDATE DESC
        ) AS LOADAPPLICATIONDATE,
        SHIP.CONTRACT_NUMBER_APPLIED,
        SHIP.LOADNUMBER_RAW,
        SHIP.FICHANUMBER_RAW,
        SHIP.SALESORDERDELIVERYID,
        SHIP.FINALDESTINATION,
        P.PRICETYPE,
        SHIP.PALLETQUANTITY,
        SHIP.PALLET,
        SHIP.PROFILE,
        --SHIP.LINENUMBER,
        SHIP.ITEMID,
        SHIP.PLANNEDCOST,
        SHIP.ACTUALCOST,
        SHIP.PENALTYCOST,
        SHIP.NUMERO_OC,
        SHIP.TN,
        SHIP.ROTA,
        SHIP.DATA_PREV_COLETA,
        SHIP.DATA_EMISSAO_OC,
        SHIP.DATA_VALIDACAO_QRCODE,
        SHIP.DATA_EMISSAO_NF_LOAD,
        SHIP.DATA_EMISSAO_NF_FICHA,
        SUM(SHIP.QUANTITY) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
        ) AS QUANTITY,
        SUM(SHIP.QUALITY_ADJUSTMENT) OVER (
            PARTITION BY SHIP.ID, SHIP.BK, SHIP.ITEMID
        ) AS QUALITY_ADJUSTMENT,
        SHIP.UOM,
        SHIP.CURRENCY
    FROM SHIPMENT_FINAL AS SHIP
    LEFT JOIN {{ ref('itemlanetransmode_master') }} AS B
            ON SHIP.LANEID = B.BODLANEID
    LEFT JOIN PRICETYPE_PRIORITY AS P
    ON
        SHIP.ID = P.ID
        AND SHIP.SOURCINGCONTRACTID = P.SOURCINGCONTRACTID
)

SELECT
    *,
    HASH(*) AS HASH_ID
FROM DETAILS_TEMP
WHERE
    1 = 1
    AND {{ date_max_filter('ESTIMATEDSHIPDATE', 'DD-MM-YYYY', 'na') }} --noqa
    AND {{ date_max_filter('ACTUALSHIPDATE', 'DD-MM-YYYY HH:MI:SS', 'na') }} --noqa
    AND {{ date_max_filter('SCHEDULEDDATE', 'DD-MM-YYYY HH:MI:SS', 'na') }} --noqa
    AND {{ date_max_filter('ARRIVALDATE', 'DD-MM-YYYY', 'na') }} --noqa
    AND {{ date_max_filter('ESTIMATEDDELIVERYDATE', 'DD-MM-YYYY HH:MI:SS', 'na') }} --noqa
    AND {{ date_max_filter('ACTUALDELIVERYDATE', 'DD-MM-YYYY HH:MI:SS', 'na') }} --noqa
    AND {{ date_max_filter('LOADAPPLICATIONDATE', 'DD-MM-YYYY', 'na') }} --noqa
