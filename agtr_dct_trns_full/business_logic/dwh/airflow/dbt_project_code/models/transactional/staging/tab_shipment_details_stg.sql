        CASE
            WHEN SHIP.ACTUALSHIPDATE = 'N/A' THEN 'N/A'
            ELSE SHIP.SOURCINGCONTRACTID
        END AS SOURCINGCONTRACTID,
        CASE
            WHEN SHIP.ACTUALSHIPDATE = 'N/A'
                THEN 'N/A'
            WHEN DAY(TO_TIMESTAMP(SHIP.ACTUALSHIPDATE, 'DD-MM-YYYY HH24:MI:SS')) = 1
                THEN SHIP.ACTUALSHIPDATE
            WHEN RDS.DATAHORASAIDA::TIME < TO_TIME(LOC_GROUP.HR_BEGIN_ONHANDS, 'HH24:MI')
                THEN TO_CHAR(
                    DATEADD(DAY, -1, TO_TIMESTAMP(SHIP.ACTUALSHIPDATE, 'DD-MM-YYYY HH24:MI:SS')),
                    'DD-MM-YYYY HH24:MI:SS'
                )
            ELSE SHIP.ACTUALSHIPDATE
        END AS ACTUALSHIPDATE,
        -- SHIP.ACTUALSHIPDATE,
        COALESCE(
            TO_CHAR(
                DATEADD('HOUR', 3, ECO.SCHEDULEDDATE), 'DD-MM-YYYY HH24:MI:SS'
            ),
            SHIP.SCHEDULEDDATE
        ) AS SCHEDULEDDATE
    FROM SHIPMENT_STG AS SHIP
    LEFT JOIN ECOPATIO_SCHEDULE_DATE AS ECO
        ON SHIP.ID = ECO.ID
    LEFT JOIN RDS_HISTORIC_DCT AS RDS
        ON
            RDS.LOADE1::STRING = SHIP.LOADNUMBER::STRING
