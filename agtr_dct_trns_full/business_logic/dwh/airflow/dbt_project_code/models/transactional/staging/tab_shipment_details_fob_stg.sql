RDS_HISTORIC_DCT AS (
    SELECT
        LOTID,
        MAX(DATAHORASAIDA) AS DATAHORASAIDA,
        MAX(DATAHORACHEGADA) AS DATAHORACHEGADA
    FROM {{ source('rds', 'VW_RDS_HISTORIC_DCT') }}
