WITH
CTE_UDC_MAPPING AS (
    SELECT
        CATEGORY,
        STAGE,
        SOURCE_CODE,
        TARGET_CODE,
        TARGET_NUMBER
    FROM {{ source('pscfl', 'F_MIN_DCT_UDC') }}
    WHERE
        1 = 1
        AND STATUS = 'ATIVO'
),

DISTRIBUITON_RAW AS (
    SELECT
        GRAINS.OPERACAO AS OPERATION,
        --GRAINS.UNIDADE_ORIGEM AS SOURCEID,
        GRAINS.FLUXO AS TRANSMODE,
        GRAINS.UNIDADE_DESTINO AS DESTINATIONID,
        GRAINS.TIPO AS "TYPE",
        ITEM.TARGET_CODE AS ITEM,
        GRAINS.VALUEINPUT AS PLANNEDQUANTITY,
        GRAINS.MONTH AS "MONTH",
        CASE
            WHEN
                GRAINS.UNIDADE_ORIGEM = GRAINS.UNIDADE_DESTINO
                AND GRAINS.FLUXO = 'RODO'
                AND GRAINS.TIPO = 'FLUXO ORIGEM'
                THEN GRAINS.SUB_REGIONAL_ORIGEM
            ELSE
                GRAINS.UNIDADE_ORIGEM
        END AS SOURCEID
    FROM {{ source('pscfl', 'F_MIN_PSI_IBP_GRAINS_BASE') }} AS GRAINS
    INNER JOIN CTE_UDC_MAPPING AS ITEM
        ON
            GRAINS.ITEM = ITEM.SOURCE_CODE
            AND ITEM.CATEGORY = 'DIST_IBP_ITEM_FILTRO'
            AND ITEM.STAGE = 'DISTRIBUITON_RAW'
    WHERE
        GRAINS.TIPO IN ('FLUXO ORIGEM', 'FLUXO TRANSBORDO', 'TBO-ARZ')
        AND TO_DATE(GRAINS.MONTH, 'MM-YYYY') >= '2025-01-01'::DATE
),

DISTRIBUTION_TRANSFORMED AS (
    SELECT
        GRAW.OPERATION,
        GRAW.TYPE,
        GRAW.ITEM,
        GRAW.PLANNEDQUANTITY,
        GRAW.MONTH,
        COALESCE(S_UF.UF, GRAW.SOURCEID) AS SOURCEID,
        CASE
            WHEN GRAW.TRANSMODE = 'TBO'
                THEN S_TRANS.TRANSMODE
            WHEN GRAW.TRANSMODE = 'ARMAZEM 509'
                THEN 'ROD'
            ELSE COALESCE(TRANS.TRANSMODE, 'N/A')
        END AS TRANSMODE,
        COALESCE(D_UF.UF, GRAW.DESTINATIONID) AS DESTINATIONID
    FROM DISTRIBUITON_RAW AS GRAW
    LEFT JOIN {{ source('pscfl', 'F_MIN_TRANSMODE') }} AS TRANS
        ON GRAW.TRANSMODE = TRANS.TRANSMODEDESCRIPTION
    LEFT JOIN {{ source('pscfl', 'F_MIN_TRANSMODE') }} AS S_TRANS
        ON GRAW.SOURCEID = S_TRANS.TRANSMODEDESCRIPTION
    LEFT JOIN {{ source('pscfl', 'F_MIN_LOCATION_UF_STATE') }} AS S_UF
        ON GRAW.SOURCEID = S_UF.STATE
    LEFT JOIN {{ source('pscfl', 'F_MIN_LOCATION_UF_STATE') }} AS D_UF
        ON GRAW.DESTINATIONID = D_UF.STATE
    WHERE
        TRY_TO_NUMERIC(GRAW.PLANNEDQUANTITY) IS NOT NULL
),

DISTRIBUTION_IBP AS (
    SELECT
        ITEM AS ITEMID,
        SOURCEID,
        DESTINATIONID AS FINALDESTINATIONID,
        "MONTH",
        OPERATION,
        "TYPE",
        TRANSMODE,
        'TN' AS UOM,
        ROUND(SUM(TO_NUMBER(REPLACE(
            PLANNEDQUANTITY, ',', '.'
        ))), 3) AS PLANNEDQUANTITY
    FROM DISTRIBUTION_TRANSFORMED
    GROUP BY
        "MONTH",
        OPERATION,
        SOURCEID,
        TRANSMODE,
        DESTINATIONID,
        "TYPE",
        ITEM
    ORDER BY TO_DATE('01-' || MONTH, 'DD-MM-YYYY')
)

SELECT
    *,
    HASH(*) AS HASH_ID
FROM DISTRIBUTION_IBP
WHERE
    1 = 1
    --AND PLANNEDQUANTITY != 0
    AND {{ date_max_filter('MONTH', 'MM-YYYY', 'na') }} --noqa
