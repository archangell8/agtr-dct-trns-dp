WITH
INTSTG_SHIPMENT_LATEST_STATUS AS (
    SELECT
        SOURCINGCONTRACTNUMBER,
        SUM(STATUSQUANTITY) AS TOTALQTY
    FROM {{ ref('intstg_shipment_latest_status') }}
    WHERE
        LATESTSTATUS != 'FINISHED'
    GROUP BY SOURCINGCONTRACTNUMBER
),

OUT_SCD AS (
    SELECT
        'CurrentWorkingView' AS VERSION_NAME,
        A.SOURCINGCONTRACTNUMBER AS CONTRACT_LINEID,
        A.ITEM,
        A.SUPPLIERID AS SUPPLIER_LOCATION,
        A.SOURCELOCATION AS SOURCE,
        A.DESTINATIONLOCATION AS "LOCATION",
        A.TRANSMODE,
        TO_CHAR(A.DELIVERYENDDATE, 'DD-MON-YY') AS DAY,
        MAX(A.FREIGHTTYPE) AS OPERATION_TYPE,
        MAX(A.FREIGHTTYPE) AS FREIGHT_TYPE,
        TO_CHAR(MAX(A.DELIVERYSTARTDATE), 'YYYY-MM-DDTHH:MI:SS')
            AS DELIVERY_START_DATE,
        TO_CHAR(MAX(A.DELIVERYENDDATE), 'YYYY-MM-DDTHH:MI:SS')
            AS DELIVERY_END_DATE,
        MIN(A.CONTRACTSTATUS) AS DELIVERY_STATUS,
        MAX(A.SALESREP) AS SALES_REPRESENTATIVE,
        SUM(A.FREIGHTCOST) AS CONTRACT_FREIGHT_COST,
        SUM(A.ACTUALCOST) AS ACTUAL_FREIGHT_COST,
        SUM(A.FREIGHTCADENCE) AS FREIGHT_CADENCE,
        SUM(A.PLANNEDCOST) AS PLANNEDCOST,
        SUM(A.RECEIVEDQUANTITY) AS RECEIVED_QUANTITY,
        SUM(A.TORECEIVETOTAL) AS TO_RECEIVE_TOTAL,
        SUM(A.TORECEIVEFLAT) AS TO_RECEIVE_FLAT,
        SUM(A.TORECEIVEPAF) AS TO_RECEIVE_PAF,
        SUM(A.CANCELLEDQUANTITY) AS CANCELLED_QUANTITY,
        SUM(A.RECEIVEDPAF) AS PAF_RECEIVED_QUANTITY,
        SUM((A.CONTRACTQUANTITY - A.RECEIVEDQUANTITY)) AS BALANCE_QUANTITY,
        SUM(B.TOTALQTY) AS PLANNED_QUANTITY,
        SUM(A.FREIGHTCADENCE) AS LOADING_POINT_CAPACITY
    FROM {{ ref('intstg_sourcing_contract_details') }} AS A
    LEFT JOIN INTSTG_SHIPMENT_LATEST_STATUS AS B
        ON A.ID = B.SOURCINGCONTRACTNUMBER
    WHERE
        A.DELIVERYENDDATE IS NOT NULL
    GROUP BY
        A.SOURCINGCONTRACTNUMBER,
        A.ITEM,
        A.SUPPLIERID,
        A.SOURCELOCATION,
        A.DESTINATIONLOCATION,
        A.TRANSMODE,
        A.DELIVERYENDDATE

),

FINAL AS (
    SELECT
        VERSION_NAME,
        CONTRACT_LINEID,
        ITEM,
        SUPPLIER_LOCATION,
        SOURCE,
        LOCATION,
        TRANSMODE,
        DAY,
        OPERATION_TYPE,
        FREIGHT_TYPE,
        DELIVERY_START_DATE,
        DELIVERY_END_DATE,
        DELIVERY_STATUS,
        SALES_REPRESENTATIVE,
        CONTRACT_FREIGHT_COST,
        ACTUAL_FREIGHT_COST,
        FREIGHT_CADENCE,
        PLANNEDCOST,
        RECEIVED_QUANTITY,
        TO_RECEIVE_TOTAL,
        TO_RECEIVE_FLAT,
        TO_RECEIVE_PAF,
        CANCELLED_QUANTITY,
        PAF_RECEIVED_QUANTITY,
        BALANCE_QUANTITY,
        PLANNED_QUANTITY,
        LOADING_POINT_CAPACITY
    FROM OUT_SCD
)

SELECT
    *,
    HASH(*) AS HASH_ID
FROM FINAL
