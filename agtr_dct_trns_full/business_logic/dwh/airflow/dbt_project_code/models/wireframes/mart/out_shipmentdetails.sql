WITH
OUT_SHIPMENTDETAILS_AUX AS (
    SELECT
        'CurrentWorkingView' AS VERSION_NAME,
        A.ID,
        A.SHIPMENTLINEID AS SHIPMENT_LINEID,
        A.SOURCELOCATION AS SOURCE,
        A.DESTINATIONLOCATION AS "LOCATION",
        A.ITEM,
        A.BODLANE,
        A.TRANSMODE,
        A.CARRIER,
        A.VEHICALID AS VEHICLEID,
        'N/A' AS SURVEYOR,
        A.OPERATIONTYPE AS OPERATION_TYPE,
        A.SALESORDERDELIVERYID,
        A.FINALDESTINATION,
        CASE
            WHEN A.SOURCINGCONTRACTNUMBER = 'N/A'
                THEN 'N/A'
            ELSE
                SPLIT_PART(A.SOURCINGCONTRACTNUMBER, '-', 2)
        END AS CONTRACT_LINEID,
        TO_CHAR(
            MAX(A.ACTUALSHIPDATE), 'DD-MON-YY'
        ) AS "DAY",
        TO_CHAR(
            MAX(A.ESTIMATEDSHIPDATE), 'DD-MON-YY'
        ) AS ESTIMATED_SHIP_DATE,
        TO_CHAR(
            MAX(A.ACTUALSHIPDATE), 'DD-MON-YY'
        ) AS ACTUAL_SHIP_DATE,
        TO_CHAR(
            MAX(A.SCHEDULEDDATE), 'DD-MON-YY'
        ) AS SHIPMENT_SCHEDULED_DATE,
        TO_CHAR(
            MAX(A.ARRIVALDATE), 'DD-MON-YY'
        ) AS SHIPMENT_ARRIVAL_DATE,
        TO_CHAR(
            MAX(A.ESTIMATEDDELIVERYDATE), 'DD-MON-YY'
        ) AS ESTIMATED_DELIVERY_DATE,
        TO_CHAR(
            MAX(A.ACTUALDELIVERYDATE), 'DD-MON-YY'
        ) AS ACTUAL_DELIVERY_DATE,
        TO_CHAR(
            MAX(A.LOADAPPLICATIONDATE), 'DD-MON-YY'
        ) AS LOAD_APPLICATION_DATE,
        SUM(A.PLANNEDCOST) AS PLANNED_COST,
        SUM(A.ACTUALCOST) AS ACTUAL_COST,
        SUM(A.QUANTITY) AS SHIPMENTQUANTITY,
        MAX(C.LATESTSTATUS) AS SHIPMENT_DETAILS_STATUS
    FROM {{ ref('intstg_shipment_details_without_cancelled_shipments') }} AS A
    LEFT JOIN {{ ref('intstg_shipment_latest_status') }} AS C
        ON A.ID = C.ID
    GROUP BY
        A.ID,
        A.SHIPMENTLINEID,
        A.SOURCELOCATION,
        A.DESTINATIONLOCATION,
        A.ITEM,
        A.BODLANE,
        A.SOURCINGCONTRACTNUMBER,
        A.TRANSMODE,
        A.CARRIER,
        A.VEHICALID,
        A.OPERATIONTYPE,
        A.SALESORDERDELIVERYID,
        A.FINALDESTINATION
),

STATUS_QLTY_TEMP AS (
    SELECT DISTINCT
        PVT.SHIPMENTID,
        PVT.STATUSREFERENCEDATE AS REFERENCEDATE,
        PVT.STATUS,
        PVT.QUANTITY
    FROM {{ ref('shipment_status_quality_details_master') }} AS PVT
),

STATUS_QLTY AS (
    SELECT *
    FROM STATUS_QLTY_TEMP
    PIVOT( --noqa
        SUM(QUANTITY) FOR STATUS IN (
            'FINISHED' AS FINISHED,
            'IN SOURCE' AS IN_SOURCE,
            'CANCELLED' AS CANCELLED,
            'INVOICE' AS INVOICE,
            'IN DESTINATION' AS IN_DESTINATION,
            'LOADING ORDER' AS LOADING_ORDER,
            'UNLOADED' AS UNLOADED
        )
    )
),

SHIP_DET_TEMP AS (
    SELECT
        A.VERSION_NAME,
        A.SHIPMENT_LINEID,
        A.SOURCE,
        A.LOCATION,
        A.ITEM,
        A.BODLANE,
        A.CONTRACT_LINEID,
        A.TRANSMODE,
        A.CARRIER,
        A.VEHICLEID,
        A.SURVEYOR,
        A.OPERATION_TYPE,
        A.DAY,
        A.ESTIMATED_SHIP_DATE,
        A.ACTUAL_SHIP_DATE,
        A.SHIPMENT_SCHEDULED_DATE,
        A.SHIPMENT_ARRIVAL_DATE,
        A.ESTIMATED_DELIVERY_DATE,
        A.ACTUAL_DELIVERY_DATE,
        A.LOAD_APPLICATION_DATE,
        A.PLANNED_COST,
        A.ACTUAL_COST,
        A.SHIPMENTQUANTITY,
        A.SHIPMENT_DETAILS_STATUS,
        A.SALESORDERDELIVERYID,
        A.FINALDESTINATION,
        SUM(B.INVOICE) AS INVOICE_QTY,
        SUM(B.UNLOADED) AS UNLOADED_QTY
    FROM OUT_SHIPMENTDETAILS_AUX AS A
    LEFT JOIN STATUS_QLTY AS B
        ON A.ID = B.SHIPMENTID
    WHERE A.DAY IS NOT NULL
    GROUP BY
        A.VERSION_NAME,
        A.SHIPMENT_LINEID,
        A.SOURCE,
        A.LOCATION,
        A.ITEM,
        A.BODLANE,
        A.CONTRACT_LINEID,
        A.TRANSMODE,
        A.CARRIER,
        A.VEHICLEID,
        A.SURVEYOR,
        A.OPERATION_TYPE,
        A.DAY,
        A.ESTIMATED_SHIP_DATE,
        A.ACTUAL_SHIP_DATE,
        A.SHIPMENT_SCHEDULED_DATE,
        A.SHIPMENT_ARRIVAL_DATE,
        A.ESTIMATED_DELIVERY_DATE,
        A.ACTUAL_DELIVERY_DATE,
        A.LOAD_APPLICATION_DATE,
        A.PLANNED_COST,
        A.ACTUAL_COST,
        A.SHIPMENTQUANTITY,
        A.SHIPMENT_DETAILS_STATUS,
        A.SALESORDERDELIVERYID,
        A.FINALDESTINATION
),

SHIP_DET AS (
    SELECT
        VERSION_NAME,
        SHIPMENT_LINEID,
        SOURCE,
        LOCATION,
        ITEM,
        BODLANE,
        CONTRACT_LINEID,
        TRANSMODE,
        CARRIER,
        VEHICLEID,
        SURVEYOR,
        OPERATION_TYPE,
        "DAY",
        ESTIMATED_SHIP_DATE,
        ACTUAL_SHIP_DATE,
        SHIPMENT_SCHEDULED_DATE,
        SHIPMENT_ARRIVAL_DATE,
        ESTIMATED_DELIVERY_DATE,
        ACTUAL_DELIVERY_DATE,
        LOAD_APPLICATION_DATE,
        SHIPMENT_DETAILS_STATUS,
        SALESORDERDELIVERYID AS SHIPMENT_SALES_ORDER,
        FINALDESTINATION AS SHIPMENT_FINAL_DESTINATION,
        PLANNED_COST::DECIMAL(20, 3) AS PLANNED_COST,
        ACTUAL_COST::DECIMAL(20, 3) AS ACTUAL_COST,
        SHIPMENTQUANTITY::DECIMAL(20, 3) AS SHIPMENTQUANTITY,
        INVOICE_QTY::DECIMAL(20, 3) AS INVOICE_QTY,
        UNLOADED_QTY::DECIMAL(20, 3) AS UNLOADED_QTY,
        (
            COALESCE(UNLOADED_QTY, 0) - COALESCE(INVOICE_QTY, 0)
        )::DECIMAL(20, 3) AS UNLOADED_VS_INVOICE
    FROM SHIP_DET_TEMP
)

SELECT
    *,
    HASH(*) AS HASH_ID
FROM SHIP_DET
