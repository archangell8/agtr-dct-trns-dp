WITH
SRCDETAILS AS (
    SELECT
        SOURCINGCONTRACTNUMBER,
        SUM(ACTUALCOST)::DECIMAL(20, 3) AS ACTUALCOST,
        SUM(FREIGHTCOST)::DECIMAL(20, 3) AS FREIGHTCOST,
        SUM(PLANNEDCOST)::DECIMAL(20, 3) AS PLANNEDCOST,
        SUM(FREIGHTCADENCE)::DECIMAL(20, 3) AS FREIGHTCADENCE,
        SUM(CONTRACTQUANTITY)::DECIMAL(20, 3) AS CONTRACTQUANTITY,
        SUM(RECEIVEDQUANTITY)::DECIMAL(20, 3) AS RECEIVEDQUANTITY,
        SUM(TORECEIVETOTAL)::DECIMAL(20, 3) AS TORECEIVETOTAL,
        SUM(TORECEIVEFLAT)::DECIMAL(20, 3) AS TORECEIVEFLAT,
        SUM(TORECEIVEPAF)::DECIMAL(20, 3) AS TORECEIVEPAF,
        SUM(CANCELLEDQUANTITY)::DECIMAL(20, 3) AS CANCELLEDQUANTITY,
        (
            SUM(ACTUALCOST) - SUM(FREIGHTCOST)
        )::DECIMAL(20, 3) AS DIFFACTFR,
        (
            SUM(ACTUALCOST) - SUM(PLANNEDCOST)
        )::DECIMAL(20, 3) AS DIFFACTPL
    FROM {{ ref('intstg_sourcing_contract_details') }}
    GROUP BY SOURCINGCONTRACTNUMBER
),

CONTRACTS_TEMP AS (
    SELECT
        A.SOURCINGCONTRACTNUMBER AS CONTRACTLINEID,
        A.CONTRACTSTATUS AS STATUS,
        A.FISCALCONDITION,
        A.TYPE,
        A.PAYMENTDETAILS,
        A.FREIGHTTYPE,
        A.DESTINATIONLOCATIONCODE AS DESTINATION,
        S.CANCELLEDQUANTITY AS CANCELLED,
        S.RECEIVEDQUANTITY AS RECEIVED,
        S.TORECEIVETOTAL AS BALANCE,
        A.SOURCINGCONTRACTNUMBER AS CONTRACTID,
        A.CONTRACTSTATUS AS CONTRACT_STATUS,
        A.TRANSMODE,
        S.FREIGHTCADENCE AS OVERRIDE_DELIVERY_RATE_TON,
        A.DELIVERYBP AS DELIVERY,
        S.CONTRACTQUANTITY AS TOTAL_QTY_TON,
        S.RECEIVEDQUANTITY AS RECEIVED_QTY_TON,
        S.TORECEIVETOTAL AS TO_RECEIVE_TOTAL_TON,
        S.TORECEIVEFLAT AS TO_RECEIVE_FLAT_TON,
        S.TORECEIVEPAF AS TO_RECEIVE_PAF_TON,
        S.CANCELLEDQUANTITY AS CANCELLED_QTY_TON,
        A.CURRENCY,
        S.FREIGHTCOST AS FREIGHT_COST,
        S.PLANNEDCOST AS PLANNED_COST_BOGEY,
        S.ACTUALCOST AS ACTUAL_COST,
        S.DIFFACTFR AS ACTUAL_VS_FREIGHT,
        S.DIFFACTPL AS ACTUAL_VS_BOGEY,
        NULL AS AVAILABLE_QTY_TON,
        NULL AS BLOCKED_QTY_TON,
        A.SALESREP,
        A.HARVEST,
        A.ID,
        A.PRIORITY AS CONTRACT_PRIORITY,
        S.CONTRACTQUANTITY AS QUANTITY,
        S.CONTRACTQUANTITY AS PURCHASED,
        A.ISSLIPWITHCHANGEDDESTINATION,
        'Origination Contract' AS CONTRACT_TYPE,
        'All' AS ALL_CONTRACT,
        'N/A' AS SCHEDULING_STATUS,
        CONCAT(A.ORIGINATIONLOCATION, ' - ', C.BP_NAME)
            AS SOURCEBP,
        CONCAT(A.FARM, ' - ', B.LOCATION_NAME) AS FARM,
        CONCAT(A.DELIVERYBP, ' - ', D.BP_NAME) AS DELIVERY_BP,
        CONCAT(A.DESTINATIONLOCATION, ' - ', F.LOCATION_NAME) AS DELIVERY_UNIT,
        CONCAT(A.ITEM, ' - ', G.ITEMNAME) AS ITEM,
        CONCAT(A.SOURCELOCATION, ' - ', H.LOCATION_NAME) AS PICKUP,
        CONCAT(I.SUPPLIERID, ' - ', I.NAME) AS PRODUCER,
        TO_CHAR(A.DELIVERYSTARTDATE, 'DD-MON-YY')
            AS STARTDATE,
        TO_CHAR(A.DELIVERYENDDATE, 'DD-MON-YY') AS ENDDATE,
        TO_CHAR(
            TRY_TO_DATE(A.PAYMENTDATE, 'DD-MM-YYYY'),
            'DD-MON-YY'
        ) AS PAYMENTDATE,
        TO_CHAR(A.PURCHASEDATE, 'DD-MON-YY') AS PURCHASEDATE,
        CASE
            WHEN A.CURRENCY = 'BRE' THEN CONCAT('R$ ', A.PRICE)
            WHEN A.CURRENCY = 'USM' THEN CONCAT('$ ', A.PRICE)
        END AS PRICE,
        CASE
            WHEN A.FREIGHTTYPE IN ('CIF', 'FOB', 'FBZ') THEN A.FREIGHTCOST
        END AS FREIGHT,
        CASE
            WHEN A.GLOBALINVOICE = 'TRUE' THEN 'Y'
            WHEN A.GLOBALINVOICE = 'FALSE' THEN 'N'
        END AS GLOBAL_INVOICE,
        HASH(
            A.SOURCINGCONTRACTNUMBER, A.SOURCELOCATION, A.DELIVERYENDDATE,
            A.TRANSMODE, A.SUPPLIERID, A.DESTINATIONLOCATIONCODE, A.ITEM,
            A.FREIGHTTYPE
        ) AS HASH_KEY
    FROM {{ ref('intstg_sourcing_contract_details') }} AS A
    LEFT JOIN SRCDETAILS AS S
        ON A.SOURCINGCONTRACTNUMBER = S.SOURCINGCONTRACTNUMBER
    LEFT JOIN {{ ref('location_master') }} AS B
        ON A.FARM = B.LOCATIONID
    LEFT JOIN {{ ref('location_bp_master') }} AS C
        ON A.ORIGINATIONLOCATION = C.BP_NUMBER
    LEFT JOIN {{ ref('location_bp_master') }} AS D
        ON A.DELIVERYBP = D.BP_NUMBER
    LEFT JOIN {{ ref('location_master') }} AS F
        ON A.DESTINATIONLOCATION = F.LOCATIONID
    LEFT JOIN {{ ref('item_master') }} AS G
        ON A.ITEM = G.ITEM
    LEFT JOIN {{ ref('location_master') }} AS H
        ON A.SOURCELOCATION = H.LOCATIONID
    LEFT JOIN {{ ref('supplier_master') }} AS I
        ON A.SUPPLIERID = I.SUPPLIERID
),

