WITH
CTE_VESSEL AS (
    SELECT
        VESSELID,
        TRIPID,
        LOCATION,
        SUM(PLANNEDQUANTITY) AS PLANNEDQUANTITY
    FROM {{ ref('intstg_vesseldetails') }}
    GROUP BY
        VESSELID,
        TRIPID,
        LOCATION
),

CTE_ACTUALVESSELLOAD AS (
    SELECT
        VESSELID,
        SUM(LOADEDQUANTITY) AS ACTVESSELLOADEDQTY
    FROM {{ ref('actual_vessel_load_master') }}
    GROUP BY VESSELID
),

CTE_PORTPENALTY AS (
    SELECT
        A.TYPE,
        B.TRIPID,
        A.ITEMID AS ITEM,
        B.LOCATION,
        A.DATE,
        A.CURRENCY,
        SUM(A.ESTIMATEDVALUE) AS ESTIMATEDVALUE,
        SUM(A.ACTUALVALUE) AS ACTUALVALUE,
        SUM(B.PLANNEDQUANTITY) AS PLANNEDQUANTITY,
        SUM(C.ACTVESSELLOADEDQTY) AS ACTVESSELLOADEDQTY
    FROM {{ ref('port_penalty_master') }} AS A
    LEFT JOIN CTE_VESSEL AS B
        ON A.VESSELID = B.VESSELID
    INNER JOIN CTE_ACTUALVESSELLOAD AS C
        ON A.VESSELID = C.VESSELID
    GROUP BY
        B.TRIPID,
        A.TYPE,
        A.CURRENCY,
        A.DATE,
        A.ITEMID,
        B.LOCATION
)

SELECT
    LOCATION,
    ITEM,
    TRIPID,
    TYPE,
    PLANNEDQUANTITY::DECIMAL(10, 3) AS PLANNEDQTYNOITEM,
    ACTVESSELLOADEDQTY::DECIMAL(10, 3) AS ACTQUANTITYNOITEM,
    ESTIMATEDVALUE::DECIMAL(10, 3) AS ESTIMATED_VALUE,
    ACTUALVALUE::DECIMAL(10, 3) AS ACTUAL_VALUE,
    IFF(
        PLANNEDQUANTITY = 0, 0, (ESTIMATEDVALUE / PLANNEDQUANTITY)
    )::DECIMAL(10, 3) AS VALUE_ESTIMATED_VALUE_PER_TNDIFFERENCE,
    IFF(
        PLANNEDQUANTITY = 0, 0, (ACTUALVALUE / PLANNEDQUANTITY)
    )::DECIMAL(10, 3) AS ACTUAL_VALUE_PER_TN,
    TRY_TO_DATE(DATE, 'DD-MM-YYYY') AS "DATE"
FROM CTE_PORTPENALTY
