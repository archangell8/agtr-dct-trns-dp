WITH
INTSTG_SOURCINGCONTRACTDETAILS AS (
    SELECT
        HASH_ID,
        ID,
        CONTRACTNUMBER AS SOURCINGCONTRACTNUMBER,
        ITEMID AS ITEM,
        SUPPLIERID,
        SOURCE AS SOURCELOCATION,
        DESTINATION AS DESTINATIONLOCATIONCODE,
        DELIVERYUNITID AS DESTINATIONLOCATION,
        DELIVERY AS DELIVERYBP,
        TRANSMODE,
        ORIGINATION AS ORIGINATIONLOCATION,
        FREIGHTTYPE,
        STATUS AS CONTRACTSTATUS,
        SALESREP,
        CURRENCY,
        UOM,
        FARM,
        FISCALCONDITION,
        TYPE,
        PAYMENTDATE,
        PAYMENTDETAILS,
        GLOBALINVOICE,
        HARVEST,
        PRIORITY,
        ISSLIPWITHCHANGEDDESTINATION,
        TRY_TO_TIMESTAMP(PURCHASEDATE, 'DD-MM-YYYY') AS PURCHASEDATE,
        TRY_TO_TIMESTAMP(DELIVERYSTART, 'DD-MM-YYYY') AS DELIVERYSTARTDATE,
        TRY_TO_TIMESTAMP(DELIVERYEND, 'DD-MM-YYYY') AS DELIVERYENDDATE,
        TRY_TO_DECIMAL(PRICE, 20, 3) AS PRICE,
        TRY_TO_DECIMAL(FREIGHTCOST, 20, 3) AS FREIGHTCOST,
        TRY_TO_DECIMAL(ACTUALCOST, 20, 3) AS ACTUALCOST,
        TRY_TO_DECIMAL(
            COALESCE(FREIGHTCADENCE, '1'),
            20, 3
        ) AS FREIGHTCADENCE,
        TRY_TO_DECIMAL(PLANNEDCOST, 20, 3) AS PLANNEDCOST,
        TRY_TO_DECIMAL(QUANTITY, 20, 3) AS CONTRACTQUANTITY,
        TRY_TO_DECIMAL(RECEIVEDQUANTITY, 20, 3) AS RECEIVEDQUANTITY,
        TRY_TO_DECIMAL(TORECEIVETOTAL, 20, 3) AS TORECEIVETOTAL,
        TRY_TO_DECIMAL(TORECEIVEFLAT, 20, 3) AS TORECEIVEFLAT,
        TRY_TO_DECIMAL(TORECEIVEPAF, 20, 3) AS TORECEIVEPAF,
        TRY_TO_DECIMAL(CANCELLEDQUANTITY, 20, 3) AS CANCELLEDQUANTITY,
        TRY_TO_DECIMAL(RECEIVEDPAF, 20, 3) AS RECEIVEDPAF
    FROM {{ ref('sourcing_contract_details_master') }}
    WHERE
        1 = 1
)

SELECT *
FROM INTSTG_SOURCINGCONTRACTDETAILS
