{{
    config(
        materialized='table',
        tags=['master']
    )
}}

WITH
TRANSP_MASTER_ID AS (
    SELECT DISTINCT
        TRANSPORTATIONCONTRACTID,
        TRANSPORTATIONCONTRACTLINEID
    FROM {{ ref('transportation_contract_details_master') }}
),

TRANSP_CONTRACT_CONTROL AS (
    SELECT
        TRANSPORTATIONCONTRACTID,
        TRANSPORTATIONCONTRACTLINEID,
        ROW_NUMBER() OVER (
            PARTITION BY TRANSPORTATIONCONTRACTID
            ORDER BY TRANSPORTATIONCONTRACTLINEID::NUMBER
        ) AS LINEID
    FROM TRANSP_MASTER_ID
),

TRANSP_CONTRACT AS (
    SELECT DISTINCT
        A.TRANSPORTATIONCONTRACTID,
        A.TRANSPORTATIONCONTRACTLINEID AS TCIID,
        A.CURRENCY,
        A.SOURCE AS SOURCELOCATION,
        A.DESTINATION AS DESTINATIONLOCATION,
        A.ITEMID AS L1,
        A.TRANSMODE,
        A.UOM,
        A.QUANTITY AS CONTRACTQUANTITY,
        A.PENALTYFEE,
        A.PAIDPENALTY,
        A.MINTOLERANCE,
        CONCAT(
            A.TRANSPORTATIONCONTRACTID, '-', D.LINEID
        ) AS TRANSPORTATIONCONTRACTLINEID,
        TRY_TO_DATE(A.STARTDATE, 'DD-MM-YYYY') AS CONTRACTSTARTDATE,
        TRY_TO_DATE(A.ENDDATE, 'DD-MM-YYYY') AS CONTRACTENDDATE,
        (A.QUANTITY / (
            DATEDIFF(
                'DAY',
                TRY_TO_DATE(A.STARTDATE, 'DD-MM-YYYY'),
                TRY_TO_DATE(A.ENDDATE, 'DD-MM-YYYY')
            ) + 1
        )) AS CONTRACTDAILYQTY
    FROM {{ ref('transportation_contract_details_master') }} AS A
    INNER JOIN TRANSP_CONTRACT_CONTROL AS D
        ON
            A.TRANSPORTATIONCONTRACTID = D.TRANSPORTATIONCONTRACTID
            AND A.TRANSPORTATIONCONTRACTLINEID = D.TRANSPORTATIONCONTRACTLINEID
)

SELECT
    TRANSPORTATIONCONTRACTID,
    TCIID,
    CURRENCY,
    SOURCELOCATION,
    DESTINATIONLOCATION,
    L1,
    TRANSMODE,
    UOM,
    CONTRACTQUANTITY,
    PENALTYFEE,
    PAIDPENALTY,
    MINTOLERANCE,
    TRANSPORTATIONCONTRACTLINEID,
    CONTRACTSTARTDATE,
    CONTRACTENDDATE,
    CONTRACTDAILYQTY::DECIMAL(20, 3) AS CONTRACTDAILYQTY
FROM TRANSP_CONTRACT
