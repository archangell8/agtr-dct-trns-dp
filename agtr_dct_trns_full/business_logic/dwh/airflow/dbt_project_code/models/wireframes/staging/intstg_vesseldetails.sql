WITH
VESSELDETAILS AS (
    SELECT
        A.ID AS TRIPID,
        A.ID AS VESSELID,
        A.NAME AS VESSELNAME,
        A.CHARTER,
        A.LOCATION,
        A.ITEMID AS ITEM,
        A.UOM,
        A.BUYER,
        A.DESTINATION,
        A.PLANNEDQUANTITY,
        C.DURATION AS PORTDOWNTIMEDURATION,
        TRY_TO_DECIMAL(A.DEMURRAGERATE, 20, 3) AS DEMURRAGERATE,
        TRY_TO_DECIMAL(A.DESPATCHRATE, 20, 3) AS DESPATCHRATE,
        TRY_TO_DATE(A.ESTIMATEDTIMEARRIVAL, 'DD-MM-YYYY')
            AS ESTIMATEDARRIVALTIME,
        TRY_TO_DATE(A.ESTIMATEDTIMEBERTHING, 'DD-MM-YYYY')
            AS ESTIMATEDBERTHINGTIME,
        TRY_TO_DATE(A.ESTIMATEDTIMECOMPLETION, 'DD-MM-YYYY')
            AS ESTIMATEDCOMPLETIONTIME,
        TRY_TO_DATE(A.LAYCANMIN, 'DD-MM-YYYY') AS LAYCANMIN,
        TRY_TO_DATE(A.LAYCANMAX, 'DD-MM-YYYY') AS LAYCANMAX,
        TRY_TO_DATE(C.STARTDATE, 'DD-MM-YYYY') AS PORTDOWNTIMESTARTDATE,
        DATEADD(
            'DAY',
            CEIL(C.DURATION / 24),
            TRY_TO_DATE(C.STARTDATE, 'DD-MM-YYYY')
        ) AS PORTDOWNTIMEENDDATE
    FROM {{ ref('vessel_details_master') }} AS A
    LEFT JOIN {{ ref('port_down_time_master') }} AS C
        ON A.LOCATION = C.LOCATION
)

SELECT
    TRIPID,
    VESSELID,
    VESSELNAME,
    ESTIMATEDARRIVALTIME,
    ESTIMATEDBERTHINGTIME,
    ESTIMATEDCOMPLETIONTIME,
    LAYCANMIN,
    LAYCANMAX,
    CHARTER,
    LOCATION,
    DEMURRAGERATE,
    DESPATCHRATE,
    ITEM,
    PLANNEDQUANTITY,
    UOM,
    PORTDOWNTIMESTARTDATE,
    PORTDOWNTIMEDURATION,
    PORTDOWNTIMEENDDATE,
    BUYER,
    DESTINATION
FROM VESSELDETAILS
