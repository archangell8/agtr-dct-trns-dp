WITH CALLDIARIO AS (
    SELECT
        'CALLDIARIO' AS ORIGEM,
        UOM,
        UPPER(ITEM) AS ITEMID,
        UPPER(REPLACE(TRIM(SOURCE), '	')) AS SOURCEID,
        UPPER(TRANSMODE) AS TRANSMODE,
        TO_CHAR("DAY", 'DD-MM-YYYY') AS "DAY",
        COALESCE(
            TRY_TO_DECIMAL(REPLACE(PLANNEDQUANTITY, ',', '.'), 20, 3),
            0
        ) AS PLANNEDQUANTITY,
        UPPER(FINALDESTINATION) AS FINALDESTINATIONID,
        UPPER(CIF_FOB) AS CIF_FOB,
        UPPER(ISBASELINE) AS ISBASELINE,
        UPPER(OPERATOR) AS OPERATOR,
        REPLACE(UPPER(OPERATIONTYPE), 'FLUXO ORIGEM', 'EMBARQUE NA ORIGEM')
            AS OPERATIONTYPE,
        UPPER(EMBARQUE) AS EMBARQUE
    FROM {{ source('pscfl', 'F_MIN_CALLDIARIO') }}
),

CALLDIARIO_RESUMO AS (
    SELECT
        'CALLDIARIO_RESUMO' AS ORIGEM,
        NULL AS CIF_FOB,
        'FALSE' AS ISBASELINE,
        UOM,
        UPPER(ITEM) AS ITEMID,
        COALESCE(UPPER(SOURCE), 'ALL') AS SOURCEID,
        CASE
            WHEN UPPER(FINALDESTINATION) = 'STM' THEN 'PORTO SANTAREM'
            WHEN UPPER(FINALDESTINATION) = 'TUB' THEN 'PORTO TUBARAO'
            WHEN UPPER(FINALDESTINATION) = 'GJA' THEN 'PORTO SANTOS'
            WHEN UPPER(FINALDESTINATION) = 'PDM' THEN 'PORTO PDM VLI'
            WHEN UPPER(FINALDESTINATION) = 'TEGRAM' THEN 'PORTO TEGRAM'
            WHEN UPPER(FINALDESTINATION) = 'BAR' THEN 'PORTO BARCARENA'
            WHEN UPPER(FINALDESTINATION) = 'TMIB' THEN 'PORTO TMIB'
            WHEN UPPER(FINALDESTINATION) = 'ATU' THEN 'PORTO ARATU'
            WHEN UPPER(FINALDESTINATION) = 'PGA' THEN 'PORTO PARANAGUA'
            WHEN UPPER(FINALDESTINATION) = 'SFS'
                THEN 'PORTO SAO FRANCISCO TERLOGS'
            ELSE UPPER(FINALDESTINATION)
        END AS FINALDESTINATIONID,
        CASE
            WHEN UPPER(TRANSMODE) LIKE 'ROD%'
                THEN 'ROD'
            WHEN UPPER(TRANSMODE) LIKE '%ATT-SFS%'
                THEN 'FLO'
            WHEN UPPER(TRANSMODE) LIKE '%MGA-SFS%'
                THEN 'FMN'
            WHEN UPPER(TRANSMODE) LIKE '%PPF%'
                THEN 'FPF'
            WHEN UPPER(TRANSMODE) LIKE '%PTN%'
                THEN 'FPT'
            ELSE UPPER(TRANSMODE)
        END AS TRANSMODE,
        TO_CHAR("MONTH", 'DD-MM-YYYY') AS "DAY",
        COALESCE(
            REPLACE(PLANNEDQUANTITY, ',', '.')::DECIMAL(20, 3),
            0
        ) AS PLANNEDQUANTITY,
        UPPER(OPERATOR) AS OPERATOR,
        REPLACE(
            UPPER(OPERATIONTYPE), 'DISPONÍVEL PARA EXECUÇÃO',
            'DISPONIVEL PARA EMBARQUE'
        ) AS OPERATIONTYPE,
        REPLACE(
            UPPER(OPERATIONTYPE), 'DISPONÍVEL PARA EXECUÇÃO',
            'DISPONIVEL PARA EMBARQUE'
        ) AS EMBARQUE
    FROM {{ source('pscfl', 'F_MIN_CALLDIARIO_RESUMO') }}
),

DESCARGA AS (
    SELECT
        'DESCARGA' AS ORIGEM,
        'ALL' AS SOURCEID,
        NULL AS CIF_FOB,
        'FALSE' AS ISBASELINE,
        'TN' AS UOM,
        'DESCARGA NO DESTINO' AS OPERATIONTYPE,
        'DESCARGA NO DESTINO' AS EMBARQUE,
        UPPER(PRODUCT) AS ITEMID,
        UPPER(MODAL) AS TRANSMODE,
        TO_CHAR("DIA", 'DD-MM-YYYY') AS "DAY",
        COALESCE(
            REPLACE("VOLUME", ',', '.')::DECIMAL(20, 3),
            0
        ) AS PLANNEDQUANTITY,
        CASE
            WHEN UPPER(LOCATION) = 'TBD'
                THEN '624'
            ELSE UPPER(LOCATION)
        END AS FINALDESTINATIONID,
        UPPER(OPERATOR) AS OPERATOR
    FROM {{ source('pscfl', 'F_MIN_DESCARGA_PORTO') }}
    WHERE
        UPPER(SHIPPER) = 'CARGILL'
        AND UPPER(PRODUCT) <> 'TALLOW'
),

SNOE_STG AS (
    SELECT
        ITEMID,
        SOURCEID,
        TRANSMODE,
        "DAY",
        PLANNEDQUANTITY,
        FINALDESTINATIONID,
        CIF_FOB,
        ISBASELINE,
        UOM,
        OPERATOR,
        OPERATIONTYPE,
        EMBARQUE,
        ORIGEM
    FROM CALLDIARIO

    UNION ALL

    SELECT
        ITEMID,
        SOURCEID,
        TRANSMODE,
        "DAY",
        PLANNEDQUANTITY,
        FINALDESTINATIONID,
        CIF_FOB,
        ISBASELINE,
        UOM,
        OPERATOR,
        OPERATIONTYPE,
        EMBARQUE,
        ORIGEM
    FROM CALLDIARIO_RESUMO

    UNION ALL

    SELECT
        ITEMID,
        SOURCEID,
        TRANSMODE,
        "DAY",
        PLANNEDQUANTITY,
        FINALDESTINATIONID,
        CIF_FOB,
        ISBASELINE,
        UOM,
        OPERATOR,
        OPERATIONTYPE,
        EMBARQUE,
        ORIGEM
    FROM DESCARGA
),

SNOE AS (
    SELECT
        ORIGEM,
        ITEMID,
        SOURCEID,
        "DAY",
        PLANNEDQUANTITY,
        FINALDESTINATIONID,
        CIF_FOB,
        UOM,
        EMBARQUE,
        CASE
            WHEN UPPER(TRANSMODE) IS NULL
                THEN 'ROD'
            WHEN UPPER(TRANSMODE) = 'NÃO ENCONTRADO'
                THEN 'ROD'
            WHEN UPPER(TRANSMODE) = 'BARCAÇA'
                THEN 'HIDRO'
            ELSE UPPER(TRANSMODE)
        END AS TRANSMODE,
        COALESCE(NULLIF(ISBASELINE, ''), 'FALSE') AS ISBASELINE,
        COALESCE(NULLIF(OPERATOR, ''), 'N/A') AS OPERATOR,
        COALESCE(NULLIF(OPERATIONTYPE, ''), 'N/A') AS OPERATIONTYPE
    FROM SNOE_STG
    WHERE
        UPPER(SOURCEID) NOT IN ('IGNORAR', 'NÃO ENCONTRADO')
        AND TRY_TO_DATE("DAY", 'DD-MM-YYYY') >= '2025-01-01'::DATE
)

SELECT
    ITEMID,
    SOURCEID,
    TRANSMODE,
    "DAY",
    PLANNEDQUANTITY,
    FINALDESTINATIONID,
    CIF_FOB,
    ISBASELINE,
    UOM,
    OPERATOR,
    OPERATIONTYPE,
    EMBARQUE,
    ORIGEM
FROM SNOE
