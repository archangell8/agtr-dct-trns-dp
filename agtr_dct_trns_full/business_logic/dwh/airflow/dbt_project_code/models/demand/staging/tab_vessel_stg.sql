WITH VESSEL_TEMP AS (
    SELECT
        V.ORIGEM,
        COALESCE(NULLIF(V.ID, ''), 'N/A') AS ID,
        COALESCE(NULLIF(V.NAME, ''), 'N/A') AS NAME,
        NULLIF(V.ESTIMATEDTIMEARRIVAL, '') AS ESTIMATEDTIMEARRIVAL,
        NULLIF(V.ESTIMATEDTIMEBERTHING, '') AS ESTIMATEDTIMEBERTHING,
        NULLIF(V.ESTIMATEDTIMECOMPLETION, '') AS ESTIMATEDTIMECOMPLETION,
        COALESCE(NULLIF(V.LAYCANMIN, ''), 'N/A') AS LAYCANMIN,
        COALESCE(NULLIF(V.LAYCANMAX, ''), 'N/A') AS LAYCANMAX,
        COALESCE(NULLIF(V.CHARTER, ''), 'N/A') AS CHARTER,
        COALESCE(NULLIF(V.LOCATION, ''), 'N/A') AS LOCATION,
        COALESCE(NULLIF(D.DEMURRAGE_RATE, ''), 'N/A') AS DEMURRAGERATE,
        COALESCE(NULLIF(D.DESPATCH_RATE, ''), 'N/A') AS DESPATCHRATE,
        COALESCE(NULLIF(V.CONTRATO, ''), 'N/A') AS CAK
    FROM {{ ref('vw_vessel_entire_stg') }} AS V
    LEFT JOIN {{ ref('vw_demurrage_despatch_stg') }} AS D
        ON V.MERGE_ID = D.MERGE_ID
),

PDF AS (
    SELECT
        'PDF' AS ORIGEM,
        COALESCE(NULLIF(V.ID, ''), 'N/A') AS ID,
        COALESCE(NULLIF(V.NAME, ''), 'N/A') AS NAME,
        NULLIF(V.ESTIMATEDTIMEARRIVAL, '') AS ESTIMATEDTIMEARRIVAL,
        NULLIF(V.ESTIMATEDTIMEBERTHING, '') AS ESTIMATEDTIMEBERTHING,
        NULLIF(V.ESTIMATEDTIMECOMPLETION, '') AS ESTIMATEDTIMECOMPLETION,
        COALESCE(NULLIF(V.LAYCANMIN, ''), 'N/A') AS LAYCANMIN,
        COALESCE(NULLIF(V.LAYCANMAX, ''), 'N/A') AS LAYCANMAX,
        COALESCE(NULLIF(V.CHARTER, ''), 'N/A') AS CHARTER,
        COALESCE(NULLIF(V.LOCATION, ''), 'N/A') AS LOCATION,
        COALESCE(NULLIF(V.DEMURRAGERATE, ''), 'N/A') AS DEMURRAGERATE,
        COALESCE(NULLIF(V.DESPATCHRATE, ''), 'N/A') AS DESPATCHRATE,
        COALESCE(NULLIF(V.CAK, ''), 'N/A') AS CAK
    FROM {{ source('pscfl', 'F_MIN_VESSEL') }} AS V
),

VESSEL_INI AS (
    SELECT * FROM VESSEL_TEMP
    UNION ALL
    SELECT * FROM PDF
),

CTE_CAK_FTS AS (
    SELECT
        DS_VESSEL,
        CD_NICK_BUYER AS BUYER,
        DT_FROM_LAYCAN AS LAYCANMIN,
        DT_TO_LAYCAN AS LAYCANMAX,
        MAX(VL_DEMURRAGE_RATE) AS DEMURRAGERATE,
        MAX(VL_DESPATCH_RATE) AS DESPATCHRATE,
        LISTAGG(
            DISTINCT DS_DISCHARGE_COUNTRY, ','
        ) WITHIN GROUP (ORDER BY DS_DISCHARGE_COUNTRY) AS DESTINATION,
        REPLACE(DS_CAK_NBR, ' ', '') AS CAK
    FROM {{ source('fts', 'CAK_OVER_UNDER') }}
    GROUP BY
        DS_VESSEL,
        CD_NICK_BUYER,
        DT_FROM_LAYCAN,
        DT_TO_LAYCAN,
        DS_CAK_NBR
),

VESSEL AS (
    SELECT
        COALESCE(NULLIF(VES.ID, ''), 'N/A') AS ID,
        COALESCE(NULLIF(VES.NAME, ''), 'N/A') AS NAME,
        COALESCE(NULLIF(VES.ESTIMATEDTIMEARRIVAL, ''), 'N/A')
            AS ESTIMATEDTIMEARRIVAL,
        COALESCE(NULLIF(VES.ESTIMATEDTIMEBERTHING, ''), 'N/A')
            AS ESTIMATEDTIMEBERTHING,
        COALESCE(NULLIF(VES.ESTIMATEDTIMECOMPLETION, ''), 'N/A')
            AS ESTIMATEDTIMECOMPLETION,
        COALESCE(NULLIF(VES.LAYCANMIN, ''), 'N/A') AS LAYCANMIN,
        COALESCE(NULLIF(VES.LAYCANMAX, ''), 'N/A') AS LAYCANMAX,
        COALESCE(NULLIF(VES.CHARTER, ''), 'N/A') AS CHARTER,
        COALESCE(NULLIF(VES.LOCATION, ''), 'N/A') AS LOCATION,
        COALESCE(NULLIF(VES.DEMURRAGERATE, ''), 'N/A') AS DEMURRAGERATE,
        COALESCE(NULLIF(VES.DESPATCHRATE, ''), 'N/A') AS DESPATCHRATE,
        COALESCE(NULLIF(FTS.CAK, ''), 'N/A') AS CAK,
        COALESCE(NULLIF(FTS.BUYER, ''), 'N/A') AS BUYER,
        COALESCE(NULLIF(FTS.DESTINATION, ''), 'N/A') AS DESTINATION
    FROM VESSEL_INI AS VES
    LEFT JOIN CTE_CAK_FTS AS FTS
        ON
            VES.CAK = FTS.CAK
            AND VES.NAME = FTS.DS_VESSEL
)

SELECT
    *,
    HASH(*) AS HASH_ID
FROM VESSEL
