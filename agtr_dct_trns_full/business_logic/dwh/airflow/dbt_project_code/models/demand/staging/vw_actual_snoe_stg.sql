WITH ACTUAL_SNOE AS (
    SELECT
        ITEMID,
        SOURCEID,
        TRANSMODE,
        FINALDESTINATIONID,
        "DAY",
        UOM,
        OPERATOR,
        OPERATIONTYPE,
        SUM(PLANNEDQUANTITY) AS PLANNEDQUANTITY
    FROM {{ ref('vw_snoe_stg') }}
    WHERE TO_DATE("DAY", 'DD-MM-YYYY') < CURRENT_DATE()
    GROUP BY
        ITEMID,
        SOURCEID,
        TRANSMODE,
        FINALDESTINATIONID,
        "DAY",
        UOM,
        OPERATOR,
        OPERATIONTYPE
)

SELECT
    COALESCE(ITEMID, 'N/A') AS ITEMID,
    COALESCE(SOURCEID, 'N/A') AS SOURCEID,
    COALESCE(TRANSMODE, 'N/A') AS TRANSMODE,
    COALESCE(FINALDESTINATIONID, 'N/A') AS FINALDESTINATIONID,
    COALESCE("DAY", 'N/A') AS "DAY",
    COALESCE(PLANNEDQUANTITY::DECIMAL(18, 3), 0) AS PLANNEDQUANTITY,
    COALESCE(UOM, 'N/A') AS UOM,
    COALESCE(OPERATOR, 'N/A') AS OPERATOR,
    COALESCE(OPERATIONTYPE, 'N/A') AS OPERATIONTYPE,
    HASH(*) AS HASH_ID
FROM ACTUAL_SNOE
WHERE
    1 = 1
    --AND COALESCE(PLANNEDQUANTITY::DECIMAL(18, 3), 0) != 0
