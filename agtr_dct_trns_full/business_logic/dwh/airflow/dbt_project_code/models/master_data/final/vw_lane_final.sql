WITH FINAL AS (
    SELECT
        0 AS IDX,
        'LANEID' AS LANEID,
        'LOCATION_FROM' AS LOCATION_FROM,
        'LOCATION_TO' AS LOCATION_TO,
        'TRANSMODE' AS TRANSMODE,
        'LANE_DESCRIPTION' AS LANE_DESCRIPTION,
        'LOCATION_FROM_UNIT_STRUCTURE' AS LOCATION_FROM_UNIT_STRUCTURE,
        'LOCATION_TO_UNIT_STRUCTURE' AS LOCATION_TO_UNIT_STRUCTURE,
        'ISLANE_OPTIMIZABLE' AS ISLANE_OPTIMIZABLE,
        NULL AS HASH_ID,
        NULL AS CDP_TRANSACTION,
        (SELECT CDP_TIMESTAMP FROM {{ ref('tab_cdp_timestamp_models') }} WHERE MODEL_NAME = UPPER('lane')) AS CDP_TIMESTAMP_FULL, -- noqa
        (SELECT CDP_TIMESTAMP FROM {{ ref('tab_cdp_timestamp_models') }} WHERE MODEL_NAME = UPPER('lane')) AS CDP_TIMESTAMP_INC, -- noqa
        'CDP_TIMESTAMP_O9' AS CDP_TIMESTAMP_O9

    UNION ALL

    SELECT
        1 AS IDX,
        LANEID::STRING,
        LOCATION_FROM::STRING,
        LOCATION_TO::STRING,
        TRANSMODE::STRING,
        LANE_DESCRIPTION::STRING,
        LOCATION_FROM_UNIT_STRUCTURE::STRING,
        LOCATION_TO_UNIT_STRUCTURE::STRING,
        ISLANE_OPTIMIZABLE::STRING,
        HASH_ID,
        CDP_TRANSACTION,
        CDP_TIMESTAMP_FULL,
        CDP_TIMESTAMP_INC,
        CDP_TIMESTAMP_O9::STRING
    FROM {{ ref('lane') }}
)

SELECT
    LANEID,
    LOCATION_FROM,
    LOCATION_TO,
    TRANSMODE,
    LANE_DESCRIPTION,
    LOCATION_FROM_UNIT_STRUCTURE,
    LOCATION_TO_UNIT_STRUCTURE,
    ISLANE_OPTIMIZABLE,
    HASH_ID,
    CDP_TRANSACTION,
    CDP_TIMESTAMP_FULL,
    CDP_TIMESTAMP_INC,
    CDP_TIMESTAMP_O9
FROM FINAL
ORDER BY IDX ASC
