WITH
CTE_UDC_MAPPING AS (
    SELECT
        CATEGORY,
        STAGE,
        SOURCE_CODE,
        TARGET_CODE,
        TARGET_NUMBER
    FROM {{ source('pscfl', 'F_MIN_DCT_UDC') }}
    WHERE
        1 = 1
        AND STATUS = 'ATIVO'
),

CTE_SALES_ORDER_DELIVERY AS (
    SELECT DISTINCT F4211.SDSHAN
    FROM {{ source('jde', 'F4211') }} AS F4211
    WHERE
        1 = 1
        AND F4211.SDLNTY != 'BX'
        AND F4211.SDUOM IN ('PK', 'CX', 'KG', 'TB', 'SC', 'M3')
        AND (
            F4211.SDLTTR != '980'
            OR F4211.SDNXTR IN ('521', '528', '530', '560', '999')
        )
        AND F4211.SDDCTO IN (
            SELECT UDC.SOURCE_CODE
            FROM CTE_UDC_MAPPING AS UDC
            WHERE
                TRIM(UDC.CATEGORY) = 'SALES_ORDER_DELIVERY'
                AND TRIM(UDC.STAGE) = 'ORDERS'
        )
        AND F4211.SDKCOO IN ('52171', '52180', '52191')
        AND (
            F4211.SDTRDJ >= 124001
            OR
            F4211.SDDRQJ >= 124001
            OR
            F4211.SDADDJ >= 124001
        )
        AND {{ filter_remove_jde_delete_data('F4211') }} -- noqa
),

CTE_BP_FILTER AS (
    SELECT DISTINCT DELIVERY AS LOC
    FROM {{ ref('tab_sourcing_contract_stg') }}
    UNION DISTINCT
    SELECT DISTINCT ORIGINATION AS LOC
    FROM {{ ref('tab_sourcing_contract_stg') }}
    UNION DISTINCT
    SELECT DISTINCT NEGOTIATION_BRANCH_PLANT AS LOC
    FROM {{ ref('tab_shipment_fichas_jde_stg') }}
    UNION DISTINCT
    SELECT DISTINCT BRANCH_PLANT_DESTINATION AS LOC
    FROM {{ ref('tab_shipment_fichas_jde_stg') }}
    UNION DISTINCT
    SELECT DISTINCT BRANCH_PLANT_SOURCE AS LOC
    FROM {{ ref('tab_shipment_loads_faturados_jde_stg') }}
    UNION DISTINCT
    SELECT DISTINCT BRANCH_PLANT_DESTINATION AS LOC
    FROM {{ ref('tab_shipment_loads_faturados_jde_stg') }}
    UNION DISTINCT
    SELECT DISTINCT BP_ORIGEM AS LOC
    FROM {{ ref('tab_shipment_ctms_oc_stg') }}
    UNION DISTINCT
    SELECT DISTINCT BP_DESTINO AS LOC
    FROM {{ ref('tab_shipment_ctms_oc_stg') }}
    UNION DISTINCT
    SELECT DISTINCT BP_ORIGEM AS LOC
    FROM {{ source('ctms', 'VW_DCT_TN') }}
    UNION DISTINCT
    SELECT DISTINCT BP_DESTINO AS LOC
    FROM {{ source('ctms', 'VW_DCT_TN') }}
    UNION DISTINCT
    SELECT DISTINCT BP_ORIGEM AS LOC
    FROM {{ ref('tab_cmm_stg') }}
    UNION DISTINCT
    SELECT DISTINCT BP_DESTINO AS LOC
    FROM {{ ref('tab_cmm_stg') }}
    UNION DISTINCT
    SELECT DISTINCT BP_ORIGEM AS LOC
    FROM {{ source('ctms', 'VW_DCT_LOAD') }}
    UNION DISTINCT
    SELECT DISTINCT BP_DESTINO AS LOC
    FROM {{ source('ctms', 'VW_DCT_LOAD') }}
    UNION DISTINCT
    SELECT DISTINCT BP_ENTREGA_SLIP AS LOC
    FROM {{ source('pscfl', 'F_MIN_ATIVO_IBP') }}
),

CTE_PICKUP_FILTER AS (
    SELECT DISTINCT TRIM(SOURCE) AS LOC
    FROM {{ ref('tab_sourcing_contract_stg') }}
    UNION DISTINCT
    SELECT DISTINCT TRIM(SUPPLIERID) AS LOC
    FROM {{ ref('tab_sourcing_contract_stg') }}
    UNION DISTINCT
    SELECT DISTINCT TRIM(FARM) AS LOC
    FROM {{ ref('tab_sourcing_contract_stg') }}
    UNION DISTINCT
    SELECT DISTINCT TRIM(FARM_ADDRESS) AS LOC
    FROM {{ ref('tab_shipment_fichas_jde_stg') }}
    UNION DISTINCT
    SELECT DISTINCT TRIM(ADDRESS_DESTINATION) AS LOC
    FROM {{ ref('tab_shipment_fichas_jde_stg') }}
    UNION DISTINCT
    SELECT DISTINCT TO_CHAR(ROUND(ADDRESS_DESTINATION, 0)) AS LOC
    FROM {{ ref('tab_shipment_loads_faturados_jde_stg') }}
    UNION DISTINCT
    SELECT DISTINCT TO_CHAR(ROUND(ADDRESS_COLETA, 0)) AS LOC
    FROM {{ ref('tab_shipment_loads_faturados_jde_stg') }}
    UNION DISTINCT
    SELECT DISTINCT TO_CHAR(ROUND(ADDRESS_DESTINATION, 0)) AS LOC
    FROM {{ ref('tab_shipment_loads_abertos_jde_stg') }}
    UNION DISTINCT
    SELECT DISTINCT TRIM(ADRESS_COLETA) AS LOC
    FROM {{ ref('tab_shipment_ctms_oc_stg') }}
    UNION DISTINCT
    SELECT DISTINCT TRIM(BP_ORIGEM) AS LOC
    FROM {{ ref('tab_shipment_ctms_oc_stg') }}
    UNION DISTINCT
    SELECT DISTINCT ADRESS_COLETA AS LOC
    FROM {{ source('ctms', 'VW_DCT_TN') }}
    UNION DISTINCT
    SELECT DISTINCT BP_DESTINO AS LOC
    FROM {{ source('ctms', 'VW_DCT_TN') }}
    UNION DISTINCT
    SELECT DISTINCT ADDRESS_PRODUTOR AS LOC
    FROM {{ ref('tab_cmm_stg') }}
    UNION DISTINCT
    SELECT DISTINCT ADDRESS_COLETA AS LOC
    FROM {{ ref('tab_cmm_stg') }}
    UNION DISTINCT
    SELECT DISTINCT ADRESS_ORIGEM AS LOC
    FROM {{ source('ctms', 'VW_DCT_LOAD') }}
    UNION DISTINCT
    SELECT DISTINCT SDSHAN AS LOC
    FROM CTE_SALES_ORDER_DELIVERY
),

VIRTUAL_LOCATION AS (
    SELECT DISTINCT -- noqa
        LOCATION_UNIT_ID AS LOCATIONID,
        'VIRTUAL' AS LOCATION_TYPE
    FROM {{ ref('tab_location_internal_stg') }}
    WHERE
        1 = 1
        AND LOCATION_UNIT_STRUCTURE = 'ARMAZÉM'
    GROUP BY
        LOCATION_UNIT_ID
    HAVING
        LISTAGG(LOCATION_TYPE, ', ') NOT LIKE '%FÍSICA%'
),

LOC_AGRUPADA AS (
    SELECT DISTINCT
        LOC.LOCATION_UNIT_ID AS LOCATIONID,
        LOC.ZIP,
        LOC.ADDRESS,
        'N/A' AS ROTEIRO_OBSERVACOES,
        'N/A' AS RESTRICOES,
        COALESCE(GRP.ORIGINATION_STRUCTURE, 'N/A') AS LOCATION_UNIT_STRUCTURE,
        COALESCE(LOC.LOCATION_GROUP, 'N/A') AS LOCATION_GROUP,
        COALESCE(LOC.LOCATION_COUNTRY, 'N/A') AS LOCATION_COUNTRY,
        COALESCE(GRP.LOCATION_REGION, LOC.LOCATION_REGION) AS LOCATION_REGION,
        COALESCE(LOC.LOCATION_NAME, 'N/A') AS LOCATION_NAME,
        COALESCE(LOC.LOCATION_CODE, LOC.LOCATION_SUB_REGION) AS LOCATION_CODE,
        COALESCE(LOC.COMMENTS, 'N/A') AS COMMENTS,
        COALESCE(LOC_TYPE.LOCATION_TYPE, 'PHYSICAL') AS LOCATION_TYPE,
        COALESCE(GRP.CITY, LOC.CITY) AS CITY,
        COALESCE(GRP.LONGITUDE, LOC.LONGITUDE) AS LONGITUDE,
        COALESCE(GRP.LATITUDE, LOC.LATITUDE) AS LATITUDE,
        COALESCE(GRP.STATE, LOC.STATE) AS "STATE",
        COALESCE(GRP.ORIGIN_OWNERSHIP, 'N/A') AS LOCATION_OWNERSHIP,
        COALESCE(LOC.OPERATOR, 'N/A') AS OPERATOR,
        COALESCE(LOC.LOCATION_IBP_ASSET, 'N/A') AS LOCATION_IBP_ASSET,
        COALESCE(
            SUBREG.TARGET_CODE, LOC.LOCATION_SUB_REGION, 'N/A'
        ) AS LOCATION_SUB_REGION
    FROM {{ ref('tab_location_internal_stg') }} AS LOC
    LEFT JOIN {{ source('pscfl', 'F_MIN_LOCATION_AGRUPADA') }} AS GRP
        ON LOC.LOCATION_UNIT_ID = GRP.UNIT_ID
    LEFT JOIN CTE_UDC_MAPPING AS SUBREG
        ON
            LOC.LOCATION_UNIT_ID = SUBREG.SOURCE_CODE
            AND SUBREG.CATEGORY = 'LOCATION_SUBREGION'
            AND SUBREG.STAGE = 'LOCAITONID'
    LEFT JOIN VIRTUAL_LOCATION AS LOC_TYPE
        ON LOC.LOCATION_UNIT_ID = LOC_TYPE.LOCATIONID
    INNER JOIN CTE_BP_FILTER AS FILTER_
        ON LOC.LOCATIONID = FILTER_.LOC
    WHERE
        GRP.ORIGINATION_STRUCTURE IS NOT NULL
        AND LOC.LOCATION_IBP_ASSET != 'N/A'
),

LOC_PONTO_COLETA AS (
    SELECT DISTINCT
        LOC.LOCATIONID,
        LOC.ZIP,
        LOC.ADDRESS,
        REST.ROTEIRO_OBSERVACOES,
        REST.RESTRICOES,
        COALESCE(LOC.LOCATION_UNIT_STRUCTURE, 'N/A') AS LOCATION_UNIT_STRUCTURE,
        COALESCE(LOC.LOCATION_GROUP, 'N/A') AS LOCATION_GROUP,
        COALESCE(LOC.LOCATION_COUNTRY, 'N/A') AS LOCATION_COUNTRY,
        COALESCE(LOC.LOCATION_REGION, 'N/A') AS LOCATION_REGION,
        COALESCE(LOC.LOCATION_NAME, 'N/A') AS LOCATION_NAME,
        COALESCE(LOC.LOCATION_CODE, 'N/A') AS LOCATION_CODE,
        COALESCE(LOC.COMMENTS, 'N/A') AS COMMENTS,
        TRIM('PHYSICAL') AS LOCATION_TYPE,
        COALESCE(LOC.CITY, 'N/A') AS CITY,
        COALESCE(LOC.LONGITUDE, '0') AS LONGITUDE,
        COALESCE(LOC.LATITUDE, '0') AS LATITUDE,
        COALESCE(LOC.STATE, 'N/A') AS "STATE",
        COALESCE(LOC.LOCATION_OWNERSHIP, 'N/A') AS LOCATION_OWNERSHIP,
        COALESCE(LOC.OPERATOR, 'N/A') AS OPERATOR,
        COALESCE(LOC.LOCATION_SUB_REGION, 'N/A') AS LOCATION_IBP_ASSET,
        COALESCE(LOC.LOCATION_SUB_REGION, 'N/A') AS LOCATION_SUB_REGION
    FROM {{ ref('tab_location_internal_stg') }} AS LOC
    LEFT JOIN {{ source('pscfl','F_MIN_LOCATION_RESTRICTION') }} AS REST
        ON LOC.LOCATIONID = REST.ADDRESS_LOCAL_COLETA
    INNER JOIN CTE_PICKUP_FILTER AS FILTER_
        ON LOC.LOCATIONID = FILTER_.LOC
    WHERE
        LOCATION_UNIT_STRUCTURE IN ('PONTO DE COLETA', 'CLIENTE OUTBOUND')
        AND LOCATION_SUB_REGION != 'N/A'
),

LOC_OTHERS AS (
    SELECT DISTINCT
        LOCATIONID,
        ZIP,
        ADDRESS,
        'N/A' AS ROTEIRO_OBSERVACOES,
        'N/A' AS RESTRICOES,
        COALESCE(LOCATION_UNIT_STRUCTURE, 'N/A') AS LOCATION_UNIT_STRUCTURE,
        COALESCE(LOCATION_GROUP, 'N/A') AS LOCATION_GROUP,
        COALESCE(LOCATION_COUNTRY, 'N/A') AS LOCATION_COUNTRY,
        COALESCE(LOCATION_REGION, 'N/A') AS LOCATION_REGION,
        COALESCE(LOCATION_SUB_REGION, 'N/A') AS LOCATION_SUB_REGION,
        COALESCE(LOCATION_NAME, 'N/A') AS LOCATION_NAME,
        COALESCE(LOCATION_CODE, LOCATION_SUB_REGION) AS LOCATION_CODE,
        COALESCE(COMMENTS, 'N/A') AS COMMENTS,
        TRIM('PHYSICAL') AS LOCATION_TYPE,
        COALESCE(CITY, 'N/A') AS CITY,
        COALESCE(LONGITUDE, '0') AS LONGITUDE,
        COALESCE(LATITUDE, '0') AS LATITUDE,
        COALESCE(STATE, 'N/A') AS "STATE",
        COALESCE(LOCATION_OWNERSHIP, 'N/A') AS LOCATION_OWNERSHIP,
        COALESCE(OPERATOR, 'N/A') AS OPERATOR,
        COALESCE(LOCATION_IBP_ASSET, LOCATION_SUB_REGION) AS LOCATION_IBP_ASSET
    FROM {{ source('pscfl','F_MIN_LOCATION_OTHERS') }}
),

LOC_ESTADOS AS (
    SELECT DISTINCT
        LOC.STATE AS LOCATIONID,
        'MERCADO INTERNO' AS LOCATION_UNIT_STRUCTURE,
        'CASC SA' AS LOCATION_GROUP,
        'BR' AS LOCATION_COUNTRY,
        LOC.STATE AS LOCATION_SUB_REGION,
        ST.STATE AS LOCATION_NAME,
        LOC.STATE AS LOCATION_CODE,
        'N/A' AS ZIP,
        'N/A' AS "ADDRESS",
        'N/A' AS COMMENTS,
        'VIRTUAL' AS LOCATION_TYPE,
        'N/A' AS CITY,
        '0' AS LONGITUDE,
        '0' AS LATITUDE,
        LOC.STATE,
        'MERCADO INTERNO' AS LOCATION_OWNERSHIP,
        'N/A' AS OPERATOR,
        LOC.STATE AS LOCATION_IBP_ASSET,
        'N/A' AS ROTEIRO_OBSERVACOES,
        'N/A' AS RESTRICOES,
        CASE
            WHEN LOC.STATE = 'MG' THEN 'SUDESTE'
            WHEN LOC.STATE = 'SP' THEN 'SUDESTE'
            WHEN LOC.STATE = 'TO' THEN 'NORTE'
            WHEN LOC.STATE = 'MT' THEN 'CENTRO'
            WHEN LOC.STATE = 'ES' THEN 'SUDESTE'
            ELSE LOC.LOCATION_REGION
        END AS LOCATION_REGION
    FROM {{ ref('tab_location_internal_stg') }} AS LOC
    INNER JOIN {{ source('pscfl','F_MIN_LOCATION_UF_STATE') }} AS ST
        ON LOC.STATE = ST.UF
),

LOCATION AS (
    SELECT
        LOCATIONID,
        LOCATION_UNIT_STRUCTURE,
        LOCATION_GROUP,
        LOCATION_COUNTRY,
        LOCATION_REGION,
        DECODE(
            LOCATION_SUB_REGION, 'GJA', 'SP', LOCATION_SUB_REGION
        ) AS LOCATION_SUB_REGION,
        LOCATION_NAME,
        LOCATION_CODE,
        ZIP,
        ADDRESS,
        COMMENTS,
        LOCATION_TYPE,
        CITY,
        LONGITUDE,
        LATITUDE,
        STATE,
        LOCATION_OWNERSHIP,
        OPERATOR,
        LOCATION_IBP_ASSET,
        ROTEIRO_OBSERVACOES,
        RESTRICOES
    FROM LOC_AGRUPADA
    UNION DISTINCT
    SELECT
        LOCATIONID,
        LOCATION_UNIT_STRUCTURE,
        LOCATION_GROUP,
        LOCATION_COUNTRY,
        LOCATION_REGION,
        DECODE(LOCATION_SUB_REGION, 'GJA', 'SP', LOCATION_SUB_REGION)
            AS LOCATION_SUB_REGION,
        LOCATION_NAME,
        LOCATION_CODE,
        ZIP,
        ADDRESS,
        COMMENTS,
        LOCATION_TYPE,
        CITY,
        LONGITUDE,
        LATITUDE,
        STATE,
        LOCATION_OWNERSHIP,
        OPERATOR,
        LOCATION_IBP_ASSET,
        ROTEIRO_OBSERVACOES,
        RESTRICOES
    FROM LOC_PONTO_COLETA
    UNION DISTINCT
    SELECT
        LOCATIONID,
        LOCATION_UNIT_STRUCTURE,
        LOCATION_GROUP,
        LOCATION_COUNTRY,
        LOCATION_REGION,
        DECODE(
            LOCATION_SUB_REGION, 'GJA', 'SP', LOCATION_SUB_REGION
        ) AS LOCATION_SUB_REGION,
        LOCATION_NAME,
        LOCATION_CODE,
        ZIP,
        ADDRESS,
        COMMENTS,
        LOCATION_TYPE,
        CITY,
        LONGITUDE,
        LATITUDE,
        STATE,
        LOCATION_OWNERSHIP,
        OPERATOR,
        LOCATION_IBP_ASSET,
        ROTEIRO_OBSERVACOES,
        RESTRICOES
    FROM LOC_OTHERS
    UNION DISTINCT
    SELECT
        LOCATIONID,
        LOCATION_UNIT_STRUCTURE,
        LOCATION_GROUP,
        LOCATION_COUNTRY,
        LOCATION_REGION,
        DECODE(
            LOCATION_SUB_REGION, 'GJA', 'SP', LOCATION_SUB_REGION
        ) AS LOCATION_SUB_REGION,
        LOCATION_NAME,
        LOCATION_CODE,
        ZIP,
        ADDRESS,
        COMMENTS,
        LOCATION_TYPE,
        CITY,
        LONGITUDE,
        LATITUDE,
        STATE,
        LOCATION_OWNERSHIP,
        OPERATOR,
        LOCATION_IBP_ASSET,
        ROTEIRO_OBSERVACOES,
        RESTRICOES
    FROM LOC_ESTADOS

)

SELECT
    COALESCE(NULLIF(UPPER(LOCATIONID), ''), 'N/A') AS LOCATIONID,
    COALESCE(
        NULLIF(UPPER(LOCATION_UNIT_STRUCTURE), ''), 'N/A'
    ) AS LOCATION_UNIT_STRUCTURE,
    COALESCE(NULLIF(UPPER(LOCATION_GROUP), ''), 'N/A') AS LOCATION_GROUP,
    COALESCE(NULLIF(UPPER(LOCATION_COUNTRY), ''), 'N/A') AS LOCATION_COUNTRY,
    COALESCE(NULLIF(UPPER(LOCATION_REGION), ''), 'N/A') AS LOCATION_REGION,
    COALESCE(
        NULLIF(UPPER(LOCATION_SUB_REGION), ''),
        CONCAT(LOCATION_COUNTRY, '-', 'OTHERS')
    ) AS LOCATION_SUB_REGION,
    COALESCE(NULLIF(UPPER(LOCATION_NAME), ''), 'N/A') AS LOCATION_NAME,
    COALESCE(
        NULLIF(UPPER(LOCATION_CODE), ''),
        CONCAT(LOCATION_COUNTRY, '-', 'OTHERS')
    ) AS LOCATION_CODE,
    COALESCE(NULLIF(UPPER(ZIP), ''), 'N/A') AS ZIP,
    COALESCE(NULLIF(UPPER(ADDRESS), ''), 'N/A') AS ADDRESS,
    COALESCE(NULLIF(UPPER(CITY), ''), 'N/A') AS CITY,
    COALESCE(NULLIF(UPPER(LONGITUDE), ''), '0') AS LONGITUDE,
    COALESCE(NULLIF(UPPER(LATITUDE), ''), '0') AS LATITUDE,
    COALESCE(NULLIF(UPPER(STATE), ''), 'N/A') AS STATE,
    COALESCE(
        NULLIF(UPPER(LOCATION_OWNERSHIP), ''), 'N/A'
    ) AS LOCATION_OWNERSHIP,
    COALESCE(NULLIF(UPPER(OPERATOR), ''), 'N/A') AS OPERATOR,
    COALESCE(
        NULLIF(UPPER(LOCATION_IBP_ASSET), ''),
        CONCAT(LOCATION_COUNTRY, '-', 'OTHERS')
    ) AS LOCATION_IBP_ASSET,
    COALESCE(NULLIF(ROTEIRO_OBSERVACOES, ''), 'N/A') AS ROUTINGCOMMENTS,
    COALESCE(NULLIF(RESTRICOES, ''), 'N/A') AS RESTRICTION,
    TRIM('TRUE') AS ISACTIVE,
    COALESCE(NULLIF(LOCATION_TYPE, ''), 'VIRTUAL') AS LOCATION_TYPE,
    HASH(*) AS HASH_ID
FROM LOCATION
