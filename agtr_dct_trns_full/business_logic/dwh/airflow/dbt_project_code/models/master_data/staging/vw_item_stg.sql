WITH ITEM AS (
    SELECT DISTINCT
        COALESCE(NULLIF(ITEM.ITEM, ''), 'N/A') AS ITEM,
        COALESCE(NULLIF(TRIM(F4101.IMDSC1), ''), ITEM.ITEMNAME) AS ITEMNAME,
        COALESCE(NULLIF(ITEM.ITEMSTATUS, ''), 'N/A') AS ITEMSTATUS,
        COALESCE(NULLIF(ITEM.ITEMCLASS, ''), 'N/A') AS ITEMCLASS,
        COALESCE(NULLIF(ITEM.ITEMSTAGE, ''), 'N/A') AS ITEMSTAGE,
        COALESCE(NULLIF(ITEM.ITEM_TYPE, ''), 'N/A') AS ITEM_TYPE,
        COALESCE(NULLIF(ITEM.L1, ''), 'N/A') AS L1,
        COALESCE(NULLIF(ITEM.L2, ''), 'N/A') AS L2,
        COALESCE(NULLIF(ITEM.L3, ''), 'N/A') AS L3,
        COALESCE(NULLIF(ITEM.BASEUOM, ''), 'N/A') AS BASEUOM,
        COALESCE(
            NULLIF(ITEM.BASEUOMDESCRIPTION, ''), 'N/A'
        ) AS BASEUOMDESCRIPTION,
        COALESCE(NULLIF(ITEM.RESOURCE, ''), 'N/A') AS "RESOURCE",
        COALESCE(NULLIF(ITEM.CONTAINERSIZE, ''), 'N/A') AS CONTAINERSIZE,
        COALESCE(NULLIF(ITEM.PACKAGESIZE, ''), 'N/A') AS PACKAGESIZE
    FROM {{ source('pscfl', 'F_MIN_ITEM') }} AS ITEM
    LEFT JOIN {{ source('jde', 'F4101') }} AS F4101
        ON ITEM.ITEM = TRIM(F4101.IMLITM)
)

SELECT
    *,
    HASH(*) AS HASH_ID
FROM ITEM
