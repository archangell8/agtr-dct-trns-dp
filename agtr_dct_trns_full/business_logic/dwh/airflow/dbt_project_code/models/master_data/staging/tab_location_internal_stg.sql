WITH
CTE_UDC_MAPPING AS (
    SELECT
        CATEGORY,
        STAGE,
        SOURCE_CODE,
        TARGET_CODE,
        TARGET_NUMBER
    FROM {{ source('pscfl', 'F_MIN_DCT_UDC') }}
    WHERE
        1 = 1
        AND STATUS = 'ATIVO'
),

LOCATION_INTERNAL_BP AS (
    SELECT DISTINCT -- noqa
        BP.LOCATIONID,
        COALESCE(UNIT.UNIT_BASE, BP.LOCATION_UNIT_ID) AS LOCATION_UNIT_ID,
        COALESCE(GRP.ORIGINATION_STRUCTURE, 'N/A') AS LOCATION_UNIT_STRUCTURE,
        BP.LOCATION_GROUP,
        BP.LOCATION_COUNTRY,
        COALESCE(GRP.LOCATION_REGION, BP.LOCATION_REGION) AS LOCATION_REGION,
        COALESCE(UNIT.UNIT_NOME, BP.LOCATION_NAME) AS LOCATION_NAME,
        COALESCE(
            LCTP.TARGET_CODE,
            CASE
                WHEN LEFT(TRIM(BP.LOCATIONID), 5) = '02191' THEN 'FÍSICA'
                ELSE BP.LOCATION_TYPE
            END
        ) AS LOCATION_TYPE,
        BP.COMMENTS,
        BP.ISACTIVE,
        COALESCE(GRP.CITY, BP.CITY) AS CITY,
        COALESCE(GRP.STATE, BP.STATE) AS "STATE",
        COALESCE(GRP.ORIGIN_OWNERSHIP, 'N/A') AS LOCATION_OWNERSHIP,
        BP.ADDRESS_NUMBER,
        BP.ADDRESS_PAI,
        COALESCE(IBP.ATIVO_IBP, 'N/A') AS LOCATION_IBP_ASSET,
        BP.CNPJ,
        BP.IE,
        BP.IBGE,
        COALESCE(
            CODE.TARGET_CODE,
            NULLIF(IBP.CODE, '0'),
            BP.LOCATION_SUB_REGION
        ) AS LOCATION_CODE,
        COALESCE(BP.ZIP, 'N/A') AS ZIP,
        COALESCE(BP.ADDRESS, 'N/A') AS "ADDRESS",
        COALESCE(GRP.LONGITUDE, BP.LONGITUDE, '0') AS LONGITUDE,
        COALESCE(GRP.LATITUDE, BP.LATITUDE, '0') AS LATITUDE,
        COALESCE(OP.DESCR_MODAL, 'N/A') AS OPERATOR,
        BP.LOCATION_SUB_REGION,
        GRP.HR_BEGIN_ONHANDS,
        GRP.TIMEZONE
    FROM {{ ref('vw_location_branchplant_stg') }} AS BP
    LEFT JOIN {{ source('pscfl', 'F_MIN_ATIVO_IBP') }} AS IBP
        ON BP.LOCATIONID = IBP.BP_ENTREGA_SLIP
    LEFT JOIN {{ source('pscfl', 'F_MIN_LOCATION_UNIT') }} AS UNIT
        ON BP.LOCATIONID = UNIT.BP_COD
    LEFT JOIN {{ source('pscfl', 'F_MIN_LOCATION_OPERATOR') }} AS OP
        ON IBP.CODE = OP.MODAL
    INNER JOIN {{ source('pscfl', 'F_MIN_LOCATION_AGRUPADA') }} AS GRP
        ON COALESCE(UNIT.UNIT_BASE, BP.LOCATION_UNIT_ID) = GRP.UNIT_ID
    LEFT JOIN CTE_UDC_MAPPING AS CODE
        ON
            UPPER(TRIM(IBP.CODE)) = CODE.SOURCE_CODE
            AND CODE.CATEGORY = 'LOCATION_CODE'
            AND CODE.STAGE = 'DESTINATION'
    LEFT JOIN CTE_UDC_MAPPING AS LCTP
        ON
            UPPER(TRIM(BP.LOCATIONID)) = LCTP.SOURCE_CODE
            AND LCTP.CATEGORY = 'LOCATION_TYPE'
            AND LCTP.STAGE = 'LOCATIONID'
),

CTE_SUBREGION_IBGE AS (
    SELECT
        T3RMK AS COD_IBGE,
        T3RMK2 AS LOCATION_SUB_REGION
    FROM {{ source('jde', 'F00092') }}
    WHERE
        TRIM(T3SDB) = 'EXT'
        AND TRIM(T3TYDT) = 'SR'
    GROUP BY T3RMK, T3RMK2
    QUALIFY RANK() OVER (
        PARTITION BY T3RMK
        ORDER BY COUNT(T3RMK2) DESC
    ) = 1
),

CTE_PICKUP_STRUCTURE AS (
    SELECT DISTINCT LRAN8 AS LOC
    FROM {{ source('jde', 'F5543064') }}
    WHERE
        LRKCO IN ('52171', '52191', '52180')
        AND LRUPMJ > 123000
        AND COALESCE(TRIM(LRAN8), 0) > 0

    UNION DISTINCT

    SELECT DISTINCT CSSHAN AS LOC
    FROM {{ source('jde', 'F5543050') }}
    WHERE
        CSKCO IN ('52171', '52191', '52180')
        AND CSTRDJ > 123000
        AND COALESCE(TRIM(CSSHAN), 0) > 0

    UNION DISTINCT

    SELECT DISTINCT PDSHAN AS LOC
    FROM {{ source('jde', 'F4311') }}
    WHERE
        PDKCOO IN ('52171', '52191', '52180')
        AND PDTRDJ > 123000
        AND COALESCE(TRIM(PDSHAN), 0) > 0

    UNION DISTINCT

    SELECT DISTINCT CFAN8 AS LOC
    FROM {{ source('jde', 'F5549300') }}
    WHERE
        CFKCOO IN ('52171', '52191', '52180')
        AND CFUPMJ > 123000
        AND TRIM(CFURCD) != 'C'
        AND CFANCR > 0

    UNION DISTINCT

    SELECT DISTINCT TRIM(ADRESS_COLETA) AS LOC
    FROM {{ source('ctms', 'VW_DCT_TN') }}
),

LOCATION_INTERNAL_PICKUP AS (
    SELECT -- noqa
        AB.LOCATIONID,
        AB.LOCATION_UNIT_ID,
        AB.LOCATION_GROUP,
        AB.LOCATION_COUNTRY,
        AB.LOCATION_REGION,
        AB.LOCATION_NAME,
        AB.LOCATION_TYPE,
        AB.ZIP,
        AB.ADDRESS,
        AB.COMMENTS,
        AB.ISACTIVE,
        AB.CITY,
        AB.LONGITUDE::STRING AS LONGITUDE,
        AB.LATITUDE::STRING AS LATITUDE,
        AB.STATE,
        AB.LOCATION_OWNERSHIP,
        AB.ADDRESS_NUMBER,
        AB.ADDRESS_PAI,
        'N/A' AS OPERATOR,
        AB.CNPJ,
        AB.IE,
        AB.IBGE,
        CASE
            WHEN STR.LOC IS NOT NULL THEN 'PONTO DE COLETA'
            ELSE AB.LOCATION_UNIT_STRUCTURE
        END AS LOCATION_UNIT_STRUCTURE,
        COALESCE(
            IBGE.LOCATION_SUB_REGION,
            CONCAT(AB.LOCATION_COUNTRY, '-', 'OTHERS')
        ) AS LOCATION_IBP_ASSET,
        COALESCE(
            IBGE.LOCATION_SUB_REGION,
            CONCAT(AB.LOCATION_COUNTRY, '-', 'OTHERS')
        ) AS LOCATION_CODE,
        COALESCE(
            IBGE.LOCATION_SUB_REGION,
            CONCAT(AB.LOCATION_COUNTRY, '-', 'OTHERS')
        ) AS LOCATION_SUB_REGION,
        '00:00' AS HR_BEGIN_ONHANDS,
        '-03:00' AS TIMEZONE
    FROM {{ ref('vw_location_pickuppoint_stg') }} AS AB
    LEFT JOIN CTE_SUBREGION_IBGE AS IBGE
        ON
            IBGE.COD_IBGE = AB.IBGE
    LEFT JOIN CTE_PICKUP_STRUCTURE AS STR
        ON
            AB.LOCATIONID = STR.LOC
),

LOCATION_INTERNAL_STG AS (
    SELECT
        LOCATIONID,
        LOCATION_UNIT_ID,
        LOCATION_UNIT_STRUCTURE,
        LOCATION_GROUP,
        LOCATION_COUNTRY,
        LOCATION_REGION,
        LOCATION_SUB_REGION,
        LOCATION_NAME,
        LOCATION_TYPE,
        LOCATION_CODE,
        ZIP,
        ADDRESS,
        COMMENTS,
        ISACTIVE,
        CITY,
        LONGITUDE,
        LATITUDE,
        STATE,
        LOCATION_OWNERSHIP,
        ADDRESS_NUMBER,
        ADDRESS_PAI,
        OPERATOR,
        LOCATION_IBP_ASSET,
        CNPJ,
        IE,
        IBGE,
        HR_BEGIN_ONHANDS,
        TIMEZONE
    FROM LOCATION_INTERNAL_BP

    UNION DISTINCT

    SELECT
        LOCATIONID,
        LOCATION_UNIT_ID,
        LOCATION_UNIT_STRUCTURE,
        LOCATION_GROUP,
        LOCATION_COUNTRY,
        LOCATION_REGION,
        LOCATION_SUB_REGION,
        LOCATION_NAME,
        LOCATION_TYPE,
        LOCATION_CODE,
        ZIP,
        ADDRESS,
        COMMENTS,
        ISACTIVE,
        CITY,
        LONGITUDE,
        LATITUDE,
        STATE,
        LOCATION_OWNERSHIP,
        ADDRESS_NUMBER,
        ADDRESS_PAI,
        OPERATOR,
        LOCATION_IBP_ASSET,
        CNPJ,
        IE,
        IBGE,
        HR_BEGIN_ONHANDS,
        TIMEZONE
    FROM LOCATION_INTERNAL_PICKUP
),

LOCATION_INTERNAL AS (
    SELECT
        UPPER(LOCATIONID) AS LOCATIONID,
        UPPER(LOCATION_UNIT_ID) AS LOCATION_UNIT_ID,
        UPPER(LOCATION_UNIT_STRUCTURE) AS LOCATION_UNIT_STRUCTURE,
        UPPER(LOCATION_GROUP) AS LOCATION_GROUP,
        UPPER(LOCATION_COUNTRY) AS LOCATION_COUNTRY,
        UPPER(LOCATION_REGION) AS LOCATION_REGION,
        UPPER(LOCATION_SUB_REGION) AS LOCATION_SUB_REGION,
        UPPER(LOCATION_NAME) AS LOCATION_NAME,
        UPPER(LOCATION_TYPE) AS LOCATION_TYPE,
        UPPER(LOCATION_CODE) AS LOCATION_CODE,
        UPPER(ZIP) AS ZIP,
        UPPER(ADDRESS) AS "ADDRESS",
        UPPER(COMMENTS) AS COMMENTS,
        UPPER(ISACTIVE) AS ISACTIVE,
        UPPER(CITY) AS CITY,
        UPPER(LONGITUDE) AS LONGITUDE,
        UPPER(LATITUDE) AS LATITUDE,
        UPPER(STATE) AS "STATE",
        UPPER(LOCATION_OWNERSHIP) AS LOCATION_OWNERSHIP,
        UPPER(ADDRESS_NUMBER) AS ADDRESS_NUMBER,
        UPPER(ADDRESS_PAI) AS ADDRESS_PAI,
        UPPER(OPERATOR) AS OPERATOR,
        UPPER(LOCATION_IBP_ASSET) AS LOCATION_IBP_ASSET,
        UPPER(CNPJ) AS CNPJ,
        UPPER(IE) AS IE,
        UPPER(IBGE) AS IBGE,
        UPPER(HR_BEGIN_ONHANDS) AS HR_BEGIN_ONHANDS,
        UPPER(TIMEZONE) AS TIMEZONE
    FROM LOCATION_INTERNAL_STG
)

SELECT
    *,
    HASH(*) AS HASH_ID
FROM LOCATION_INTERNAL
