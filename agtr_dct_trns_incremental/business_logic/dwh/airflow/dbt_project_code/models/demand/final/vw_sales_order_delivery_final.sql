WITH FINAL AS (
    SELECT
        0 AS IDX,
        'DEMANDID' AS DEMANDID,
        'ITEM' AS ITEM,
        'LOCATION' AS LOCATION, -- noqa
        'CUSTOMERID' AS CUSTOMERID,
        'SHIPTO' AS SHIPTO,
        'REFERENCEPORT' AS REFERENCEPORT,
        'LASTCHANGEDDATEOFSALESORDER' AS LASTCHANGEDDATEOFSALESORDER,
        'DELIVEREDSALESORDERQUANTITY' AS DELIVEREDSALESORDERQUANTITY,
        'COMMITTEDSALESORDERQUANTITY' AS COMMITTEDSALESORDERQUANTITY,
        'CREATIONDATEOFSALESORDERDOCUMENT' AS CREATIONDATEOFSALESORDERDOCUMENT,
        'SALESORDERCOMMITDATE' AS SALESORDERCOMMITDATE,
        --'SALESORDERDELIVERYDATE' AS SALESORDERDELIVERYDATE,
        'UOM' AS UOM,
        'LTA' AS LTA,
        'BLOCKEDQUANTITY' AS BLOCKEDQUANTITY,
        'FREIGHTTYPE' AS FREIGHTTYPE,
        'SOURCEBP' AS SOURCEBP,
        'AVAILABLEQUANTITY' AS AVAILABLEQUANTITY,
        'BLOCKINGTYPE' AS BLOCKINGTYPE,
        'STATUS' AS STATUS,
        'TRANSMODE' AS TRANSMODE,
        'OPERATIONTYPE' AS OPERATIONTYPE,
        'CMM_SHIPTO_ADDRESS' AS CMM_SHIPTO_ADDRESS,
        NULL AS HASH_ID,
        NULL AS CDP_TRANSACTION,
        (SELECT CDP_TIMESTAMP FROM {{ ref('tab_cdp_timestamp_models') }} WHERE MODEL_NAME = UPPER('sales_order_delivery')) AS CDP_TIMESTAMP_FULL, -- noqa
        (SELECT CDP_TIMESTAMP FROM {{ ref('tab_cdp_timestamp_models') }} WHERE MODEL_NAME = UPPER('sales_order_delivery')) AS CDP_TIMESTAMP_INC, -- noqa
        'CDP_TIMESTAMP_O9' AS CDP_TIMESTAMP_O9

    UNION ALL

    SELECT
        1 AS IDX,
        DEMANDID::STRING,
        ITEM::STRING,
        LOCATION::STRING,
        CUSTOMERID::STRING,
        SHIPTO::STRING,
        REFERENCEPORT::STRING,
        LASTCHANGEDDATEOFSALESORDER::STRING,
        DELIVEREDSALESORDERQUANTITY::STRING,
        COMMITTEDSALESORDERQUANTITY::STRING,
        CREATIONDATEOFSALESORDERDOCUMENT::STRING,
        SALESORDERCOMMITDATE::STRING,
        --SALESORDERDELIVERYDATE::STRING,
        UOM::STRING,
        LTA::STRING,
        BLOCKEDQUANTITY::STRING,
        FREIGHTTYPE::STRING,
        SOURCEBP::STRING,
        AVAILABLEQUANTITY::STRING,
        BLOCKINGTYPE::STRING,
        STATUS::STRING,
        TRANSMODE::STRING,
        OPERATIONTYPE::STRING,
        CMM_SHIPTO_ADDRESS::STRING,
        HASH_ID,
        CDP_TRANSACTION,
        CDP_TIMESTAMP_FULL,
        CDP_TIMESTAMP_INC,
        CDP_TIMESTAMP_O9::STRING
    FROM {{ ref('sales_order_delivery') }}
)

SELECT
    DEMANDID,
    ITEM,
    LOCATION,
    CUSTOMERID,
    SHIPTO,
    REFERENCEPORT,
    LASTCHANGEDDATEOFSALESORDER,
    DELIVEREDSALESORDERQUANTITY,
    COMMITTEDSALESORDERQUANTITY,
    CREATIONDATEOFSALESORDERDOCUMENT,
    SALESORDERCOMMITDATE,
    --SALESORDERDELIVERYDATE,
    UOM,
    LTA,
    BLOCKEDQUANTITY,
    FREIGHTTYPE,
    SOURCEBP,
    AVAILABLEQUANTITY,
    BLOCKINGTYPE,
    STATUS,
    TRANSMODE,
    OPERATIONTYPE,
    CMM_SHIPTO_ADDRESS,
    HASH_ID,
    CDP_TRANSACTION,
    CDP_TIMESTAMP_FULL,
    CDP_TIMESTAMP_INC,
    CDP_TIMESTAMP_O9
FROM FINAL
ORDER BY IDX ASC
