{{
    config(
        materialized='table',
        tags=['master']
    )
}}

WITH
MAIN_LOCATION AS (
    SELECT DISTINCT
        LOCATIONID AS "LOCATION",
        ZIP AS LOCATION_ZIP,
        ADDRESS,
        LONGITUDE,
        LATITUDE,
        LOCATION_UNIT_STRUCTURE,
        LOCATION_GROUP,
        LOCATION_COUNTRY,
        LOCATION_REGION,
        LOCATION_SUB_REGION,
        LOCATION_CODE,
        CITY,
        STATE AS LOCATION_STATE,
        LOCATION_OWNERSHIP,
        OPERATOR AS LOCATION_OPERATOR,
        LOCATION_IBP_ASSET,
        'All' AS ALL_LOCATION,
        LOCATION_TYPE,
        '' AS PLANNING_LOCATION,
        '' AS REPORTING_LOCATION,
        '' AS STATUS,
        CONCAT(LOCATIONID, ' - ', LOCATION_NAME) AS LOCATION_DISPLAYNAME,
        CONCAT(
            LOCATION_CODE, ' - ', LOCATION_IBP_ASSET
        ) AS LOCATION_IBP_ASSET_DISPLAYNAME,
        CASE
            WHEN TRY_TO_NUMBER(LOCATIONID) IS NOT NULL THEN 'R5'
            ELSE 'R2'
        END AS LA1
    FROM {{ ref('location_master') }}
),

R5_DUMMY_LOCATION AS (
    SELECT DISTINCT
        LOCATION_CODE AS "LOCATION",
        LOCATION_CODE AS LOCATION_DISPLAYNAME,
        ZIP AS LOCATION_ZIP,
        ADDRESS,
        LOCATION_UNIT_STRUCTURE,
        LOCATION_GROUP,
        LOCATION_COUNTRY,
        LOCATION_REGION,
        LOCATION_SUB_REGION,
        LOCATION_CODE,
        STATE AS LOCATION_STATE,
        OPERATOR AS LOCATION_OPERATOR,
        LOCATION_CODE AS LOCATION_IBP_ASSET,
        LOCATION_CODE AS LOCATION_IBP_ASSET_DISPLAYNAME,
        '' AS LONGITUDE,
        '' AS LATITUDE,
        '' AS CITY,
        'PROPRIA' AS LOCATION_OWNERSHIP,
        'All' AS ALL_LOCATION,
        'PHYSICAL' AS LOCATION_TYPE,
        '' AS PLANNING_LOCATION,
        '' AS REPORTING_LOCATION,
        '' AS STATUS,
        'R5-Port' AS LA1
    FROM {{ ref('location_master') }}
    WHERE
        1 = 1
        AND LOCATION_UNIT_STRUCTURE = 'PORTO MARÍTIMO'
),

LOCATION_TEMP AS (
    SELECT
        LOCATION,
        LOCATION_ZIP,
        ADDRESS,
        LONGITUDE,
        LATITUDE,
        LOCATION_UNIT_STRUCTURE,
        LOCATION_GROUP,
        LOCATION_COUNTRY,
        LOCATION_REGION,
        LOCATION_SUB_REGION,
        LOCATION_CODE,
        CITY,
        LOCATION_STATE,
        LOCATION_OWNERSHIP,
        LOCATION_OPERATOR,
        LOCATION_IBP_ASSET,
        ALL_LOCATION,
        LOCATION_TYPE,
        PLANNING_LOCATION,
        REPORTING_LOCATION,
        STATUS,
        LOCATION_DISPLAYNAME,
        LOCATION_IBP_ASSET_DISPLAYNAME,
        LA1
    FROM MAIN_LOCATION

    UNION DISTINCT

    SELECT
        LOCATION,
        LOCATION_ZIP,
        ADDRESS,
        LONGITUDE,
        LATITUDE,
        LOCATION_UNIT_STRUCTURE,
        LOCATION_GROUP,
        LOCATION_COUNTRY,
        LOCATION_REGION,
        LOCATION_SUB_REGION,
        LOCATION_CODE,
        CITY,
        LOCATION_STATE,
        LOCATION_OWNERSHIP,
        LOCATION_OPERATOR,
        LOCATION_IBP_ASSET,
        ALL_LOCATION,
        LOCATION_TYPE,
        PLANNING_LOCATION,
        REPORTING_LOCATION,
        STATUS,
        LOCATION_DISPLAYNAME,
        LOCATION_IBP_ASSET_DISPLAYNAME,
        LA1
    FROM R5_DUMMY_LOCATION
)

SELECT
    *,
    HASH(*) AS HASH_ID
FROM LOCATION_TEMP
