WITH
SOURCE_MASTER AS (
    SELECT DISTINCT
        LOCATIONID AS SOURCE,
        ZIP AS SOURCE_ZIP,
        LOCATION_UNIT_STRUCTURE AS SOURCE_UNIT_STRUCTURE,
        LOCATION_GROUP AS SOURCE_GROUP,
        LOCATION_COUNTRY AS SOURCE_COUNTRY,
        LOCATION_REGION AS SOURCE_REGION,
        LOCATION_SUB_REGION AS SOURCE_SUB_REGION,
        STATE AS SOURCE_STATE,
        LOCATION_OWNERSHIP AS SOURCE_OWNERSHIP,
        LOCATION_IBP_ASSET AS SOURCE_IBP_ASSET,
        LOCATION_CODE AS SOURCE_CODE,
        OPERATOR AS SOURCE_OPERATOR,
        ADDRESS,
        LATITUDE,
        LONGITUDE,
        CITY,
        '' AS SOURCE_TYPE,
        '' AS STATUS,
        '' AS PLANNING_SOURCE,
        '' AS REPORTING_SOURCE,
        'All' AS ALL_SOURCE,
        LOCATION_NAME AS SOURCE_LABEL,
        CONCAT(LOCATIONID, ' - ', LOCATION_NAME) AS SOURCE_DISPLAYNAME
    FROM {{ ref('location_master') }}
)

SELECT
    *,
    HASH(*) AS HASH_ID
FROM SOURCE_MASTER
