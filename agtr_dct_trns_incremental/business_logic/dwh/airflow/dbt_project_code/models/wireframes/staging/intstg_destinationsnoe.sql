{{
    config(
        materialized='table',
        tags=['master']
    )
}}

WITH
DESTINATION_SNOE_TEMP AS (
    SELECT
        NULL AS REFERENCEDATE,
        ITEMID,
        SOURCEID,
        TRANSMODE,
        FINALDESTINATIONID,
        DAY,
        OPERATOR,
        OPERATIONTYPE,
        PLANNEDQUANTITY AS ACTPLANNEDQTY,
        NULL AS DISTPLANNEDQTY,
        NULL AS OPPLANNEDQTY,
        NULL AS ISBASELINE
    FROM {{ ref('actual_snoe_master') }}

    UNION ALL

    SELECT
        REFERENCEDATE,
        ITEMID,
        SOURCEID,
        TRANSMODE,
        FINALDESTINATIONID,
        DAY,
        OPERATOR,
        OPERATIONTYPE,
        NULL AS ACTPLANNEDQTY,
        PLANNEDQUANTITY AS DISTPLANNEDQTY,
        NULL AS OPPLANNEDQTY,
        ISBASELINE
    FROM {{ ref('distribution_snoe_master') }}
    WHERE ISBASELINE = 'TRUE'

    UNION ALL

    SELECT
        NULL AS REFERENCEDATE,
        ITEMID,
        SOURCEID,
        TRANSMODE,
        FINALDESTINATIONID,
        DAY,
        OPERATOR,
        OPERATIONTYPE,
        NULL AS ACTPLANNEDQTY,
        NULL AS DISTPLANNEDQTY,
        PLANNEDQUANTITY AS OPPLANNEDQTY,
        NULL AS ISBASELINE
    FROM {{ ref('distribution_operational_master') }}
)

SELECT
    ITEMID,
    SOURCEID,
    TRANSMODE,
    FINALDESTINATIONID,
    OPERATOR,
    OPERATIONTYPE,
    ISBASELINE,
    TRY_TO_DATE(REFERENCEDATE, 'DD-MM-YYYY') AS REFERENCEDATE,
    TRY_TO_DATE(DAY, 'DD-MM-YYYY') AS "DAY",
    SUM(ACTPLANNEDQTY) AS ACTPLANNEDQTY,
    SUM(OPPLANNEDQTY) AS OPPLANNEDQTY,
    SUM(DISTPLANNEDQTY) AS DISTPLANNEDQTY
FROM DESTINATION_SNOE_TEMP
WHERE
    1 = 1
    AND OPERATIONTYPE = 'DESCARGA NO DESTINO'
GROUP BY
    ITEMID,
    SOURCEID,
    TRANSMODE,
    FINALDESTINATIONID,
    OPERATOR,
    OPERATIONTYPE,
    ISBASELINE,
    TRY_TO_DATE(REFERENCEDATE, 'DD-MM-YYYY'),
    TRY_TO_DATE(DAY, 'DD-MM-YYYY')
