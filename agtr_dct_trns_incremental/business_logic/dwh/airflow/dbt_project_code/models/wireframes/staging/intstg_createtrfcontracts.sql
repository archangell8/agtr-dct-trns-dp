WITH
NEXT_30_DAYS AS (
    --tabela para gerar os 30 dias futuros
    SELECT
        DATEADD(
            DAY,
            ROW_NUMBER() OVER (ORDER BY NULL),
            DATEADD(DAY, -1, CURRENT_DATE())
        ) AS DATES
    FROM TABLE(GENERATOR(ROWCOUNT => 31))
),

LANEFORWAREHOUSE AS (
    SELECT
        A.LOCATION_FROM AS FROMLOCATION,
        B.LOCATION_NAME AS LOCATIONNAME,
        C.LOCATION_CODE AS TOLOCATION,
        A.TRANSMODE,
        D.ITEM,
        D.L1,
        0 AS SCHEDULEDQTY
    FROM {{ ref('lane_master') }} AS A
    INNER JOIN {{ ref('location_master') }} AS B
        ON A.LOCATION_FROM = B.LOCATIONID
    INNER JOIN {{ ref('location_master') }} AS C
        ON A.LOCATION_TO = C.LOCATIONID
    INNER JOIN {{ ref('item_master') }} AS D
        ON D.ITEM IN ('00027', '00001')
    WHERE
        A.LOCATION_FROM_UNIT_STRUCTURE = 'ARMAZÉM'
        AND A.TRANSMODE = 'ROD'
        AND A.LOCATION_TO_UNIT_STRUCTURE IN (
            'ARMAZÉM', 'PORTO MARÍTIMO', 'FÁBRICA', 'MERCADO INTERNO'
        )

    UNION ALL

    SELECT DISTINCT
        A.LOCATION_FROM AS FROMLOCATION,
        B.LOCATION_NAME AS LOCATIONNAME,
        C.LOCATION_CODE AS TOLOCATION,
        A.TRANSMODE,
        '00035' AS ITEM,
        'SOJA EUROPA' AS L1,
        0 AS SCHEDULEDQTY
    FROM {{ ref('lane_master') }} AS A
    INNER JOIN {{ ref('location_master') }} AS B
        ON A.LOCATION_FROM = B.LOCATIONID
    INNER JOIN {{ ref('location_master') }} AS C
        ON A.LOCATION_TO = C.LOCATIONID
    INNER JOIN {{ ref('onhands_master') }} AS D
        ON A.LOCATION_FROM = D.LOCATION
    WHERE
        A.LOCATION_FROM_UNIT_STRUCTURE = 'ARMAZÉM'
        AND A.TRANSMODE = 'ROD'
        AND D.ITEM = '00035'
        AND D.ONHANDQUANTITY IS NOT NULL
        AND A.LOCATION_TO_UNIT_STRUCTURE IN (
            'ARMAZÉM', 'PORTO MARÍTIMO', 'FÁBRICA', 'MERCADO INTERNO'
        )

    UNION ALL

    SELECT DISTINCT
        A.LOCATION_FROM AS FROMLOCATION,
        B.LOCATION_NAME AS LOCATIONNAME,
        C.LOCATION_CODE AS TOLOCATION,
        A.TRANSMODE,
        '00100' AS ITEM,
        'MILHO WAXY' AS L1,
        '0' AS SCHEDULEDQTY
    FROM {{ ref('lane_master') }} AS A
    INNER JOIN {{ ref('location_master') }} AS B
        ON A.LOCATION_FROM = B.LOCATIONID
    INNER JOIN {{ ref('location_master') }} AS C
        ON A.LOCATION_TO = C.LOCATIONID
    INNER JOIN {{ ref('onhands_master') }} AS D
        ON A.LOCATION_FROM = D.LOCATION
    WHERE
        A.LOCATION_FROM_UNIT_STRUCTURE = 'ARMAZÉM'
        AND A.TRANSMODE = 'ROD'
        AND D.ITEM = '00100'
        AND D.ONHANDQUANTITY IS NOT NULL
        AND A.LOCATION_TO_UNIT_STRUCTURE IN (
            'ARMAZÉM', 'PORTO MARÍTIMO', 'FÁBRICA', 'MERCADO INTERNO'
        )
),

FINALDESTINATIONPLANTS AS (
    SELECT
        LOCATION_FROM AS FROMLOCATION,
        LOCATION_FROM_UNIT_STRUCTURE AS LOCATIONFROMUNITSTRUCTURE,
        LOCATION_TO AS TOLOCATION,
        LOCATION_TO_UNIT_STRUCTURE AS LOCATIONTOUNITSTRUCTURE,
        'ROD' AS TRANSMODE
    FROM {{ ref('lane_master') }}
    WHERE
        LOCATION_FROM_UNIT_STRUCTURE IN ('FÁBRICA', 'MERCADO INTERNO')
        AND LOCATION_TO_UNIT_STRUCTURE NOT IN (
            'CLIENTE OUTBOUND', 'FÁBRICA', 'TRANSBORDO', 'PORTO FLUVIAL',
            'PONTO DE COLETA'
        )

    UNION ALL

    SELECT
        A.LOCATION_FROM AS FROMLOCATION,
        A.LOCATION_FROM_UNIT_STRUCTURE AS LOCATIONFROMUNITSTRUCTURE,
        B.LOCATION_TO AS TOLOCATION,
        B.LOCATION_TO_UNIT_STRUCTURE AS LOCATIONTOUNITSTRUCTURE,
        'ROD' AS TRANSMODE
    FROM {{ ref('lane_master') }} AS A
    INNER JOIN {{ ref('lane_master') }} AS B
        ON A.LOCATION_TO = B.LOCATION_FROM
    WHERE
        A.LOCATION_FROM_UNIT_STRUCTURE IN ('FÁBRICA', 'MERCADO INTERNO')
        AND A.LOCATION_TO_UNIT_STRUCTURE IN ('TRANSBORDO', 'PORTO FLUVIAL')
        AND B.LOCATION_TO_UNIT_STRUCTURE IN ('PORTO MARÍTIMO')
        AND B.TRANSMODE != 'ROD'
),

TRFPLANTS AS (
    SELECT
        A.*,
        D.LOCATION_CODE AS FROMLOCATIONCODE,
        B.LOCATION_CODE AS TOLOCATIONCODE,
        C.ITEM,
        CASE
            WHEN C.ITEM = '00027' THEN 'SOJA'
            WHEN C.ITEM = '00035' THEN 'SOJA EUROPA'
            WHEN C.ITEM = '00001' THEN 'MILHO'
            WHEN C.ITEM = '00100' THEN 'MILHO WAXY'
            ELSE E.ITEMNAME
        END AS ITEMNAME
    FROM FINALDESTINATIONPLANTS AS A
    INNER JOIN {{ ref('location_master') }} AS B
        ON A.TOLOCATION = B.LOCATIONID
    INNER JOIN {{ ref('location_master') }} AS D
        ON A.FROMLOCATION = D.LOCATIONID
    INNER JOIN {{ ref('onhands_master') }} AS C
        ON A.FROMLOCATION = C.LOCATION
    INNER JOIN {{ ref('item_master') }} AS E
        ON C.ITEM = E.ITEM
    WHERE
        E.L3 = 'INBOUND'
),

INTSTG_CREATECONTRACTS AS (
    SELECT DISTINCT
        A.TOLOCATION AS DESTINATION,
        A.FROMLOCATION AS PICKUP,
        A.TRANSMODE,
        A.ITEM,
        CONCAT('TRF-', A.LOCATIONNAME) AS CONTRACTID,
        CONCAT(
            'TRF-', A.LOCATIONNAME, '-', A.TOLOCATION, '-', A.L1
        ) AS CONTRACTLINEID
    FROM LANEFORWAREHOUSE AS A

    UNION ALL

    SELECT DISTINCT
        TOLOCATIONCODE AS DESTINATION,
        FROMLOCATION AS PICKUP,
        TRANSMODE,
        ITEM,
        CONCAT('TRF-', FROMLOCATIONCODE) AS CONTRACTID,
        CONCAT(
            'TRF-', FROMLOCATIONCODE, '-', TOLOCATIONCODE, '-', ITEMNAME
        ) AS CONTRACTLINEID
    FROM TRFPLANTS
)

SELECT
    A.CONTRACTID,
    A.CONTRACTLINEID,
    A.DESTINATION,
    A.PICKUP,
    A.TRANSMODE,
    A.ITEM,
    'N/A' AS SUPPLIER,
    E.DATES AS "DAY",
    0 AS SCHEDULEDQUANTITY
FROM INTSTG_CREATECONTRACTS AS A
CROSS JOIN NEXT_30_DAYS AS E
