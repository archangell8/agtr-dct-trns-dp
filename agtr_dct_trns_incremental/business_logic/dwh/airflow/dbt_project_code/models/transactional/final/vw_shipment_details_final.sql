WITH FINAL AS (
    SELECT
        0 AS IDX,
        'ID' AS ID,
        'OPERATIONTYPE' AS OPERATIONTYPE,
        'SOURCE' AS SOURCE,
        'SOURCEBP' AS SOURCEBP,
        'DESTINATION' AS DESTINATION,
        'LOADNUMBER' AS LOADNUMBER,
        'LANEID' AS LANEID,
        'SOURCINGCONTRACTID' AS SOURCINGCONTRACTID,
        'TRANSMODE' AS TRANSMODE,
        'CARRIER' AS CARRIER,
        'VEHICLEID' AS VEHICLEID,
        'ESTIMATEDSHIPDATE' AS ESTIMATEDSHIPDATE,
        'ACTUALSHIPDATE' AS ACTUALSHIPDATE,
        'SCHEDULEDDATE' AS SCHEDULEDDATE,
        'ARRIVALDATE' AS ARRIVALDATE,
        'ESTIMATEDDELIVERYDATE' AS ESTIMATEDDELIVERYDATE,
        'ACTUALDELIVERYDATE' AS ACTUALDELIVERYDATE,
        'LOADAPPLICATIONDATE' AS LOADAPPLICATIONDATE,
        'SALESORDERDELIVERYID' AS SALESORDERDELIVERYID,
        'FINALDESTINATION' AS FINALDESTINATION,
        'PRICETYPE' AS PRICETYPE,
        'ITEMID' AS ITEMID,
        'PLANNEDCOST' AS PLANNEDCOST,
        'ACTUALCOST' AS ACTUALCOST,
        'PENALTYCOST' AS PENALTYCOST,
        'QUANTITY' AS QUANTITY,
        'UOM' AS UOM,
        'CURRENCY' AS CURRENCY,
        'PALLET' AS PALLET,
        'PALLETQUANTITY' AS PALLETQUANTITY,
        'PROFILE' AS PROFILE,
        'QUALITY_ADJUSTMENT' AS QUALITY_ADJUSTMENT,
        NULL AS HASH_ID,
        NULL AS CDP_TRANSACTION,
        (SELECT CDP_TIMESTAMP FROM {{ ref('tab_cdp_timestamp_models') }} WHERE MODEL_NAME = UPPER('shipment_details')) AS CDP_TIMESTAMP_FULL, -- noqa
