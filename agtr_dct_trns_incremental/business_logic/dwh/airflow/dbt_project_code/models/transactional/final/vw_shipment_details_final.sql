        'CDP_TIMESTAMP_O9' AS CDP_TIMESTAMP_O9

    UNION ALL

    SELECT
        1 AS IDX,
        ID::STRING,
        OPERATIONTYPE::STRING,
        SOURCE::STRING,
        SOURCEBP::STRING,
        DESTINATION::STRING,
        LOADNUMBER::STRING,
        LANEID::STRING,
        SOURCINGCONTRACTID::STRING,
        TRANSMODE::STRING,
        CARRIER::STRING,
        VEHICLEID::STRING,
        ESTIMATEDSHIPDATE::STRING,
        ACTUALSHIPDATE::STRING,
        SCHEDULEDDATE::STRING,
        ARRIVALDATE::STRING,
        ESTIMATEDDELIVERYDATE::STRING,
        ACTUALDELIVERYDATE::STRING,
        LOADAPPLICATIONDATE::STRING,
        SALESORDERDELIVERYID::STRING,
        FINALDESTINATION::STRING,
        PRICETYPE::STRING,
        ITEMID::STRING,
        PLANNEDCOST::STRING,
        ACTUALCOST::STRING,
        PENALTYCOST::STRING,
        QUANTITY::STRING,
        UOM::STRING,
        CURRENCY::STRING,
        PALLET::STRING,
        PALLETQUANTITY::STRING,
        PROFILE::STRING,
        QUALITY_ADJUSTMENT::STRING,
        HASH_ID,
        CDP_TRANSACTION,
        CDP_TIMESTAMP_FULL,
        CDP_TIMESTAMP_INC,
        CDP_TIMESTAMP_O9::STRING
    FROM {{ ref('shipment_details') }}
)

SELECT
    ID,
    OPERATIONTYPE,
    SOURCE,
    SOURCEBP,
    DESTINATION,
    LOADNUMBER,
    LANEID,
    SOURCINGCONTRACTID,
    TRANSMODE,
    CARRIER,
    VEHICLEID,
    ESTIMATEDSHIPDATE,
    ACTUALSHIPDATE,
    SCHEDULEDDATE,
    ARRIVALDATE,
    ESTIMATEDDELIVERYDATE,
    ACTUALDELIVERYDATE,
    LOADAPPLICATIONDATE,
    SALESORDERDELIVERYID,
    FINALDESTINATION,
    PRICETYPE,
    ITEMID,
    PLANNEDCOST,
    ACTUALCOST,
    PENALTYCOST,
    QUANTITY,
    UOM,
    CURRENCY,
    PALLET,
    PALLETQUANTITY,
    PROFILE,
    QUALITY_ADJUSTMENT,
    HASH_ID,
    CDP_TRANSACTION,
    CDP_TIMESTAMP_FULL,
    CDP_TIMESTAMP_INC,
    CDP_TIMESTAMP_O9
FROM FINAL
ORDER BY IDX ASC
