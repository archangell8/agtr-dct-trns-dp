        STATUS_3098.PALLET,
        STATUS_3098.PROFILE,
        STATUS_3098.PLANNED_FREIGHT,
        'FALSE' AS SINISTRO
    FROM {{ ref('tab_shipment_loads_abertos_jde_stg') }} AS STATUS_3098
    INNER JOIN {{ ref('item_master') }} AS IT
        ON IT.ITEM = STATUS_3098.PRODUCT_CODE
    LEFT JOIN UDC_PEDIDOS AS UDC
        ON TRIM(UDC.SOURCE_CODE) = TRIM(STATUS_3098.TIPO_PEDIDO)
