        STATUS_8090.FINALDESTINATION_REAL,
        STATUS_8090.PALLETQUANTITY,
        STATUS_8090.PALLET,
        STATUS_8090.PROFILE,
        STATUS_8090.PLANNED_FREIGHT,
        STATUS_8090.SINISTRO
    FROM {{ ref('tab_shipment_loads_faturados_jde_stg') }} AS STATUS_8090
    INNER JOIN {{ ref('item_master') }} AS IT
        ON IT.ITEM = STATUS_8090.PRODUCT_CODE
    LEFT JOIN UDC_PEDIDOS AS UDC
        ON TRIM(UDC.SOURCE_CODE) = TRIM(STATUS_8090.TIPO_PEDIDO)

    UNION

    SELECT
        --STATUS_3098.LOAD_NUMBER || '-' || COALESCE(STATUS_3098.PEDIDO, 'N/A')
        --|| COALESCE(STATUS_3098.TIPO_PEDIDO, 'N/A')
        --|| COALESCE(STATUS_3098.LINHA_PEDIDO, 'N/A') AS BK,
        --CONCAT(
        --    COALESCE(STATUS_3098.OC_NUMBER, 'N/A'),
        --    '-', COALESCE(STATUS_3098.LOAD_NUMBER, 'N/A')
        --) AS BK_CTMS,
        --CONCAT(
        --     COALESCE(
        --     IFF(
        --         COALESCE(STATUS_3098.OC_NUMBER, 0) = 0,
        --         NULL,
        --         TO_CHAR(STATUS_3098.OC_NUMBER)
        --     ), 'N/A'),
        --     '-',
        --     COALESCE(
        --         IFF(
        --         COALESCE(STATUS_3098.LOAD_NUMBER, 0) = 0,
        --         NULL,
        --         TO_CHAR(STATUS_3098.LOAD_NUMBER)
        --     ), 'N/A')
        -- ) AS BK_CTMS,
        STATUS_3098.OPERATION_TYPE AS TIPO_DE_OPERACAO,
        STATUS_3098.BRANCH_PLANT_SOURCE AS BP_ORIGEM,
        {{ check_empty_or_zero('STATUS_3098.NEGOTIATION_BRANCH_PLANT') }} AS BP_NEGOCIACAO,
        {{ check_empty_or_zero('STATUS_3098.ADDRESS_DESTINATION') }} AS DESTINO_ADDRESS,
        {{ check_empty_or_zero('STATUS_3098.BRANCH_PLANT_DESTINATION') }} AS BP_DESTINO,
        --STATUS_3098.LOAD_NUMBER AS LOAD,
        --IFF(
        --    COALESCE(STATUS_3098.LOAD_NUMBER, 0) = 0,
        --    NULL,
        --    TO_CHAR(STATUS_3098.LOAD_NUMBER)
        --) AS "LOAD",
        {{ check_empty_or_zero('STATUS_3098.LOAD_NUMBER') }} AS "LOAD",
        STATUS_3098.LOAD_STATUS_CODE AS CODIGO_STATUS_LOAD,
        UPPER(STATUS_3098.LOAD_STATUS) AS STATUS_LOAD,
        --NULL AS LOAD_RECEBIDO_NO_DESTINO,
        IFF(
            COALESCE(TRIM(STATUS_3098.ORIGINATION_CONTRACT), '') IN ('', '0'),
            NULL,
            TRIM(STATUS_3098.ORIGINATION_CONTRACT)
        ) AS CONTRATO_ORIGINACAO,
        STATUS_3098.MODAL,
        STATUS_3098.CARRIER_ADDRESS AS ADDRESS_TRANSPORTADORA,
        STATUS_3098.CARRIER_NAME AS NOME_TRANSPORTADORA,
        --STATUS_3098.PLATE AS PLACA,
        TRIM(
            IFF(
                COALESCE(TRIM(STATUS_3098.PLATE), '') = '',
                NULL,
                REPLACE(TRIM(STATUS_3098.PLATE), '-', '')
            )
        ) AS PLACA,
        STATUS_3098.DRIVER_NAME AS NOME_MOTORISTA,
        STATUS_3098.SCHEDULED_SHIPPING_DATE AS DATA_PROGRAMADA_CARREGAMENTO,
        CASE
            WHEN IT.ITEMSTAGE = 'ENVASE'
                THEN STATUS_3098.SCHEDULED_SHIPPING_DATE
            ELSE STATUS_3098.SCHEDULED_LOAD_DATE
        END AS DATA_PROGRAMADA_ENVIO,
        -- STATUS_3098.SCHEDULED_LOAD_DATE AS DATA_PROGRAMADA_ENVIO,
        STATUS_3098.PRODUCT_CODE AS CODIGO_PRODUTO,
        STATUS_3098.TRANSPORTED_VOLUME AS VOLUME_TRANSPORTADO,
        STATUS_3098.UM_PRODUCT AS U_M_PRODUTO,
        STATUS_3098.CURRENCY AS MOEDA,
        NULL AS DATA_CONFIRMACAO_CARREGAMENTO,
        NULL AS DATA_EMISSAO_NF,
        --STATUS_3098.OC_NUMBER AS NUMERO_OC,
