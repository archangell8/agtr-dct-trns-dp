    SELECT
        SOURCE_CODE,
        TARGET_CODE
    FROM {{ source('pscfl', 'F_MIN_DCT_UDC') }}
    WHERE
        1 = 1
        AND TRIM(CATEGORY) = 'SALES_ORDER_DELIVERY'
        AND TRIM(STAGE) = 'ORDERS'
        AND TRIM(STATUS) = 'ATIVO'
),

