        ) AS LOADAPPLICATIONDATE,
        COALESCE(
            SHIP.CONTRATO_ORIGINACAO, CHAVE.CONTRACT_NUMBER_APPLIED
        ) AS CONTRACT_NUMBER_APPLIED,
        COALESCE(SHIP.LOTID, CHAVE.LOTEID) AS LOTEID,
        COALESCE(
            CHAVE.FINALDESTINATION, SHIP.FINALDESTINATION
        ) AS FINALDESTINATION,
        COALESCE(SHIP.PRICETYPE, CHAVE.PRICETYPE) AS PRICETYPE,
        COALESCE(SHIP.PALLETQUANTITY, CHAVE.PALLETQUANTITY) AS PALLETQUANTITY,
        COALESCE(SHIP.PALLET, CHAVE.PALLET) AS PALLET,
        COALESCE(SHIP.PROFILE, CHAVE.PROFILE) AS PROFILE,
        COALESCE(SHIP.ID_PEDIDO, CHAVE.ID_PEDIDO) AS ID_PEDIDO,
        COALESCE(SHIP.LINENUMBER, CHAVE.LINENUMBER) AS LINENUMBER,
        COALESCE(SHIP.CODIGO_PRODUTO, CHAVE.ITEMID) AS ITEMID,
        COALESCE(SHIP.UOM, CHAVE.UOM) AS UOM,
        COALESCE(SHIP.MOEDA, CHAVE.CURRENCY) AS CURRENCY,
        COALESCE(
            IFF(
                COALESCE(SHIP.VOL_BALANCA, 0) = 0,
                SHIP.VOL_NF,
                SHIP.VOL_BALANCA
            ),
            CHAVE.QUANTITY,
            0
        ) * CHAVE.PROPORTION_VOL_BALANCA AS QUANTITY,
        COALESCE(
            SHIP.VOL_DISCONTO, CHAVE.QUALITY_ADJUSTMENT
        ) AS QUALITY_ADJUSTMENT,
        COALESCE(SHIP.PLANNED_FREIGHT, CHAVE.PLANNED_FREIGHT) AS PLANNED_FREIGHT
    FROM SHIPMENT_CORE_PART2 AS CHAVE
    LEFT JOIN SHIPMENT_HEADER_FICHA AS SHIP
        ON CHAVE.SHIP_BK = SHIP.SHIP_BK
    LEFT JOIN {{ ref('tab_sourcing_contract_internal_stg') }} AS CTR
        ON SHIP.CONTRATO_ORIGINACAO = CTR.CONTRACTNUMBER
),

