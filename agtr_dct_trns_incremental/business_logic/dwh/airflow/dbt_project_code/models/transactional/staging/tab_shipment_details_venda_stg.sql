            TO_CHAR(CTMS_LOAD.DATA_PREV_COLETA, 'DD-MM-YYYY HH24:MI:SS'),
            'N/A'
        ) AS SCHEDULEDDATE,
        COALESCE(
            TO_CHAR(S.ARRIVALDATE, 'DD-MM-YYYY'), 'N/A'
        ) AS ARRIVALDATE,
        COALESCE(
            TO_CHAR(S.ACTUALDELIVERYDATE, 'DD-MM-YYYY HH24:MI:SS'),
            TO_CHAR(CTMS_LOAD.DATA_ENTREGA, 'DD-MM-YYYY HH24:MI:SS'),
            'N/A'
        ) AS ACTUALDELIVERYDATE,
        COALESCE(S.CONTRACT_NUMBER_APPLIED, 'N/A') AS CONTRACT_NUMBER_APPLIED,
        COALESCE(
            TO_CHAR(S.LOADAPPLICATIONDATE, 'DD-MM-YYYY'), 'N/A'
        ) AS LOADAPPLICATIONDATE,
        COALESCE(S.CONTRACT_INFO_NF, 'N/A') AS CONTRACT_INFO_NF,
        COALESCE(S.LOTEID, 'N/A') AS LOTEID,
