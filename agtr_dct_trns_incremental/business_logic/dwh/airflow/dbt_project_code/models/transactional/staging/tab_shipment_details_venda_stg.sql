        ON S.LOADNUMBER = CTMS_LOAD.LOAD
    LEFT JOIN FRETE_REALIZADO AS ACT
        ON
            S.LOADNUMBER = ACT.LOADNUMBER
            AND S.ITEMID = ACT.ITEMID
    LEFT JOIN FRETE_REALIZADO_VR AS ACT_VR
        ON
            S.ITEMID = ACT_VR.ITEMID
            AND S.BP_ORIGEM_INTERNAL = ACT_VR.BP_ORIGEM
            AND S.VEHICLEID = ACT_VR.PLACA
            AND SUBSTR(S.DATA_EMISSAO_NF, 1, 10) = SUBSTR(ACT_VR.DATA_DESPACHO, 1, 10) --noqa
            AND S.TIPO_PEDIDO = 'VQ'
    LEFT JOIN FRETE_PLANEJADO AS PLN
        ON S.SOURCINGCONTRACTID = PLN.SOURCINGCONTRACTID
    WHERE
        S.OPERATIONTYPE = 'VEN'
