WITH
CMAX AS (
    SELECT
        JDE_UNIT_ID,
        GRAIN_CODE,
        VALUE,
        LAST_UPDATE,
        CONCAT(
            UPPER(GRAIN), '_',
            JDE_UNIT_ID, '_',
            TO_CHAR(LAST_UPDATE, 'YYYYMMDD_HHMISS')
        ) AS SAMPLE_ID,
        CASE
            WHEN REPLACE(MEASURE, 'QUALITIES_', '') = 'DAMAGED' THEN 'AVARIADOS'
            WHEN REPLACE(MEASURE, 'QUALITIES_', '') = 'IMPURITY' THEN 'IMPUREZA'
            WHEN REPLACE(MEASURE, 'QUALITIES_', '') = 'MOISTURE' THEN 'UMIDADE'
        END AS MEASURE
    FROM {{ source('cmax', 'VW_CMAX_INVENTORY') }}
    UNPIVOT (
        VALUE FOR MEASURE IN (
            QUALITIES_DAMAGED,
            QUALITIES_IMPURITY,
            QUALITIES_MOISTURE
        )
    )
),

ONHANDS_QUALITY_INBOUND AS (
    SELECT DISTINCT -- noqa
        'INBOUND' AS ORIGIN,
        C.SAMPLE_ID,
        COALESCE(NULLIF(C.JDE_UNIT_ID, ''), 'N/A') AS LOCATION_UNIT_ID,
        COALESCE(NULLIF(C.GRAIN_CODE, ''), 'N/A') AS GRAIN_CODE,
        COALESCE(
            TO_CHAR(TO_DATE(C.LAST_UPDATE), 'DD-MM-YYYY HH24:MI:SS'),
            'N/A'
        ) AS "DAY",
        COALESCE(NULLIF(C.MEASURE, ''), 'N/A') AS MEASURE,
        COALESCE(NULLIF(C.VALUE::DOUBLE, 0), 0) AS "VALUE",
        '%' AS UNIT
    FROM CMAX AS C
    INNER JOIN {{ ref('location_master') }} AS LI
        ON TRIM(C.JDE_UNIT_ID) = TRIM(LI.LOCATIONID)
    INNER JOIN {{ ref('item_master') }} AS IT
        ON TRIM(C.GRAIN_CODE) = TRIM(IT.ITEM)
    WHERE TO_DATE(C.LAST_UPDATE) >= '2025-01-01'::DATE
),

UDC AS (
    SELECT
        CATEGORY,
        STAGE,
        SOURCE_CODE,
        TARGET_CODE
    FROM {{ source('pscfl', 'F_MIN_DCT_UDC') }}
    WHERE
        1 = 1
        AND STATUS = 'ATIVO'
),

ONHANDS_QUALITY_OUTBOUND AS (
    SELECT
        'OUTBOUND' AS ORIGIN,
        TB_RESULTADO.SPECTRUM_NAME AS SAMPLE_ID,
        AVG(TB_RESULTADO.PREDICTION_CALCULATED)::DECIMAL(20, 3) AS "VALUE",
        COALESCE(UDC_LOCATION.TARGET_CODE, 'N/A') AS "LOCATION",
        COALESCE(UDC_ITEM.TARGET_CODE, 'N/A') AS ITEM,
        COALESCE(UDC_MEASURE.TARGET_CODE, 'N/A') AS MEASURE,
        COALESCE(UDC_UOM.TARGET_CODE, 'N/A') AS UNIT,
        COALESCE(
            TO_CHAR(
                TRUNCATE(TB_RESULTADO.DATE_TIME_ANALYSIS, 'DAY'),
                'DD-MM-YYYY HH24:MI:SS'
            ),
            'N/A'
        ) AS DAY
    FROM {{ source('onet', 'T1_QUANT2_RESULTS_CDP') }} AS TB_RESULTADO
    LEFT JOIN {{ source('onet', 'T1_CATEGORIES_CDP') }} AS TB_CATEGORIA
        ON
            TB_RESULTADO.SPECTRUM_PATH = TB_CATEGORIA.PATH
            AND TB_RESULTADO.SPECTRUM_NAME = TB_CATEGORIA.FILE_NAME
    LEFT JOIN {{ source('onet', 'MPA_LOCATIONS') }} AS TB_LOCATION
        ON TB_LOCATION.MPA = TB_RESULTADO.SPECTRUM_NUMBER
    LEFT JOIN {{ source('onet', 'T1_CATEGORIES_CDP') }} AS TB_PRODUCT
        ON
            TB_RESULTADO.SPECTRUM_PATH = TB_PRODUCT.PATH
            AND TB_RESULTADO.SPECTRUM_NAME = TB_PRODUCT.FILE_NAME
            AND UPPER(TB_PRODUCT.CATEGORY_NAME) = 'PRODUCT NAME'
    LEFT JOIN {{ source('onet', 'T1_CATEGORIES_CDP') }} AS TB_TYPE
        ON
            TB_RESULTADO.SPECTRUM_PATH = TB_TYPE.PATH
            AND TB_RESULTADO.SPECTRUM_NAME = TB_TYPE.FILE_NAME
            AND UPPER(TB_TYPE.CATEGORY_NAME) = 'SAMPLE TYPE'
    LEFT JOIN {{ source('onet', 'T1_CATEGORIES_CDP') }} AS TB_TURNO
        ON
            TB_RESULTADO.SPECTRUM_PATH = TB_TURNO.PATH
            AND TB_RESULTADO.SPECTRUM_NAME = TB_TURNO.FILE_NAME
            AND UPPER(TB_TURNO.CATEGORY_NAME) = 'SHIFT'
    INNER JOIN UDC AS UDC_LOCATION
        ON
            UDC_LOCATION.SOURCE_CODE = UPPER(TB_LOCATION.PLANT)
            AND UDC_LOCATION.CATEGORY = 'ONHANDS_QUALITY'
            AND UDC_LOCATION.STAGE = 'LOCATION_ONHANDS_QUALITY'
    INNER JOIN UDC AS UDC_ITEM
        ON
            UDC_ITEM.SOURCE_CODE = UPPER(TB_PRODUCT.CATEGORY_VALUE)
            AND UDC_ITEM.CATEGORY = 'ONHANDS_QUALITY'
            AND UDC_ITEM.STAGE = 'ITEM_ONHANDS_QUALITY'
    INNER JOIN UDC AS UDC_MEASURE
        ON
            UDC_MEASURE.SOURCE_CODE = UPPER(TB_RESULTADO.COMPONENT_NAME)
            AND UDC_MEASURE.CATEGORY = 'ONHANDS_QUALITY'
            AND UDC_MEASURE.STAGE = 'METRIC_NAME'
    INNER JOIN UDC AS UDC_UOM
        ON
            UDC_UOM.SOURCE_CODE = UPPER(TB_RESULTADO.COMPONENT_NAME)
            AND UDC_UOM.CATEGORY = 'ONHANDS_QUALITY'
            AND UDC_UOM.STAGE = 'METRIC_UOM'
    WHERE
        1 = 1
        AND UPPER(TB_TYPE.CATEGORY_VALUE) IN ('PROCESSO', 'PROCESO')
        AND TB_LOCATION.COUNTRY IN ('BRAZIL')
        AND TO_DATE(TB_RESULTADO.DATE_TIME_ANALYSIS) >= '2025-01-01'::DATE
    GROUP BY
        UDC_LOCATION.TARGET_CODE,
        UDC_ITEM.TARGET_CODE,
        UDC_MEASURE.TARGET_CODE,
        UDC_UOM.TARGET_CODE,
        TB_RESULTADO.SPECTRUM_NAME,
        TO_CHAR(
            TRUNCATE(TB_RESULTADO.DATE_TIME_ANALYSIS, 'DAY'),
            'DD-MM-YYYY HH24:MI:SS'
        )
),

ONHANDS_QUALITY AS (
    SELECT
        LOCATION_UNIT_ID AS "LOCATION",
        GRAIN_CODE AS ITEM,
        DAY,
        MEASURE,
        VALUE,
        UNIT,
        ORIGIN,
        SAMPLE_ID
    FROM ONHANDS_QUALITY_INBOUND

    UNION DISTINCT

    SELECT
        LOCATION,
        ITEM,
        DAY,
        MEASURE,
        VALUE,
        UNIT,
        ORIGIN,
        SAMPLE_ID
    FROM ONHANDS_QUALITY_OUTBOUND
)

SELECT
    LOCATION,
    ITEM,
    DAY,
    MEASURE,
    VALUE,
    UNIT,
    ORIGIN,
    SAMPLE_ID,
    HASH(*) AS HASH_ID
FROM ONHANDS_QUALITY
WHERE
    1 = 1
    AND {{ date_max_filter('DAY', 'DD-MM-YYYY HH:MI:SS', 'na') }} --noqa
