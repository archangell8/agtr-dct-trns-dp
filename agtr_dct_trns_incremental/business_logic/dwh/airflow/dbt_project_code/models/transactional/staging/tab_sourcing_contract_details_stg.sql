WITH
UDC AS ( --noqa
    SELECT
        CATEGORY,
        STAGE,
        SOURCE_CODE,
        TARGET_CODE
    FROM {{ source('pscfl', 'F_MIN_DCT_UDC') }}
    WHERE
        1 = 1
        AND STATUS = 'ATIVO'
),

TOTALS AS (
    SELECT
        CIA,
        AGREEMENT_NUMBER,
        ADDRESS_LOCAL_RETIRADA_FAZENDA,
        UNIT AS UOM,
        COALESCE(NULLIF(TRIM(DESTINATION), ''), 'N/A') AS DESTINATION,
        COALESCE(VALOR_DO_FRETE_BRUTO, 0) AS FRT,
        MAX(CADENCIA_DE_EMBARQUE) AS CAD
    FROM {{ source('jde', 'F_PURCHASE_POSITION') }}
    WHERE
        1 = 1
        AND LINE_NUMBER = 1000
        AND ADDRESS_LOCAL_RETIRADA_FAZENDA IS NOT NULL
        AND REFERENCE_MONTH IS NOT NULL
    GROUP BY
        CIA,
        AGREEMENT_NUMBER,
        ADDRESS_LOCAL_RETIRADA_FAZENDA,
        UNIT,
        COALESCE(NULLIF(TRIM(DESTINATION), ''), 'N/A'),
        COALESCE(VALOR_DO_FRETE_BRUTO, 0)
),

POSICAO_1 AS (
    SELECT
        CIA,
        AGREEMENT_NUMBER,
        --DESTINATION,
        COALESCE(NULLIF(TRIM(DESTINATION), ''), 'N/A') AS DESTINATION,
        SUM(CONTRACTED_QUANTITY2 - CANCELLED_VOLUME) AS CONTRACTED_NET,
        SUM(CASE
            WHEN LINE_TYPE IN ('NPE')
                THEN
                    (RECEIVABLE_VOLUME + TO_BE_FIXED_VOLUME)
            ELSE 0
        END) AS POSICAO_PAF,
        SUM(CASE
            WHEN LINE_TYPE IN ('COMP', 'COMPONENTE')
                THEN (RECEIVABLE_VOLUME + TO_BE_FIXED_VOLUME)
            ELSE 0
        END) AS POSICAO_COMP,
        SUM(QTDE_PEDIDO_REM) AS TOTAL_REM
    FROM {{ source('jde', 'F_PURCHASE_POSITION') }}
    WHERE
        1 = 1
    GROUP BY
        CIA,
        AGREEMENT_NUMBER,
        COALESCE(NULLIF(TRIM(DESTINATION), ''), 'N/A')
),

POSICAO_2 AS (
    SELECT
        AGREEMENT_NUMBER,
        CIA,
        DESTINATION,
        CONTRACTED_NET,
        POSICAO_PAF,
        POSICAO_COMP,
        SUM(CONTRACTED_NET - POSICAO_PAF - POSICAO_COMP) AS POSICAO_FLAT
    FROM POSICAO_1
    GROUP BY
        AGREEMENT_NUMBER,
        CIA,
        CONTRACTED_NET,
        POSICAO_PAF,
        POSICAO_COMP,
        DESTINATION
),

TO_RECEIVE_QUANTITY_1 AS (
    SELECT
        CIA,
        AGREEMENT_NUMBER,
        COALESCE(NULLIF(TRIM(DESTINATION), ''), 'N/A') AS DESTINATION,
        SUM(RECEIVABLE_VOLUME) AS RECEBER,
        SUM(CASE
            WHEN LINE_TYPE IN ('COMP', 'COMPONENTE') THEN RECEIVABLE_VOLUME
            ELSE 0
        END) AS RECEBER_COMP,
        SUM(CASE
            WHEN LINE_TYPE IN ('NPE') THEN RECEIVABLE_VOLUME
            ELSE 0
        END) AS RECEBER_PAF
    FROM {{ source('jde', 'F_PURCHASE_POSITION') }}
    WHERE
        1 = 1
    GROUP BY
        CIA,
        AGREEMENT_NUMBER,
        COALESCE(NULLIF(TRIM(DESTINATION), ''), 'N/A')
),

TO_RECEIVE_QUANTITY_2 AS (
    SELECT
        CIA,
        AGREEMENT_NUMBER,
        DESTINATION,
        RECEBER_COMP,
        RECEBER_PAF,
        RECEBER,
        SUM(RECEBER - RECEBER_PAF - RECEBER_COMP) AS RECEBER_FLAT
    FROM TO_RECEIVE_QUANTITY_1
    WHERE
        1 = 1
    GROUP BY
        CIA,
        AGREEMENT_NUMBER,
        DESTINATION,
        RECEBER_COMP,
        RECEBER_PAF,
        RECEBER
),

RECEIVED_QUANTITY AS (
    SELECT
        P.CIA,
        P.AGREEMENT_NUMBER,
        P.DESTINATION,
        (
            (P.POSICAO_PAF - R.RECEBER_PAF) + (P.POSICAO_COMP - R.RECEBER_COMP)
            + (P.POSICAO_FLAT - R.RECEBER_FLAT)
        ) AS REC,
        (P.POSICAO_PAF - R.RECEBER_PAF) AS REC_PAF,
        (P.POSICAO_COMP - R.RECEBER_COMP) AS REC_COMP,
        (P.POSICAO_FLAT - R.RECEBER_FLAT) AS REC_FLAT
    FROM POSICAO_2 AS P
    INNER JOIN TO_RECEIVE_QUANTITY_2 AS R
        ON
            P.AGREEMENT_NUMBER = R.AGREEMENT_NUMBER
            AND P.CIA = R.CIA
            AND P.DESTINATION = R.DESTINATION
    WHERE
        1 = 1
),

CANCELLED_QUANTITY AS (
    SELECT
        CIA,
        AGREEMENT_NUMBER,
        LINE_NUMBER,
        COALESCE(NULLIF(TRIM(DESTINATION), ''), 'N/A') AS DESTINATION,
        SUM(CANCELLED_VOLUME) AS CAN,
        SUM(CASE
            WHEN LINE_TYPE NOT IN ('NPE') THEN (CANCELLED_VOLUME) ELSE 0
        END) AS CAN_FLAT,
        SUM(CASE
            WHEN LINE_TYPE IN ('NPE') THEN (CANCELLED_VOLUME) ELSE 0
        END) AS CAN_PAF
    FROM {{ source('jde', 'F_PURCHASE_POSITION') }}
    WHERE
        1 = 1
        --AND LINE_TYPE != 'COMP'
    GROUP BY
        CIA,
        AGREEMENT_NUMBER,
        LINE_NUMBER,
        COALESCE(NULLIF(TRIM(DESTINATION), ''), 'N/A')
),

POSICAO_OHGLOBAL AS (
    SELECT
        CIA,
        AGREEMENT_NUMBER,
        SUM(QTDE_PEDIDO_REM) AS TOTAL_REM,
        SUM(SALDO_EM_ABERTO_REM) AS OPEN_REM,
        SUM(QTDE_CONSUMIDA) AS REC_REM
    FROM {{ source('jde', 'F_PURCHASE_POSITION') }}
    WHERE
        1 = 1
    GROUP BY
        CIA,
        AGREEMENT_NUMBER
),

DESTINATION_FIX AS (
    SELECT DISTINCT
        F50_INT.CSDMCT,
        F50_INT.CSKCO,
        COALESCE(
            UDC_AMID.TARGET_CODE, --RECOMERA DEST AMIDOS
            UDC_MODAL_2.TARGET_CODE, --RECUPERA DEST DE-PARA CONCAT DEST E MODAL
            UDC_MODAL_1.TARGET_CODE, --RECUPERA DEST DE-PARA
            COALESCE(NULLIF(TRIM(F50_INT.CSAA10), ''), 'N/A')
        ) AS DESTINATION
    FROM {{ source('jde', 'F5543050') }} AS F50_INT
    LEFT JOIN UDC AS UDC_AMID
        ON
            TRIM(UDC_AMID.SOURCE_CODE) = SUBSTR(TRIM(F50_INT.CSMCU), 1, 8)
            AND UDC_AMID.CATEGORY = 'SOURCING CONTRACT'
            AND UDC_AMID.STAGE = 'DESTINATION AMIDOS'
    LEFT JOIN UDC AS UDC_MODAL_1
        ON
            TRIM(UDC_MODAL_1.SOURCE_CODE) = TRIM(F50_INT.CSAA10)
            AND UDC_MODAL_1.CATEGORY = 'LOCATION_CODE'
            AND UDC_MODAL_1.STAGE = 'DESTINATION'
    LEFT JOIN UDC AS UDC_MODAL_2
        ON
            TRIM(UDC_MODAL_2.SOURCE_CODE) = CONCAT(
                TRIM(F50_INT.CSAA10), TRIM(F50_INT.CSMOT)
            )
            AND UDC_MODAL_2.CATEGORY = 'LOCATION_CODE'
            AND UDC_MODAL_2.STAGE = 'DESTINATION'
    WHERE
        1 = 1
        AND F50_INT.CSZ55SLPT = '12'
),

CONT AS (
    SELECT
        CONTRACTNUMBER_INTERNAL,
        CIA,
        COUNT(*) AS QTDE
    FROM {{ ref('tab_sourcing_contract_stg') }}
    GROUP BY
        CONTRACTNUMBER_INTERNAL,
        CIA
    HAVING COUNT(*) > 1
),


MAIN_TEMP_A AS (
    SELECT DISTINCT
        P.CIA,
        T.ADDRESS_LOCAL_RETIRADA_FAZENDA,
        P.DESTINATION_BRANCH_PLANT_CODE AS DESTINATION_BP,
        P.ORIGINATION_BRANCH_PLANT_CODE AS ORIGINATION_BP,
        P.MODAL,
        P.FREIGHT_TYPE,
        P.REFERENCE_MONTH,
        P.AGREEMENT_NUMBER,
        P.LINE_NUMBER AS LINE,
        0.00 AS ACTUALCOST,
        Q.CONTRACTED_NET AS QUANTITY,
        Q.POSICAO_FLAT AS QUANTITYFLAT, --A
        Q.POSICAO_PAF AS QUANTITYPAF, --A
        P.SCCRCD AS CURRENCY,
        P.PRECO_RS_US_SC AS PRECO_SACA,
        T.UOM,
        P.TIPO_PED_OW,
        OH.OPEN_REM AS OPENREM,
        OH.REC_REM AS RECEIVEDREM,
        TRIM(P.PRODUCT) AS ITEMID,
        COALESCE(NULLIF(TRIM(P.DESTINATION), ''), 'N/A') AS DESTINATION,
        COALESCE(T.FRT, 0) AS FREIGHTCOST,
        T.CAD / 1000 AS FREIGHTCADENCE,
        -- sempre que o cak for cif, mesmo que seja OH global, deve considerar
        -- o volume da OH, e nao das OW
        CASE
            WHEN
                TRIM(P.FREIGHT_TYPE) IN ('CIF', '')
                OR UDC_EXP_CONTRACTS.SOURCE_CODE IS NOT NULL
                THEN 0
            ELSE OH.TOTAL_REM
        END AS QUANTITYREM,
        CASE
            WHEN CONT.QTDE IS NOT NULL
                THEN CONCAT(
                    P.CIA, '-', TRIM(P.AGREEMENT_NUMBER), '-',
                    CASE
                        WHEN
                            P.LINE_NUMBER = '1000'
                            AND P.DESTINATION != DEST_FIX.DESTINATION
                            THEN DEST_FIX.DESTINATION
                        ELSE
                            COALESCE(
                                UDC_AMID.TARGET_CODE,
                                UDC_MODAL_2.TARGET_CODE,
                                UDC_MODAL_1.TARGET_CODE,
                                COALESCE(
                                    NULLIF(TRIM(P.DESTINATION), ''),
                                    'N/A'
                                )
                            )
                    END
                )
            ELSE CONCAT(P.CIA, '-', TRIM(P.AGREEMENT_NUMBER))
        END AS SOURCINGCONTRACTID,
        RANK() OVER (
            PARTITION BY P.AGREEMENT_NUMBER
            ORDER BY P.LINE_NUMBER ASC
        ) AS RNK
    FROM {{ source('jde', 'F_PURCHASE_POSITION') }} AS P
    LEFT JOIN TOTALS AS T
        ON
            P.AGREEMENT_NUMBER = T.AGREEMENT_NUMBER
            AND P.CIA = T.CIA --A
            AND COALESCE(NULLIF(TRIM(P.DESTINATION), ''), 'N/A') = T.DESTINATION
    LEFT JOIN POSICAO_2 AS Q
        ON
            P.AGREEMENT_NUMBER = Q.AGREEMENT_NUMBER
            AND P.CIA = Q.CIA
            AND COALESCE(NULLIF(TRIM(P.DESTINATION), ''), 'N/A') = Q.DESTINATION
    LEFT JOIN POSICAO_OHGLOBAL AS OH
        ON
            P.AGREEMENT_NUMBER = OH.AGREEMENT_NUMBER
            AND P.CIA = OH.CIA
    LEFT JOIN UDC AS UDC_AMID
        ON
            TRIM(UDC_AMID.SOURCE_CODE) = SUBSTR(
                TRIM(P.DESTINATION_BRANCH_PLANT_CODE), 1, 8
            )
            AND UDC_AMID.CATEGORY = 'SOURCING CONTRACT'
            AND UDC_AMID.STAGE = 'DESTINATION AMIDOS'
    LEFT JOIN UDC AS UDC_MODAL_1
        ON
            TRIM(UDC_MODAL_1.SOURCE_CODE) = TRIM(P.DESTINATION)
            AND UDC_MODAL_1.CATEGORY = 'LOCATION_CODE'
            AND UDC_MODAL_1.STAGE = 'DESTINATION'
    LEFT JOIN UDC AS UDC_MODAL_2
        ON
            TRIM(UDC_MODAL_2.SOURCE_CODE) = CONCAT(
                TRIM(P.DESTINATION), TRIM(P.MODAL)
            )
            AND UDC_MODAL_2.CATEGORY = 'LOCATION_CODE'
            AND UDC_MODAL_2.STAGE = 'DESTINATION'
    LEFT JOIN DESTINATION_FIX AS DEST_FIX
        ON
            TRIM(DEST_FIX.CSDMCT) = TRIM(P.AGREEMENT_NUMBER)
            AND TRIM(DEST_FIX.CSKCO) = TRIM(P.CIA)
    LEFT JOIN CONT AS CONT
        ON
            TRIM(CONT.CONTRACTNUMBER_INTERNAL) = TRIM(P.AGREEMENT_NUMBER)
            AND TRIM(CONT.CIA) = TRIM(P.CIA)
    LEFT JOIN UDC AS UDC_EXP_CONTRACTS
        ON
            TRIM(UDC_EXP_CONTRACTS.SOURCE_CODE) = TRIM(P.AGREEMENT_NUMBER)
            AND UDC_EXP_CONTRACTS.CATEGORY = 'SOURCING CONTRACT'
            AND UDC_EXP_CONTRACTS.STAGE = 'DESATIVA OH GLOBAL'
),

MAIN_TEMP_B AS (
    SELECT
        MA.*,
        SUM(RQ.REC) AS RECEIVEDQUANTITY,
        SUM(RQ.REC_FLAT) AS RECEIVEDQUANTITYFLAT, --A
        SUM(RQ.REC_PAF) AS RECEIVEDQUANTITYPAF,
        SUM(R.RECEBER_COMP) AS TORECEIVECOMP,
        SUM(R.RECEBER_PAF) AS TORECEIVEPAF,
        SUM(R.RECEBER_FLAT) AS TORECEIVEFLAT,
        SUM(R.RECEBER) AS TORECEIVETOTAL
    FROM MAIN_TEMP_A AS MA
    LEFT JOIN RECEIVED_QUANTITY AS RQ
        ON
            MA.AGREEMENT_NUMBER = RQ.AGREEMENT_NUMBER
            AND MA.CIA = RQ.CIA
            AND MA.DESTINATION = RQ.DESTINATION
    LEFT JOIN TO_RECEIVE_QUANTITY_2 AS R
        ON
            MA.AGREEMENT_NUMBER = R.AGREEMENT_NUMBER
            AND MA.CIA = R.CIA
            AND MA.DESTINATION = R.DESTINATION
    GROUP BY
        MA.CIA, --A
        MA.SOURCINGCONTRACTID,
        MA.ADDRESS_LOCAL_RETIRADA_FAZENDA,
        MA.DESTINATION_BP,
        MA.ORIGINATION_BP,
        MA.DESTINATION,
        MA.MODAL,
        MA.LINE,
        MA.ITEMID,
        MA.FREIGHTCOST,
        MA.ACTUALCOST,
        MA.FREIGHTCADENCE,
        MA.CURRENCY,
        MA.QUANTITY,
        MA.QUANTITYFLAT,
        MA.QUANTITYPAF,
        MA.UOM,
        MA.AGREEMENT_NUMBER,
        MA.FREIGHT_TYPE,
        MA.REFERENCE_MONTH,
        MA.PRECO_SACA,
        MA.RNK,
        MA.QUANTITYREM,
        MA.TIPO_PED_OW,
        MA.RECEIVEDREM,
        MA.OPENREM
),

MAIN AS (
    SELECT
        MB.*,
        SUM(CQ.CAN) AS CANCELLEDQUANTITY,
        SUM(CQ.CAN_FLAT) AS CANCELLEDQUANTITYFLAT,
        SUM(CQ.CAN_PAF) AS CANCELLEDQUANTITYPAF
    FROM MAIN_TEMP_B AS MB
    LEFT JOIN CANCELLED_QUANTITY AS CQ
        ON
            MB.AGREEMENT_NUMBER = CQ.AGREEMENT_NUMBER
            AND MB.CIA = CQ.CIA
            AND MB.DESTINATION = CQ.DESTINATION
    GROUP BY
        MB.CIA,--A
        MB.SOURCINGCONTRACTID,
        MB.ADDRESS_LOCAL_RETIRADA_FAZENDA,
        MB.DESTINATION_BP,
        MB.ORIGINATION_BP,
        MB.DESTINATION,
        MB.MODAL,
        MB.LINE,
        MB.ITEMID,
        MB.FREIGHTCOST,
        MB.ACTUALCOST,
        MB.FREIGHTCADENCE,
        MB.CURRENCY,
        MB.QUANTITY,
        MB.QUANTITYFLAT,--A
        MB.QUANTITYPAF, --A
        MB.AGREEMENT_NUMBER,
        MB.UOM,
        MB.RNK,
        MB.RECEIVEDQUANTITY,
        MB.RECEIVEDQUANTITYFLAT,
        MB.RECEIVEDQUANTITYPAF,
        MB.TORECEIVECOMP,
        MB.TORECEIVEPAF,
        MB.TORECEIVEFLAT,
        MB.TORECEIVETOTAL,
        MB.FREIGHT_TYPE,
        MB.PRECO_SACA,
        MB.REFERENCE_MONTH,
        MB.QUANTITYREM,
        MB.RECEIVEDREM,
        MB.OPENREM,
        MB.TIPO_PED_OW
),

SEQUENCING AS (
    SELECT
        SOURCINGCONTRACTID,
        MAX(RNK) AS SEQ
    FROM MAIN
    GROUP BY
        SOURCINGCONTRACTID
),

PLANNEDCOST_F554349F AS ( --noqa
    SELECT --MAX(A9_INT.MFUKID)
        --MFFRTH,
        TRIM(A.MFAA10) AS MFAA10,
        TRIM(A.MFMOT) AS MFMOT,
        TRIM(A.MFLITM) AS MFLITM,
        TRIM(A.MFAA11) AS MFAA11,
        TRIM(A.MFAFRT) AS MFAFRT,
        --MFSHAN,
        RANK() OVER (
            PARTITION BY TRIM(A.MFAA10), TRIM(A.MFMOT), TRIM(A.MFLITM), TRIM(A.MFAA11) --noqa
            ORDER BY A.MFUKID DESC
        ) AS RNK
    FROM {{ source('jde', 'F554349F') }} AS A
    WHERE
        1 = 1
        AND (
            COALESCE(A.OP_TYPE, '-') NOT IN ('0', '3')
            OR (A.OP_TYPE = '0' AND A.OP_TIME = '1969-12-31 16:00:00.000')
        )
    QUALIFY RNK = 1
),

-- WORKAROUND FOR CURRENCY ERROR ON F_PURCHASE_POSITION,
-- IT SHALL BE REMOVED ONCE IS FIXED
FIX_CURRENCY_TEMP AS (
    SELECT
        CSDMCT,
        MAX(CSZ55SLPN) AS CSZ55SLPN
    FROM  {{ source('jde', 'F5543050') }}
    WHERE
        1 = 1
        AND CSZ55SLPT IN ('12','10')
        AND CSZ55SLPS IN ('E', 'P')
        AND CSKCO IN ('52171', '52191', '52180')
        AND CSUPMJ >= 125000
    GROUP BY CSDMCT
),

FIX_CURRENCY AS (
    SELECT
        F50.CSCRCD,
        F50.CSDMCT
    FROM {{ source('jde', 'F5543050') }} AS F50
    INNER JOIN FIX_CURRENCY_TEMP AS TEMP
        ON
            F50.CSDMCT = TEMP.CSDMCT
            AND F50.CSZ55SLPN = TEMP.CSZ55SLPN
),

CONTRACT_DETAILS_PC_TEMP AS (
    SELECT DISTINCT
        A1.SOURCINGCONTRACTID,
        A1.ADDRESS_LOCAL_RETIRADA_FAZENDA,
        A1.FREIGHTCOST,
        A1.ACTUALCOST,
        A1.UOM AS UNIT,
        A1.OPENREM AS OPEN_OHGLOBAL,
        TRIM(COALESCE(UDC_PRODUTOS.TARGET_CODE, A1.ITEMID)) AS ITEMID, --noqa
        TRIM(A1.PRECO_SACA) AS PRICE,
        -- FX_CUR.CSCRCD IS A WORKAROUND FOR CURRENCY ERROR IN
        -- F_PURCHASE_POSITION, IT SHALL BE REMOVED ONCE IS FIXED
        COALESCE(FX_CUR.CSCRCD, A1.CURRENCY, 'BRE') AS CURRENCY,
        COALESCE(CONV.UOMFROM, 'TN') AS UOM,--noqa
        COALESCE(A1.FREIGHTCADENCE, 1) AS FREIGHTCADENCE,
        IFF(A1.QUANTITY < 0, 0, A1.QUANTITY)
        / CONV.SUPPLYPLANNINGFINALCONVERSIONFACTOR AS QUANTITY,--noqa
        (CASE
            WHEN A1.QUANTITYREM > 0
                THEN A1.RECEIVEDREM
            ELSE
                A1.RECEIVEDQUANTITY
        END) / CONV.SUPPLYPLANNINGFINALCONVERSIONFACTOR AS RECEIVEDQUANTITY,--noqa
        (CASE
            WHEN A1.QUANTITYREM > 0
                THEN 0
            ELSE
                COALESCE(A1.RECEIVEDQUANTITYPAF, 0)
        END) / CONV.SUPPLYPLANNINGFINALCONVERSIONFACTOR AS RECEIVEDPAF,--noqa
        (
            A1.CANCELLEDQUANTITY / CONV.SUPPLYPLANNINGFINALCONVERSIONFACTOR --noqa
        ) AS CANCELLEDQUANTITY,
        COALESCE(
            CASE
                WHEN A7.DNDMSC = 'A' --noqa
                    THEN A9.MFAFRT / 100 --noqa
                ELSE A10.MFAFRT / 100 --noqa
            END,
            0
        ) AS PLANNEDCOST,
        (CASE
            WHEN A1.QUANTITYREM > 0
                THEN A1.OPENREM
            ELSE
                CASE --noqa
                    WHEN (A1.TORECEIVETOTAL) < 0 THEN 0
                    ELSE (A1.TORECEIVETOTAL)
                END
        END) / CONV.SUPPLYPLANNINGFINALCONVERSIONFACTOR AS TORECEIVETOTAL,--noqa
        (CASE
            WHEN A1.QUANTITYREM > 0
                THEN A1.OPENREM
            ELSE
                CASE --noqa
                    WHEN (A1.TORECEIVEFLAT + A1.TORECEIVECOMP) < 0 THEN 0
                    ELSE (A1.TORECEIVEFLAT + A1.TORECEIVECOMP)
                END
        END) / CONV.SUPPLYPLANNINGFINALCONVERSIONFACTOR AS TORECEIVEFLAT, --noqa
        (CASE
            WHEN A1.QUANTITYREM > 0
                THEN 0
            ELSE
                CASE --noqa
                    WHEN (A1.TORECEIVEPAF) < 0 THEN 0
                    ELSE (A1.TORECEIVEPAF)
                END
        END) / CONV.SUPPLYPLANNINGFINALCONVERSIONFACTOR AS TORECEIVEPAF --noqa
    FROM MAIN AS A1
    INNER JOIN SEQUENCING AS A2
        ON A1.SOURCINGCONTRACTID = A2.SOURCINGCONTRACTID
    INNER JOIN {{ source('jde', 'F38010') }} AS A7
        ON
            TRIM(A7.DNDMCT) = TRIM(A1.AGREEMENT_NUMBER)
            AND {{ filter_remove_jde_delete_data('A7') }} -- noqa
    LEFT JOIN PLANNEDCOST_F554349F AS A9
        ON
            --TRIM(A9.MFFRTH) = TRIM(A1.FREIGHT_TYPE) AND
            TRIM(A9.MFAA10) = TRIM(A1.DESTINATION)
            AND TRIM(A9.MFMOT) = TRIM(A1.MODAL)
            --AND TRIM(A9.MFSHAN) = TRIM(A1.ADDRESS_LOCAL_RETIRADA_FAZENDA)
            AND TRIM(A9.MFLITM) = TRIM(A1.ITEMID)
            AND TRIM(A9.MFAA11) = TO_CHAR(CURRENT_DATE(), 'MM/YYYY')
    LEFT JOIN PLANNEDCOST_F554349F AS A10
        ON
            --TRIM(A10.MFFRTH) = TRIM(A1.FREIGHT_TYPE) AND
            TRIM(A10.MFAA10) = TRIM(A1.DESTINATION)
            AND TRIM(A10.MFMOT) = TRIM(A1.MODAL)
            --AND TRIM(A10.MFSHAN) = TRIM(A1.ADDRESS_LOCAL_RETIRADA_FAZENDA)
            AND TRIM(A10.MFLITM) = TRIM(A1.ITEMID)
            AND TRIM(A10.MFAA11) = TO_CHAR(
                {{ julian_date_to_gregorian('A7', 'DNUPMJ') }}, --noqa
                'MM/YYYY'
            )
    LEFT JOIN {{ ref('uom_conversion_master') }} AS CONV
        ON
            TRIM(A1.ITEMID) = TRIM(CONV.ITEM)
            AND TRIM(COALESCE(A1.UOM, 'KG')) = TRIM(CONV.UOMTO)
            AND TRIM(CONV.UOMFROM) = 'TN'
    LEFT JOIN UDC AS UDC_PRODUTOS
        ON
            UDC_PRODUTOS.CATEGORY = 'SOURCING CONTRACT'
            AND UDC_PRODUTOS.STAGE = 'DE-PARA PRODUTO'
            AND TRIM(A1.ITEMID) = TRIM(UDC_PRODUTOS.SOURCE_CODE)
    INNER JOIN {{ ref('item_master') }} AS ITM
        ON
            TRIM(A1.ITEMID) = TRIM(ITM.ITEM)
            AND TRIM(ITM.L3) = 'INBOUND'
    LEFT JOIN FIX_CURRENCY AS FX_CUR
        ON TRIM(A1.AGREEMENT_NUMBER) = TRIM(FX_CUR.CSDMCT)
    WHERE
        1 = 1
        AND A1.RNK = A2.SEQ
        AND {{ filter_remove_jde_delete_data('A7') }} -- noqa
),

CONTRACT_DETAILS_ORIG_TEMP AS (
    SELECT
        CONCAT(F43.PDKCOO, '-', F43.PDDMCT) AS SOURCINGCONTRACTID,
        TRIM(F43.PDLITM) AS ITEMID,
        0 AS FREIGHTCOST,
        0 AS ACTUALCOST,
        0 AS FREIGHTCADENCE,
        0 AS PLANNEDCOST,
        'N/A' AS CURRENCY,
        (F43.PDUORG / 1000)
            / CONV.SUPPLYPLANNINGFINALCONVERSIONFACTOR AS QUANTITY,
        0 AS RECEIVEDQUANTITY,
        0 AS RECEIVEDPAF,
        0 AS TORECEIVETOTAL,
        0 AS TORECEIVEFLAT,
        0 AS TORECEIVEPAF,
