WITH
ONHANDS_F_ESTOQUE_PORTO AS (
    SELECT *
    FROM {{ ref('tab_onhands_estoque_portos_stg') }}
),

ONHANDS_OUTBOUND AS (
    SELECT *
    FROM {{ ref('tab_onhands_outbound_stg') }} AS OH_OUTBOUND
    WHERE
        1 = 1
        AND ITEM != 'N/A'
        AND "LOCATION" != 'N/A'
        AND NOT EXISTS (
            SELECT 1 FROM ONHANDS_F_ESTOQUE_PORTO AS ESTOQUE_PORTO
            WHERE
                1 = 1
                -- AND OH_OUTBOUND.ITEM = ESTOQUE_PORTO.ITEM
                AND OH_OUTBOUND.LOCATION = ESTOQUE_PORTO.LOCATION
        )
),

ONHANDS_INBOUND AS (
    SELECT OH_INBOUND.*
    FROM {{ ref('tab_onhands_inbound_stg') }} AS OH_INBOUND
    INNER JOIN {{ ref('tab_location_internal_stg') }} AS L
        ON L.LOCATIONID = OH_INBOUND.BP
    WHERE
        1 = 1
        AND OH_INBOUND.ITEM != 'N/A'
        AND OH_INBOUND."LOCATION" != 'N/A'
        AND L.LOCATION_TYPE != 'TROCA DE NOTA'
        AND NOT EXISTS (
            SELECT 1 FROM ONHANDS_F_ESTOQUE_PORTO AS ESTOQUE_PORTO
            WHERE
                1 = 1
                -- AND OH_INBOUND.ITEM = ESTOQUE_PORTO.ITEM
                AND OH_INBOUND.LOCATION = ESTOQUE_PORTO.LOCATION
        )
),

ONHANDS_CUTOFF AS (
    SELECT *
    FROM {{ ref('vw_onhands_cutoff_stg') }}
    WHERE
        TO_DATE(DAY, 'DD-MM-YYYY HH:MI:SS') = CURRENT_DATE()
),

ONHANDS_STG AS (
    SELECT
        LOCATION AS "LOCATION",
        DAY AS "DAY",
        BLOCKEDQUANTITY::DECIMAL(20, 3) AS BLOCKEDQUANTITY,
        ONHANDQUANTITY::DECIMAL(20, 3) AS ONHANDQUANTITY,
        QUARANTINEQUANTITY::DECIMAL(20, 3) AS QUARANTINEQUANTITY,
        0 AS CUTOFFQUANTITY,
        TRIM(UOM) AS UOM,
        COALESCE(COMPANY, 'N/A') AS COMPANY,
        TRIM(ITEM) AS ITEM
    FROM ONHANDS_F_ESTOQUE_PORTO

    UNION ALL

    SELECT
        LOCATION AS "LOCATION",
        DAY AS "DAY",
        BLOCKEDQUANTITY::DECIMAL(20, 3) AS BLOCKEDQUANTITY,
        ONHANDQUANTITY::DECIMAL(20, 3) AS ONHANDQUANTITY,
        QUARANTINEQUANTITY::DECIMAL(20, 3) AS QUARANTINEQUANTITY,
        0 AS CUTOFFQUANTITY,
        TRIM(UOM) AS UOM,
        COALESCE(COMPANY, 'N/A') AS COMPANY,
        TRIM(ITEM) AS ITEM
    FROM ONHANDS_OUTBOUND

    UNION ALL

    SELECT
        LOCATION AS "LOCATION",
        DAY AS "DAY",
        SUM(BLOCKEDQUANTITY)::DECIMAL(20, 3) AS BLOCKEDQUANTITY,
        SUM(ONHANDQUANTITY)::DECIMAL(20, 3) AS ONHANDQUANTITY,
        SUM(QUARANTINEQUANTITY)::DECIMAL(20, 3) AS QUARANTINEQUANTITY,
        0 AS CUTOFFQUANTITY,
        TRIM(UOM) AS UOM,
        CASE
            WHEN TRIM(ONHANDS_INBOUND.COMPANY) = '52171' THEN 'CARGILL'
            WHEN TRIM(ONHANDS_INBOUND.COMPANY) = '52191' THEN 'AMIDOS'
            WHEN TRIM(ONHANDS_INBOUND.COMPANY) = '52180' THEN 'CNH'
            ELSE COALESCE(COMPANY, 'N/A')
        END AS COMPANY,
        TRIM(ITEM) AS ITEM
    FROM ONHANDS_INBOUND
    GROUP BY
        1, 2, 6, 7, 8, 9

    UNION ALL

    SELECT
        LOCATION AS "LOCATION",
        DAY AS "DAY",
        BLOCKEDQUANTITY::DECIMAL(20, 3) AS BLOCKEDQUANTITY,
        ONHANDQUANTITY::DECIMAL(20, 3) AS ONHANDQUANTITY,
        QUARANTINEQUANTITY::DECIMAL(20, 3) AS QUARANTINEQUANTITY,
        CUTOFFQUANTITY::DECIMAL(20, 3) AS CUTOFFQUANTITY,
        TRIM(UOM) AS UOM,
        COALESCE(COMPANY, 'N/A') AS COMPANY,
        TRIM(ITEM) AS ITEM
    FROM ONHANDS_CUTOFF
),

ONHANDS AS (
    SELECT
        LOCATION,
        DAY,
        UOM,
        COMPANY,
        ITEM,
        SUM(BLOCKEDQUANTITY) AS BLOCKEDQUANTITY,
        SUM(ONHANDQUANTITY) AS ONHANDQUANTITY,
        SUM(QUARANTINEQUANTITY) AS QUARANTINEQUANTITY,
        SUM(CUTOFFQUANTITY) AS CUTOFFQUANTITY
    FROM ONHANDS_STG
    GROUP BY
        1, 2, 3, 4, 5
)

SELECT
    LOCATION,
    DAY,
    UOM,
    COMPANY,
    ITEM,
    BLOCKEDQUANTITY,
    ONHANDQUANTITY,
    QUARANTINEQUANTITY,
    CUTOFFQUANTITY,
    HASH(*) AS HASH_ID
FROM ONHANDS
WHERE
    1 = 1
    AND NOT (
        BLOCKEDQUANTITY = 0
        AND ONHANDQUANTITY = 0
        AND QUARANTINEQUANTITY = 0
        AND CUTOFFQUANTITY = 0
    )
    AND {{ date_max_filter('DAY', 'DD-MM-YYYY HH:MI:SS', 'na') }} --noqa
