WITH FINAL AS (
    SELECT
        0 AS IDX,
        'LOCATIONID' AS LOCATIONID,
        'LOCATION_UNIT_STRUCTURE' AS LOCATION_UNIT_STRUCTURE,
        'LOCATION_GROUP' AS LOCATION_GROUP,
        'LOCATION_COUNTRY' AS LOCATION_COUNTRY,
        'LOCATION_REGION' AS LOCATION_REGION,
        'LOCATION_SUB_REGION' AS LOCATION_SUB_REGION,
        'LOCATION_NAME' AS LOCATION_NAME,
        'LOCATION_CODE' AS LOCATION_CODE,
        'ZIP' AS ZIP,
        'ADDRESS' AS ADDRESS,
        'CITY' AS CITY,
        'LONGITUDE' AS LONGITUDE,
        'LATITUDE' AS LATITUDE,
        'STATE' AS STATE,
        'LOCATION_OWNERSHIP' AS LOCATION_OWNERSHIP,
        'OPERATOR' AS OPERATOR,
        'LOCATION_IBP_ASSET' AS LOCATION_IBP_ASSET,
        'ISACTIVE' AS ISACTIVE,
        'RESTRICTION' AS RESTRICTION,
        'ROUTINGCOMMENTS' AS ROUTINGCOMMENTS,
        'LOCATION_TYPE' AS LOCATION_TYPE,
        NULL AS HASH_ID,
        NULL AS CDP_TRANSACTION,
        (SELECT CDP_TIMESTAMP FROM {{ ref('tab_cdp_timestamp_models') }} WHERE MODEL_NAME = UPPER('location')) AS CDP_TIMESTAMP_FULL, -- noqa
        (SELECT CDP_TIMESTAMP FROM {{ ref('tab_cdp_timestamp_models') }} WHERE MODEL_NAME = UPPER('location')) AS CDP_TIMESTAMP_INC, -- noqa
        'CDP_TIMESTAMP_O9' AS CDP_TIMESTAMP_O9

    UNION ALL

    SELECT
        1 AS IDX,
        LOCATIONID::STRING,
        LOCATION_UNIT_STRUCTURE::STRING,
        LOCATION_GROUP::STRING,
        LOCATION_COUNTRY::STRING,
        LOCATION_REGION::STRING,
        LOCATION_SUB_REGION::STRING,
        LOCATION_NAME::STRING,
        LOCATION_CODE::STRING,
        ZIP::STRING,
        ADDRESS::STRING,
        CITY::STRING,
        LONGITUDE::STRING,
        LATITUDE::STRING,
        STATE::STRING,
        LOCATION_OWNERSHIP::STRING,
        OPERATOR::STRING,
        LOCATION_IBP_ASSET::STRING,
        ISACTIVE::STRING,
        RESTRICTION::STRING,
        ROUTINGCOMMENTS::STRING,
        LOCATION_TYPE::STRING,
        HASH_ID,
        CDP_TRANSACTION,
        CDP_TIMESTAMP_FULL,
        CDP_TIMESTAMP_INC,
        CDP_TIMESTAMP_O9::STRING
    FROM {{ ref('location') }}
)

SELECT
    LOCATIONID,
    LOCATION_UNIT_STRUCTURE,
    LOCATION_GROUP,
    LOCATION_COUNTRY,
    LOCATION_REGION,
    LOCATION_SUB_REGION,
    LOCATION_NAME,
    LOCATION_CODE,
    ZIP,
    ADDRESS,
    CITY,
    LONGITUDE,
    LATITUDE,
    STATE,
    LOCATION_OWNERSHIP,
    OPERATOR,
    LOCATION_IBP_ASSET,
    ISACTIVE,
    RESTRICTION,
    ROUTINGCOMMENTS,
    LOCATION_TYPE,
    HASH_ID,
    CDP_TRANSACTION,
    CDP_TIMESTAMP_FULL,
    CDP_TIMESTAMP_INC,
    CDP_TIMESTAMP_O9
FROM FINAL
ORDER BY IDX ASC
