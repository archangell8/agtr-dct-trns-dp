WITH
CUSTOMER_LOCATION_1 AS (
    SELECT DISTINCT
        TRIM(LOCATION_NAME) AS CUSTOMERID,
        TRIM('N/A') AS TAXID,
        TRIM(LOCATION_NAME) AS "NAME",
        TRIM('ATIVO') AS "STATUS",
        TRIM('N/A') AS "ADDRESS",
        TRIM('N/A') AS COMPLEMENT,
        TRIM('N/A') AS NEIGHBORHOOD,
        TRIM('N/A') AS ZIPCODE,
        TRIM(CITY) AS CITY,
        TRIM(STATE) AS STATE,
        TRIM('BR') AS COUNTRY,
        TRIM('External Market') AS MARKET,
        TRIM(LOCATION_IBP_ASSET) AS TERRITORY,
        --TRIM(LOCATION_IBP_ASSET) AS SEGMENTATION,
        TRIM('PORTO MARÍTIMO') AS SEGMENTATION,
        TRIM(LOCATION_IBP_ASSET) AS CUSTOMERGROUP,
        TRIM(LOCATION_IBP_ASSET) AS CUSTOMERGROUPDESCRIPTION,
        COALESCE(FALSE, FALSE) AS CREDITBLOCKED
    FROM {{ ref('location_master') }}
    WHERE
        1 = 1
        AND LOCATION_UNIT_STRUCTURE IN ('PORTO MARÍTIMO', 'PORTO FLUVIAL')
        AND LOCATION_IBP_ASSET != 'N/A'
        AND LOCATION_IBP_ASSET != 'BIANCHINI CRUZ ALTA'
        AND LOCATION_NAME != 'PORTO PDM VLI'
        AND LOCATION_NAME != LOCATION_IBP_ASSET
),

CUSTOMER_LOCATION_2 AS (
    SELECT DISTINCT
        TRIM(LOCATION_IBP_ASSET) AS CUSTOMERID,
        TRIM('N/A') AS TAXID,
        TRIM(LOCATION_IBP_ASSET) AS "NAME",
        TRIM('ATIVO') AS "STATUS",
        TRIM('N/A') AS "ADDRESS",
        TRIM('N/A') AS COMPLEMENT,
        TRIM('N/A') AS NEIGHBORHOOD,
        TRIM('N/A') AS ZIPCODE,
        CASE
            WHEN LOCATION_IBP_ASSET = 'PORTO PARANAGUA' THEN 'PARANAGUA'
            WHEN LOCATION_IBP_ASSET = 'PORTO SANTOS' THEN 'SANTOS'
            ELSE CITY
        END AS CITY,
        CASE
            WHEN LOCATION_IBP_ASSET = 'PORTO PARANAGUA' THEN 'PR'
            WHEN LOCATION_IBP_ASSET = 'PORTO SANTOS' THEN 'SP'
            ELSE STATE
        END AS "STATE",
        TRIM(LOCATION_COUNTRY) AS COUNTRY,
        TRIM('External Market') AS MARKET,
        TRIM(LOCATION_IBP_ASSET) AS TERRITORY,
        --TRIM(LOCATION_IBP_ASSET) AS SEGMENTATION,
        TRIM('PORTO MARÍTIMO') AS SEGMENTATION,
        TRIM(LOCATION_IBP_ASSET) AS CUSTOMERGROUP,
        TRIM(LOCATION_IBP_ASSET) AS CUSTOMERGROUPDESCRIPTION,
        COALESCE(FALSE, FALSE) AS CREDITBLOCKED
    FROM {{ ref('location_master') }}
    WHERE
        1 = 1
        AND LOCATION_UNIT_STRUCTURE IN ('PORTO MARÍTIMO', 'PORTO FLUVIAL')
        AND LOCATION_IBP_ASSET != 'N/A'
),

CUSTOMER_LOCATION_3 AS (
    SELECT DISTINCT
        TRIM(LOCATION_IBP_ASSET) AS CUSTOMERID,
        TRIM('N/A') AS TAXID,
        TRIM(LOCATION_IBP_ASSET) AS "NAME",
        TRIM('ATIVO') AS "STATUS",
        TRIM('N/A') AS "ADDRESS",
        TRIM('N/A') AS COMPLEMENT,
        TRIM('N/A') AS NEIGHBORHOOD,
        TRIM('N/A') AS ZIPCODE,
        TRIM(CITY) AS CITY,
        TRIM(STATE) AS "STATE",
        TRIM(LOCATION_COUNTRY) AS COUNTRY,
        TRIM('Domestic Market') AS MARKET,
        TRIM(LOCATION_IBP_ASSET) AS TERRITORY,
        --TRIM(LOCATION_IBP_ASSET) AS SEGMENTATION,
        TRIM('FÁBRICA') AS SEGMENTATION,
        TRIM(LOCATION_IBP_ASSET) AS CUSTOMERGROUP,
        TRIM(LOCATION_IBP_ASSET) AS CUSTOMERGROUPDESCRIPTION,
        COALESCE(FALSE, FALSE) AS CREDITBLOCKED
    FROM {{ ref('location_master') }}
    WHERE
        1 = 1
        AND LOCATION_UNIT_STRUCTURE = 'FÁBRICA'
        AND LOCATION_IBP_ASSET != 'N/A'
),

CUSTOMER_LOCATION_4 AS (
    SELECT DISTINCT
        TRIM(ST.STATE) AS CUSTOMERID,
        TRIM('N/A') AS TAXID,
        TRIM(ST.STATE) AS "NAME",
        TRIM('ATIVO') AS "STATUS",
        TRIM('N/A') AS "ADDRESS",
        TRIM('N/A') AS COMPLEMENT,
        TRIM('N/A') AS NEIGHBORHOOD,
        TRIM('N/A') AS ZIPCODE,
        TRIM('N/A') AS CITY,
        TRIM(LOC.STATE) AS "STATE",
        TRIM('BR') AS COUNTRY,
        TRIM('Domestic Market') AS MARKET,
        TRIM(LOC.STATE) AS TERRITORY,
        TRIM(LOC.STATE) AS SEGMENTATION,
        TRIM(ST.STATE) AS CUSTOMERGROUP,
        TRIM(ST.STATE) AS CUSTOMERGROUPDESCRIPTION,
        COALESCE(FALSE, FALSE) AS CREDITBLOCKED
    FROM {{ ref('tab_location_internal_stg') }} AS LOC
    INNER JOIN {{ source('pscfl','F_MIN_LOCATION_UF_STATE') }} AS ST
        ON LOC.STATE = ST.UF
),

CUSTOMER_LOCATION AS (
    SELECT * FROM CUSTOMER_LOCATION_1
    UNION ALL
    SELECT * FROM CUSTOMER_LOCATION_2
    UNION ALL
    SELECT * FROM CUSTOMER_LOCATION_3
    UNION ALL
    SELECT * FROM CUSTOMER_LOCATION_4
)

SELECT * FROM CUSTOMER_LOCATION
