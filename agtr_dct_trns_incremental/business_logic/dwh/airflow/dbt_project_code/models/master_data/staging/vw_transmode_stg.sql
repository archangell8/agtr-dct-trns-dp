WITH
TRANSMODE_TEMP AS (
    SELECT
        TRANSMODE,
        TRANSMODETYPE,
        MAX(TRANSMODEDESCRIPTION) AS TRANSMODEDESCRIPTION
    FROM {{ source('pscfl', 'F_MIN_TRANSMODE') }}
    GROUP BY
        TRANSMODE,
        TRANSMODETYPE
),

TRANSMODE AS (
    SELECT DISTINCT
        COALESCE(NULLIF(TRANSMODE, ''), 'N/A') AS TRANSMODE,
        COALESCE(
            NULLIF(TRANSMODEDESCRIPTION, ''),
            'N/A'
        ) AS TRANSMODEDESCRIPTION,
        COALESCE(NULLIF(TRANSMODETYPE, ''), 'N/A') AS TRANSMODETYPE
    FROM TRANSMODE_TEMP
)

SELECT
    *,
    HASH(*) AS HASH_ID
FROM TRANSMODE
