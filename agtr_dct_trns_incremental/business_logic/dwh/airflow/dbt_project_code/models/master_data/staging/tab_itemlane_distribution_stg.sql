    WHERE
        1 = 1
        AND FF.TRANSPORT_TYPE != 'ROD'
        AND FF.DESTINATION != 'N/A'
        AND COALESCE(FF.DISTANCIA, 0) != 0
        AND TO_DATE(FF.PERIOD, 'MM/YYYY') BETWEEN DATE_TRUNC(
            'MONTH',
            CURRENT_DATE()
