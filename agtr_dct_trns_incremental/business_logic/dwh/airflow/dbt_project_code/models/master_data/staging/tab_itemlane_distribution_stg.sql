        ON
            REPLACE(TRANSLATE(L.CITY, 'ÁÉÍÓÚÃÕÂÊÔÇ', 'AEIOUAOAEOC'), ' ', '') = FF.CIDADE_REFERENCIA --noqa
            AND BL.DESTINO = FF.DESTINATION
